function value = readDecisions(conn, runId)
%READDECISIONS Each decision with the policy that produced it.
%
% A decision without its policy is not a decision, so the policy version and the
% applied threshold travel with every row. The threshold is uncalibrated: this
% prototype ships no acceptance criterion, and no status here means validated.
rows = fetch(conn, "SELECT d.attribution_decision_id, " + ...
    "d.attribution_target_id, d.decision_status, " + ...
    "d.policy_profile_version_id, " + ...
    "IFNULL(pv.version_label,'') AS policy_version_label, " + ...
    "IFNULL(p.profile_key,'') AS policy_profile_key, " + ...
    "IFNULL(d.applied_threshold, 1e308) AS applied_threshold, " + ...
    "IFNULL(d.applied_threshold_semantics,'') AS applied_threshold_semantics, " + ...
    "IFNULL(d.exclusion_reason,'') AS exclusion_reason, " + ...
    "d.decided_at_utc " + ...
    "FROM attribution_decisions d " + ...
    "JOIN attribution_targets t " + ...
    "  ON t.attribution_target_id = d.attribution_target_id " + ...
    "LEFT JOIN config_profile_versions pv " + ...
    "  ON pv.profile_version_id = d.policy_profile_version_id " + ...
    "LEFT JOIN config_profiles p ON p.profile_id = pv.profile_id " + ...
    "WHERE t.attribution_run_id=" + string(runId) + ...
    " ORDER BY d.attribution_target_id, d.attribution_decision_id");

value = table(zeros(0, 1), zeros(0, 1), strings(0, 1), zeros(0, 1), ...
    strings(0, 1), strings(0, 1), zeros(0, 1), strings(0, 1), strings(0, 1), ...
    strings(0, 1), ...
    VariableNames=["attribution_decision_id", "attribution_target_id", ...
    "decision_status", "policy_profile_version_id", "policy_version_label", ...
    "policy_profile_key", "applied_threshold", "applied_threshold_semantics", ...
    "exclusion_reason", "decided_at_utc"]);
for index = 1:height(rows)
    value(end + 1, :) = {double(rows.attribution_decision_id(index)), ...
        double(rows.attribution_target_id(index)), ...
        presentText(rows.decision_status(index)), ...
        double(rows.policy_profile_version_id(index)), ...
        presentText(rows.policy_version_label(index)), ...
        presentText(rows.policy_profile_key(index)), ...
        sentinelNumber(rows.applied_threshold(index)), ...
        presentText(rows.applied_threshold_semantics(index)), ...
        presentText(rows.exclusion_reason(index)), ...
        presentText(rows.decided_at_utc(index))}; %#ok<AGROW>
end
end

function value = readSelections(conn, runId)
%READSELECTIONS Which candidates a decision selected. A set, never a winner.
rows = fetch(conn, "SELECT dc.attribution_decision_id, " + ...
    "dc.attribution_candidate_id, d.attribution_target_id, " + ...
    "d.decision_status, c.entity_id, " + ...
    "IFNULL(e.native_id,'') AS entity_native_id, " + ...
    "IFNULL(dc.selection_role,'') AS selection_role " + ...
    "FROM attribution_decision_candidates dc " + ...
    "JOIN attribution_decisions d " + ...
    "  ON d.attribution_decision_id = dc.attribution_decision_id " + ...
    "JOIN attribution_candidates c " + ...
    "  ON c.attribution_candidate_id = dc.attribution_candidate_id " + ...
    "JOIN attribution_targets t " + ...
    "  ON t.attribution_target_id = d.attribution_target_id " + ...
    "LEFT JOIN experimental_entities e ON e.entity_id = c.entity_id " + ...
    "WHERE t.attribution_run_id=" + string(runId) + ...
    " ORDER BY dc.attribution_decision_id, dc.attribution_candidate_id");

value = table(zeros(0, 1), zeros(0, 1), zeros(0, 1), strings(0, 1), ...
    zeros(0, 1), strings(0, 1), strings(0, 1), ...
    VariableNames=["attribution_decision_id", "attribution_candidate_id", ...
    "attribution_target_id", "decision_status", "entity_id", ...
    "entity_native_id", "selection_role"]);
for index = 1:height(rows)
    value(end + 1, :) = {double(rows.attribution_decision_id(index)), ...
        double(rows.attribution_candidate_id(index)), ...
        double(rows.attribution_target_id(index)), ...
        presentText(rows.decision_status(index)), ...
        double(rows.entity_id(index)), ...
        presentText(rows.entity_native_id(index)), ...
        presentText(rows.selection_role(index))}; %#ok<AGROW>
end
end

