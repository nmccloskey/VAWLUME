function value = absenceNote()
value = "Absence reads as absence. A missing number is NaN and missing text " + ...
    "is empty, never 0 and never a default. A candidate with no acoustic " + ...
    "evidence has no acoustic row rather than a zero-valued one, because a " + ...
    "zero would claim a measurement was made. A claim with NaN score means the " + ...
    "exporting system supplied no number. A claim with NaN entity_id means no " + ...
    "shipped resolution policy produced that row, and nothing further may be " + ...
    "inferred from it.";
end

function value = basisNote()
