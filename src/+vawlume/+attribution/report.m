function value = report(conn, runRef)
%REPORT Read back one caller-attribution run: what was stored, and what was not.
%
% VALUE = vawlume.attribution.report(CONN, RUNREF) returns what is actually
% persisted for one attribution run — its provenance, targets, candidate callers,
% long-form evidence, imported claims, window correspondences and decisions —
% together with QC that reports facts and judges nothing.
%
% This is read-only. It writes no row, recomputes no score, and re-derives no
% decision. RUNREF accepts attribution_run_id, or project_key plus run_key.
%
% WHAT THIS DOES NOT DO, and the reasons are the phase's:
%
% **It does not rank or choose a caller.** Several candidates per target is the
% ordinary case, not a degenerate one. Every candidate is returned; nothing
% privileges the top-ranked one, because a read surface that showed one and hid
% the rest would reintroduce the single caller_id this representation exists to
% avoid.
%
% **It combines no evidence dimension with any other.** Temporal-alignment,
% pose/localization, visual-identity and acoustic evidence are returned as rows
% carrying their own dimension, units and semantics. No field here is a function
% of more than one of them, and none is named as though it were. Combination is
% Phase 6's business and requires an explicit, versioned method.
%
% **It judges nothing.** No quality score for a run, no threshold that calls a
% run acceptable, no aggregate that reads as a verdict. A count of scoreless
% claims is a fact; "this run has poor score coverage" is a verdict, and only the
% first appears here.
%
% **It does not promote an imported claim into a candidate.** A claim belongs to
% (window, entity) and a candidate to (target, entity). Deciding which
% correspondence is good enough to carry a claim onto a target is a policy
% question, so this function reads across that boundary by joining and never
% closes it by writing. Where one window corresponds to two targets, its claim
% appears against both and neither is marked as chosen.
%
% THE GRAIN OF EACH TABLE, because confusing them is the easiest way to
% miscount:
%
%   targets              one row per attribution target
%   candidates           one row per (target, candidate entity)
%   evidence             one row per stored evidence record
%   imported_claims      one row per (imported window, claimed caller)
%   correspondences      one row per stored correspondence
%   claim_correspondences one row per (claim, correspondence) — the joined story,
%                        so a correspondence whose window carries two claims
%                        appears TWICE here and ONCE in correspondences
%   decisions            one row per (target, policy version)
%   decision_selections  one row per candidate a decision selected
%
% QC counts correspondences from `correspondences`, never from the joined table.
%
% TWO BASES THAT ARE NOT THE SAME FACT, both present on a correspondence:
%
%   iou_basis            'native' or 'aligned' — which intervals the IoU was
%                        computed on
%   target_extent_basis  which of the five derivations gave an agreement group
%                        its interval at all; empty for a detection or consensus
%                        event, which carry their own
%
% Reading one as the other would attribute a clock-drift artefact to a choice
% about group boundaries. Correspondence scores are summarized **per basis pair**
% and never pooled across them, because results on different extent bases rest on
% different intervals and were never comparable.
%
% ABSENCE READS AS ABSENCE. A missing number is NaN, not 0; missing text is "".
% A candidate with no acoustic evidence has no acoustic row, not a zero-valued
% one — a zero would claim a measurement was made. A claim whose source carried
% no score reads as NaN, never as 1.0.
%
% See also VAWLUME.ATTRIBUTION.CORRESPONDWINDOWS, VAWLUME.ATTRIBUTION.DECIDE,
% VAWLUME.ALIGNMENT.REPORT

arguments
    conn
    runRef (1,1) struct
end

run = attributionResolveRun(conn, runRef);
runId = run.attribution_run_id;

targets = attributionReadTargetGeometry(conn, runId);
candidates = readCandidates(conn, runId);
evidence = readEvidence(conn, runId);
claims = readClaims(conn, runId);
correspondences = readCorrespondences(conn, runId);
claimCorrespondences = readClaimCorrespondences(conn, runId);
decisions = readDecisions(conn, runId);
selections = readSelections(conn, runId);
windowCount = countWindows(conn, runId);

value = struct( ...
    attribution_run_id=runId, ...
    run_key=run.run_key, ...
    project_key=run.project_key, ...
    recording_id=run.recording_id, ...
    native_recording_id=run.native_recording_id, ...
    attribution_path=run.attribution_path, ...
    method=run.method, ...
    status=run.status, ...
    analysis_status=run.analysis_status, ...
    settings_profile_version_id=run.settings_profile_version_id, ...
    participating_entity_ids=run.participating_entity_ids, ...
    provenance=run.provenance, ...
    targets=targets, ...
    candidates=candidates, ...
    evidence=evidence, ...
    imported_claims=claims, ...
    correspondences=correspondences, ...
    claim_correspondences=claimCorrespondences, ...
    decisions=decisions, ...
    decision_selections=selections, ...
    qc=qualityControl(targets, candidates, evidence, claims, ...
        correspondences, decisions, windowCount), ...
    dimension_separation_note=dimensionSeparationNote(), ...
    absence_note=absenceNote(), ...
    basis_note=basisNote(), ...
    qc_note=qcNote(), ...
    source="stored attribution_* rows and v_attribution_window_correspondences");
end

% ------------------------------------------------------------------ reads ---

function value = readCandidates(conn, runId)
%READCANDIDATES Every candidate, in stored rank order. None is privileged.
rows = fetch(conn, "SELECT c.attribution_candidate_id, c.attribution_target_id, " + ...
    "c.entity_id, IFNULL(e.native_id,'') AS entity_native_id, " + ...
    "c.candidate_status, IFNULL(c.candidate_rank,-1) AS candidate_rank, " + ...
    "IFNULL(c.score, 1e308) AS score, " + ...
    "IFNULL(c.score_semantics,'') AS score_semantics, " + ...
    "IFNULL(c.probability, 1e308) AS probability, " + ...
    "IFNULL(c.probability_semantics,'') AS probability_semantics, " + ...
    "IFNULL(c.source_label,'') AS source_label " + ...
    "FROM attribution_candidates c " + ...
    "JOIN attribution_targets t " + ...
    "  ON t.attribution_target_id = c.attribution_target_id " + ...
    "LEFT JOIN experimental_entities e ON e.entity_id = c.entity_id " + ...
    "WHERE t.attribution_run_id=" + string(runId) + ...
    " ORDER BY c.attribution_target_id, " + ...
    "IFNULL(c.candidate_rank, 1e9), c.attribution_candidate_id");

value = table(zeros(0, 1), zeros(0, 1), zeros(0, 1), strings(0, 1), ...
    strings(0, 1), zeros(0, 1), zeros(0, 1), strings(0, 1), zeros(0, 1), ...
    strings(0, 1), strings(0, 1), ...
    VariableNames=["attribution_candidate_id", "attribution_target_id", ...
    "entity_id", "entity_native_id", "candidate_status", "candidate_rank", ...
    "score", "score_semantics", "probability", "probability_semantics", ...
    "source_label"]);
for index = 1:height(rows)
    value(end + 1, :) = {double(rows.attribution_candidate_id(index)), ...
        double(rows.attribution_target_id(index)), ...
        double(rows.entity_id(index)), ...
        presentText(rows.entity_native_id(index)), ...
        presentText(rows.candidate_status(index)), ...
        negativeSentinel(rows.candidate_rank(index)), ...
        sentinelNumber(rows.score(index)), ...
        presentText(rows.score_semantics(index)), ...
        sentinelNumber(rows.probability(index)), ...
        presentText(rows.probability_semantics(index)), ...
        presentText(rows.source_label(index))}; %#ok<AGROW>
end
end

function value = readEvidence(conn, runId)
%READEVIDENCE One row per stored evidence record, carrying its own dimension.
%
