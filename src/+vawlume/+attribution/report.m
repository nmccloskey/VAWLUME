    "says whether the IoU was computed on native or aligned intervals; " + ...
    "target_extent_basis says which of the five derivations gave an agreement " + ...
    "group its interval at all, and is empty for a detection or consensus " + ...
    "event. Correspondence scores are summarized within a basis pair and never " + ...
    "pooled across them.";
end

function value = qcNote()
value = "QC reports facts and judges nothing. There is no quality score for a " + ...
