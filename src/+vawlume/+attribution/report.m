% --------------------------------------------------------------------- QC ---

function value = qualityControl(targets, candidates, evidence, claims, ...
        correspondences, decisions, windowCount)
%QUALITYCONTROL Facts about the run. No verdict, no threshold, no quality score.
%
% Every field is a count, a membership, or an observed range. None is a grade.
% "17 targets received no candidate" is a fact a reader can act on; "this run
% scored 0.62" would be an opinion dressed as a measurement, and this prototype
% has no calibrated basis for one.
value = struct( ...
    target_count=height(targets), ...
    candidate_count=height(candidates), ...
    evidence_count=height(evidence), ...
    imported_window_count=windowCount, ...
    imported_claim_count=height(claims), ...
    correspondence_count=height(correspondences), ...
    decision_count=height(decisions), ...
    targets_without_candidate=targetsWithoutCandidate(targets, candidates), ...
    targets_with_empty_extent=targetsWithEmptyExtent(targets), ...
    candidates_per_target=candidatesPerTarget(targets, candidates), ...
    candidate_status_counts=countByText(candidates, "candidate_status"), ...
    decision_status_counts=countByText(decisions, "decision_status"), ...
    evidence_by_dimension=evidenceByDimension(evidence), ...
    claims_without_score=nnz(isnan(claims.score)), ...
    claims_without_probability=nnz(isnan(claims.probability)), ...
    claims_without_resolved_entity=nnz(isnan(claims.entity_id)), ...
    imported_label_resolution=labelResolution(claims), ...
    windows_without_correspondence=windowsWithout(correspondences, ...
        windowCount), ...
    windows_with_multiple_correspondences=windowsWithMultiple(correspondences), ...
    correspondence_by_basis=correspondenceByBasis(correspondences));
end

function value = targetsWithoutCandidate(targets, candidates)
%TARGETSWITHOUTCANDIDATE A fact, not a failure. Reported with enough identity to
% act on: which target, of which kind, and on which extent basis where that
% applies, since a group may have received candidates under one basis and not
% another.
value = targets(~ismember(targets.attribution_target_id, ...
    candidates.attribution_target_id), ...
    ["attribution_target_id", "target_kind", "target_extent_basis", ...
    "start_time_s", "end_time_s", "extent_is_empty"]);
end

function value = targetsWithEmptyExtent(targets)
%TARGETSWITHEMPTYEXTENT An agreement group whose declared extent is empty has no
% interval, so nothing could correspond to it. Surfaced rather than left to be
% inferred from an absent correspondence.
value = targets(targets.extent_is_empty, ...
    ["attribution_target_id", "target_kind", "target_extent_basis"]);
end

function value = candidatesPerTarget(targets, candidates)
value = table(zeros(0, 1), strings(0, 1), strings(0, 1), zeros(0, 1), ...
    VariableNames=["attribution_target_id", "target_kind", ...
    "target_extent_basis", "candidate_count"]);
for index = 1:height(targets)
    targetId = targets.attribution_target_id(index);
    value(end + 1, :) = {targetId, targets.target_kind(index), ...
        targets.target_extent_basis(index), ...
        nnz(candidates.attribution_target_id == targetId)}; %#ok<AGROW>
end
end

function value = countByText(rows, column)
value = table(strings(0, 1), zeros(0, 1), VariableNames=[column, "count"]);
if height(rows) == 0
    return
end
observed = unique(rows.(column));
for index = 1:numel(observed)
    value(end + 1, :) = {observed(index), ...
        nnz(rows.(column) == observed(index))}; %#ok<AGROW>
end
end

function value = evidenceByDimension(evidence)
%EVIDENCEBYDIMENSION Which dimensions this run carries, counted separately.
%
% One row per dimension present. There is deliberately no total, no coverage
% fraction, and no field spanning two dimensions: a number combining them would
% be the combination Phase 4 does not perform, arrived at by arithmetic instead
% of by method.
value = table(strings(0, 1), zeros(0, 1), zeros(0, 1), zeros(0, 1), ...
    VariableNames=["evidence_dimension", "row_count", ...
    "candidate_level_count", "target_level_count"]);
if height(evidence) == 0
    return
end
observed = unique(evidence.evidence_dimension);
for index = 1:numel(observed)
    rows = evidence(evidence.evidence_dimension == observed(index), :);
    value(end + 1, :) = {observed(index), height(rows), ...
        nnz(~isnan(rows.attribution_candidate_id)), ...
        nnz(isnan(rows.attribution_candidate_id))}; %#ok<AGROW>
end
end

function value = labelResolution(claims)
%LABELRESOLUTION Which imported label resolved to which entity, and how often.
value = table(strings(0, 1), zeros(0, 1), strings(0, 1), zeros(0, 1), ...
    VariableNames=["source_caller_label", "entity_id", "entity_native_id", ...
    "claim_count"]);
if height(claims) == 0
    return
end
labels = unique(claims.source_caller_label);
for index = 1:numel(labels)
    rows = claims(claims.source_caller_label == labels(index), :);
    value(end + 1, :) = {labels(index), rows.entity_id(1), ...
        rows.entity_native_id(1), height(rows)}; %#ok<AGROW>
end
end

function value = windowsWithout(correspondences, windowCount)
%WINDOWSWITHOUT A window matching nothing is a finding, not a failure: an
% attribution system may have emitted a window for a call no extractor found.
%
% Counted from `correspondences`, whose grain is one row per correspondence. The
% joined claim table would overcount a window carrying several claims.
if windowCount == 0
    value = 0;
    return
end
value = windowCount - numel(unique(correspondences.imported_attribution_window_id));
end

function value = windowsWithMultiple(correspondences)
%WINDOWSWITHMULTIPLE The ambiguous case, counted. Nothing resolves it.
value = 0;
if height(correspondences) == 0
    return
end
ids = correspondences.imported_attribution_window_id;
observed = unique(ids);
for index = 1:numel(observed)
    if nnz(ids == observed(index)) > 1
        value = value + 1;
    end
end
end

function value = correspondenceByBasis(correspondences)
%CORRESPONDENCEBYBASIS Score distribution, summarized WITHIN a basis pair.
%
% Never pooled across bases. An IoU computed on aligned intervals is not the IoU
% of the native ones under a piecewise clock, and an IoU against a group's union
% extent is not the IoU against its intersection extent — the intervals differ,
% so the numbers were never comparable. A single run-wide distribution would
% average quantities that measure different things, which is why none is
% offered.
%
% Min, median and max describe what was observed. None is a threshold and none
% grades the run.
value = table(strings(0, 1), strings(0, 1), zeros(0, 1), zeros(0, 1), ...
    zeros(0, 1), zeros(0, 1), zeros(0, 1), ...
    VariableNames=["iou_basis", "target_extent_basis", ...
    "correspondence_count", "window_count", "temporal_iou_min", ...
    "temporal_iou_median", "temporal_iou_max"]);
if height(correspondences) == 0
    return
end
keys = unique(strcat(correspondences.iou_basis, "|", ...
    correspondences.target_extent_basis));
for index = 1:numel(keys)
    parts = split(keys(index), "|");
    rows = correspondences(correspondences.iou_basis == parts(1) & ...
        correspondences.target_extent_basis == parts(2), :);
    ious = rows.temporal_iou(~isnan(rows.temporal_iou));
    if isempty(ious)
        minimum = NaN;
        middle = NaN;
        maximum = NaN;
    else
        minimum = min(ious);
        middle = median(ious);
        maximum = max(ious);
    end
    value(end + 1, :) = {parts(1), parts(2), height(rows), ...
        numel(unique(rows.imported_attribution_window_id)), ...
        minimum, middle, maximum}; %#ok<AGROW>
end
end

