        negativeSentinel(rows.alignment_run_id(index)), ...
        negativeSentinel(rows.source_file_id(index)), ...
        negativeSentinel(rows.mapping_profile_version_id(index)), ...
        presentText(rows.source_locator(index))}; %#ok<AGROW>
end
end

function value = readClaims(conn, runId)
%READCLAIMS The exporting system's caller claims, with their own numbers.
%
% A NULL score reads as NaN. It means the source supplied no number, not that it
% supplied zero, and certainly not that the named caller is certain.
%
% entity_id may be NaN. Under the shipped resolution policy intake resolves every
% label or refuses the import by name, so nothing writes NULL there today; a NaN
% therefore means only that no shipped policy produced this row, and nothing more
% may be inferred from it.
rows = fetch(conn, "SELECT cl.imported_attribution_claim_id, " + ...
    "cl.imported_attribution_window_id, " + ...
    "IFNULL(iw.native_window_id,'') AS native_window_id, " + ...
    "iw.start_time_native, iw.end_time_native, " + ...
    "cl.claim_ordinal, cl.source_caller_label, " + ...
    "IFNULL(cl.entity_id,-1) AS entity_id, " + ...
    "IFNULL(e.native_id,'') AS entity_native_id, " + ...
    "IFNULL(cl.score, 1e308) AS score, " + ...
    "IFNULL(cl.score_semantics,'') AS score_semantics, " + ...
    "IFNULL(cl.probability, 1e308) AS probability, " + ...
    "IFNULL(cl.probability_semantics,'') AS probability_semantics, " + ...
    "IFNULL(cl.source_locator,'') AS source_locator " + ...
    "FROM imported_attribution_claims cl " + ...
    "JOIN imported_attribution_windows iw " + ...
    "  ON iw.imported_attribution_window_id = cl.imported_attribution_window_id " + ...
    "LEFT JOIN experimental_entities e ON e.entity_id = cl.entity_id " + ...
    "WHERE iw.attribution_run_id=" + string(runId) + ...
    " ORDER BY cl.imported_attribution_window_id, cl.claim_ordinal");

value = table(zeros(0, 1), zeros(0, 1), strings(0, 1), zeros(0, 1), ...
    zeros(0, 1), zeros(0, 1), strings(0, 1), zeros(0, 1), strings(0, 1), ...
    zeros(0, 1), strings(0, 1), zeros(0, 1), strings(0, 1), strings(0, 1), ...
    VariableNames=["imported_attribution_claim_id", ...
    "imported_attribution_window_id", "native_window_id", ...
    "start_time_native", "end_time_native", "claim_ordinal", ...
    "source_caller_label", "entity_id", "entity_native_id", "score", ...
    "score_semantics", "probability", "probability_semantics", ...
    "source_locator"]);
for index = 1:height(rows)
    value(end + 1, :) = {double(rows.imported_attribution_claim_id(index)), ...
        double(rows.imported_attribution_window_id(index)), ...
        presentText(rows.native_window_id(index)), ...
        double(rows.start_time_native(index)), ...
        double(rows.end_time_native(index)), ...
        double(rows.claim_ordinal(index)), ...
        presentText(rows.source_caller_label(index)), ...
        negativeSentinel(rows.entity_id(index)), ...
        presentText(rows.entity_native_id(index)), ...
        sentinelNumber(rows.score(index)), ...
        presentText(rows.score_semantics(index)), ...
        sentinelNumber(rows.probability(index)), ...
        presentText(rows.probability_semantics(index)), ...
        presentText(rows.source_locator(index))}; %#ok<AGROW>
end
end

