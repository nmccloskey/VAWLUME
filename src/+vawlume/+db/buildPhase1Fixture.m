function ref = lookupFeatureRef(conn, extractorVersionId, nativeName, sourceArtifactType, derivationStage, operationalVariant, canonicalName)
rows = fetch(conn, ...
    "SELECT xf.extractor_feature_id, cf.canonical_feature_id " + ...
    "FROM extractor_features xf " + ...
    "JOIN feature_mappings fm ON fm.extractor_feature_id = xf.extractor_feature_id " + ...
    "JOIN canonical_features cf ON cf.canonical_feature_id = fm.canonical_feature_id " + ...
    "WHERE xf.extractor_version_id = " + string(extractorVersionId) + ...
    " AND xf.native_name = " + sqlText(nativeName) + ...
    " AND IFNULL(xf.source_artifact_type, '') = " + sqlText(sourceArtifactType) + ...
    " AND IFNULL(xf.derivation_stage, '') = " + sqlText(derivationStage) + ...
    " AND IFNULL(xf.operational_variant, '') = " + sqlText(operationalVariant) + ...
    " AND cf.canonical_name = " + sqlText(canonicalName));
if height(rows) ~= 1
    error("vawlume:db:FixtureFeatureMissing", ...
        "Expected one feature mapping for %s -> %s, found %d.", nativeName, canonicalName, height(rows));
end
ref = struct( ...
    extractor_feature_id=double(rows.extractor_feature_id(1)), ...
    canonical_feature_id=double(rows.canonical_feature_id(1)), ...
    native_name=nativeName, ...
    canonical_name=canonicalName, ...
    operational_variant=operationalVariant);
end

