function summary = buildPhase1Fixture(conn, repoRoot, options)
%BUILDPHASE1FIXTURE Populate a deterministic Phase 1 synthetic fixture.
%
% The fixture is source-controlled data for tests and examples. It assumes a
% schema has already been applied to conn, registers built-in semantic
% profiles by default, and then inserts synthetic instance data into a fresh
% project namespace.

arguments
    conn
    repoRoot (1,1) string = ""
    options.RegisterSemantics (1,1) logical = true
end

if strlength(repoRoot) == 0
    repoRoot = defaultRepoRoot();
else
    repoRoot = normalizePath(repoRoot);
end

if options.RegisterSemantics
    semanticSummary = vawlume.db.registerBuiltinSemantics(conn, repoRoot);
else
    semanticSummary = struct();
end

fixture = fixtureConstants(repoRoot);
assertFixtureProjectAbsent(conn, fixture.project_key);

oldAutoCommit = conn.AutoCommit;
conn.AutoCommit = "off";
try
    execute(conn, "PRAGMA foreign_keys = ON");

    profiles = registerExampleProfiles(conn, fixture);
    ids = struct();
    ids.project = insertProject(conn, fixture);
    insertProjectProfileAssignments(conn, ids.project, profiles, fixture);

    ids.entity_types = insertEntityTypes(conn, ids.project);
    ids.entities = insertEntities(conn, ids.project, ids.entity_types);
    insertEntityAttributes(conn, ids.entities, fixture);
    insertEntityRelationships(conn, ids.project, ids.entities);
    insertSessionProfileAssignments(conn, ids.entities, profiles, fixture);

    [ids.source_files, ids.recordings, ids.channels] = insertRecordings(conn, ids.project, ids.entities, fixture);
    insertRecordingLinks(conn, ids.recordings, ids.entities);
    insertRecordingProfileAssignments(conn, ids.recordings, profiles, fixture);
    ids.epochs = insertRecordingEpochs(conn, ids.recordings);

    ids.extractor_versions = lookupExtractorVersions(conn);
    ids.output_profiles = lookupOutputMappingProfiles(conn);
    ids.artifacts = insertArtifacts(conn, ids.project, fixture);
    ids.extraction_runs = insertExtractionRuns(conn, ids.project, ids.extractor_versions, ids.output_profiles, fixture);
    insertExtractionRunInputs(conn, ids.extraction_runs, ids.recordings, ids.channels);
    insertExtractionRunProfiles(conn, ids.extraction_runs, profiles);
    insertExtractionRunArtifacts(conn, ids.extraction_runs, ids.artifacts);
    ids.extractor_objects = insertExtractorObjects(conn, ids.extraction_runs, ids.artifacts, ids.recordings);

    ids.features = lookupMeasurementFeatures(conn, ids.extractor_versions);
    ids.detections = insertDetections(conn, ids.extraction_runs, ids.recordings, ids.artifacts, ids.extractor_objects);
    insertMeasurements(conn, ids.detections, ids.artifacts, ids.features);
    insertCurationEvents(conn, ids.detections, ids.artifacts, fixture);

    ids.analysis_runs = insertAnalysisRuns(conn, ids.project, fixture);
    insertAnalysisInputs(conn, ids.analysis_runs, ids.extraction_runs);
    [ids.match_groups, ids.consensus_events] = insertMatchingRows(conn, ids.analysis_runs.matching, ids.recordings.social, ids.detections);
    insertManualReviews(conn, ids.analysis_runs.matching, ids.detections, ids.match_groups, ids.consensus_events, fixture);

    [ids.timebases, ids.external_streams, ids.external_events, ids.alignment_run] = insertExternalAlignmentRows( ...
        conn, ids.project, ids.recordings.social, ids.source_files.behavior, ids.entities, ids.analysis_runs.alignment);

    commit(conn);
catch exception
    try
        rollback(conn);
    catch
    end
    conn.AutoCommit = oldAutoCommit;
    rethrow(exception);
end
conn.AutoCommit = oldAutoCommit;

summary = buildSummary(conn, ids.project, fixture, semanticSummary);
end

