function profileVersionId = upsertBuiltInProfileVersion(conn, expected)
profileRows = fetch(conn, ...
    "SELECT profile_id, profile_name, profile_kind, is_builtin, IFNULL(description, '') AS description " + ...
    "FROM config_profiles WHERE project_id IS NULL AND profile_key = " + sqlText(expected.profile_key));
if height(profileRows) == 0
    profileId = insertRow(conn, "config_profiles", struct( ...
        profile_key=expected.profile_key, ...
        profile_name=expected.profile_name, ...
        profile_kind=expected.profile_kind, ...
        is_builtin=1, ...
        description=expected.description, ...
        created_at_utc=expected.created_at_utc), "profile_id");
else
    profileId = double(profileRows.profile_id(1));
    assertTextEquals(profileRows.profile_name(1), expected.profile_name, "config_profiles.profile_name");
    assertTextEquals(profileRows.profile_kind(1), expected.profile_kind, "config_profiles.profile_kind");
    assert(double(profileRows.is_builtin(1)) == 1, "Expected built-in profile to have is_builtin=1.");
end

versionRows = fetch(conn, ...
    "SELECT profile_version_id, IFNULL(profile_schema_version, '') AS profile_schema_version, " + ...
    "content_format, content_uri, IFNULL(checksum_sha256, '') AS checksum_sha256, is_snapshot, " + ...
    "IFNULL(notes, '') AS notes FROM config_profile_versions " + ...
    "WHERE profile_id = " + string(profileId) + " AND version_label = " + sqlText(expected.version_label));
if height(versionRows) == 0
    profileVersionId = insertRow(conn, "config_profile_versions", struct( ...
        profile_id=profileId, ...
        version_label=expected.version_label, ...
        profile_schema_version=expected.profile_schema_version, ...
        content_format=expected.content_format, ...
        content_uri=expected.content_uri, ...
        checksum_sha256=expected.checksum_sha256, ...
        is_snapshot=1, ...
        created_at_utc=expected.created_at_utc, ...
        notes=expected.notes), "profile_version_id");
else
    profileVersionId = double(versionRows.profile_version_id(1));
    assertTextEquals(versionRows.profile_schema_version(1), expected.profile_schema_version, "config_profile_versions.profile_schema_version");
    assertTextEquals(versionRows.content_format(1), expected.content_format, "config_profile_versions.content_format");
    assertTextEquals(versionRows.content_uri(1), expected.content_uri, "config_profile_versions.content_uri");
    assertTextEquals(versionRows.checksum_sha256(1), expected.checksum_sha256, "config_profile_versions.checksum_sha256");
end
end

