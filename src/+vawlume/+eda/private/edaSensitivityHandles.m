function catalog = edaSensitivityHandles(family)
%EDASENSITIVITYHANDLES The sensitivity handles (contract 07 D6, D7), by family.
%
% FAMILY is "attribution" (vawlume.eda.attributionSensitivity, 7.8) or
% "correspondence" (vawlume.eda.correspondenceSensitivity, 7.9).
%
% variable    handles a variant may change, the factors each accepts, and what a
%             variant is. A factor not listed is refused.
% reported    handles that are NOT varied, each with its status and reason. They
%             appear as rows in every sensitivity summary of that family and are
%             never omitted. Requesting one as a variant raises
%             vawlume:eda:SensitivityHandleNotVariable with that reason.
arguments
    family (1,1) string {mustBeMember(family, ["attribution", "correspondence"])} = "attribution"
end
variable = table( ...
    ["decision_policy"; "estimator_settings"; "normalization_policy"; "alignment_run"; ...
        "matching_temporal"; "matching_spectral"], ...
    {["selection_threshold", "separation_margin", "co_occurrence_threshold"]; ...
        ["primary_instant_basis", "max_interpolation_gap_s", "min_distance", "channel_pair"]; ...
        "reference_type"; ...
        ["audio_alignment_run_id", "tracking_alignment_run_id"]; ...
        "min_temporal_iou"; ...
        "relative_tolerance"}, ...
    ["decision_set"; "run"; "run"; "run"; "configuration"; "configuration"], ...
    ["decide again on the reference run under a generated policy version; " + ...
            "the decisions sit beside the reference's"; ...
        "a generated settings version; attributeCallers again, reusing the " + ...
            "reference's normalization runs"; ...
        "normalizeCallLevels on the reference's call-window runs under a generated " + ...
            "policy, then a generated settings version naming that policy (6.12a)"; ...
        "attributeCallers again naming another, already fitted alignment run"; ...
        "a generated matching specification whose plausibility_rule.min_temporal_iou " + ...
            "differs; new matching, agreement and consensus, then native attribution"; ...
        "a generated matching specification whose every feature_support." + ...
            "discrepancy_tolerance relative_tolerance differs; new analyses, then " + ...
            "native attribution"], ...
    ["attribution"; "attribution"; "attribution"; "attribution"; "correspondence"; ...
        "correspondence"], ...
    VariableNames=["handle", "factors", "variant_kind", "how", "family"]);
reported = table( ...
    ["pose_confidence_gate"; "temporal_uncertainty_gate_s"; "dimension_declarations"; ...
        "positional_error"; "identity_uncertainty"; "call_band"; "matching_duration"], ...
    ["not_variable"; "not_variable"; "not_variable"; "reported_elsewhere"; ...
        "not_measurable"; "not_exercised"; "not_variable"], ...
    ["Method 1.0.0 implements no gate: vawlume.estimator.loadSettings refuses a " + ...
        "non-null pose_confidence_gate (SettingsGateNotImplemented)."; ...
    "Method 1.0.0 implements no gate: vawlume.estimator.loadSettings refuses a " + ...
        "non-null temporal_uncertainty_gate_s (SettingsGateNotImplemented)."; ...
    "Method 1.0.0 uses all four dimensions, so each must be declared used " + ...
        "(SettingsDimensionMisdeclared)."; ...
    "Not a variant: a read-only margin, how far a candidate's distance would " + ...
        "have to change to reverse the ranking, reported by vawlume.estimator.qcFacts " + ...
        "(contract 07 D8, itinerary 7.10)."; ...
    "Not measurable in v2: method 1.0.0 admits identity only as resolve-or-unscored " + ...
        "(contract 06 D9); identity_value is never read, so no continuous handle " + ...
        "exists, and another association set is another input."; ...
    "Available but not exercised in v2: the call band re-measures audio, which " + ...
        "attribution-side sensitivity does not do (itinerary 7.8)."; ...
    "The tracked matching specification's plausibility rule has no duration bound; " + ...
        "duration_difference_s is evidence, not a gate, so no duration variant exists. " + ...
        "Were one added, note CAL-001: the duration difference is an absolute number " + ...
        "of seconds, so its axis is not scale-free."], ...
    ["attribution"; "attribution"; "attribution"; "attribution"; "attribution"; ...
        "attribution"; "correspondence"], ...
    VariableNames=["handle", "status", "reason", "family"]);
catalog.variable = variable(variable.family == family, 1:4);
catalog.reported = reported(reported.family == family, 1:3);
catalog.all_handles = [variable.handle; reported.handle];
end
