function runId = acousticInsertRun(conn, projectId, runType, status, options)
%ACOUSTICINSERTRUN Insert the analysis_runs row of one acoustic run.
%
% OPTIONS carries RunKey, RunLabel, VawlumeVersion, SourceCommit and Notes, as
% every acoustic producer declares them.
runId = acousticInsertRow(conn, "analysis_runs", struct( ...
    project_id=projectId, run_type=runType, run_key=options.RunKey, ...
    run_label=options.RunLabel, vawlume_version=options.VawlumeVersion, ...
    source_commit=options.SourceCommit, status=status, ...
    completed_at_utc=acousticUtcTimestamp(), notes=options.Notes), ...
    "analysis_run_id");
end
