end

function value = normalizeDispersion(rows)
value = table(strings(0, 1), zeros(0, 1), strings(0, 1), zeros(0, 1), ...
    zeros(0, 1), ...
    VariableNames=["anchor_key", "timebase_id", "timebase_key", ...
    "observation_count", "spread_s"]);
for index = 1:height(rows)
    value(end + 1, :) = {presentText(rows.anchor_key(index)), ...
        double(rows.timebase_id(index)), ...
        presentText(rows.timebase_key(index)), ...
        double(rows.observation_count(index)), ...
        double(rows.spread_s(index))}; %#ok<AGROW>
end
end

function value = normalizeStray(rows)
value = table(zeros(0, 1), strings(0, 1), zeros(0, 1), ...
    VariableNames=["timebase_id", "timebase_key", "observation_count"]);
for index = 1:height(rows)
    value(end + 1, :) = {double(rows.timebase_id(index)), ...
        presentText(rows.timebase_key(index)), ...
        double(rows.observation_count(index))}; %#ok<AGROW>
end
end

function value = diagnosticsFromResiduals(residuals, transforms)
%DIAGNOSTICSFROMRESIDUALS Whether the anchors could support the model.
%
% Derived from the stored residuals, which is the same evidence the fitter used,
% so the read side and the plan side agree without a second stored copy.
%
% Every number here is reported for a reader to judge. None is a threshold, a
% grade, or a verdict: this prototype ships no calibrated acceptance criterion.
% The span and gap matter because anchors clustered at one end of a session
% support an offset far better than a slope, and a fit summary cannot show that.
value = table(zeros(0, 1), strings(0, 1), zeros(0, 1), zeros(0, 1), ...
    zeros(0, 1), zeros(0, 1), zeros(0, 1), zeros(0, 1), zeros(0, 1), ...
    VariableNames=["alignment_run_id", "source_timebase_key", ...
    "paired_anchor_count", "included_anchor_count", "withheld_anchor_count", ...
    "source_range_start", "source_range_end", "source_span_s", ...
    "largest_gap_fraction"]);
for index = 1:height(transforms)
    runId = transforms.alignment_run_id(index);
    rows = residuals(residuals.alignment_run_id == runId, :);
    included = sort(rows.observed_source_time(rows.included_in_fit == 1));
    rangeStart = NaN;
    rangeEnd = NaN;
    span = NaN;
    gap = NaN;
    if ~isempty(included)
        rangeStart = included(1);
        rangeEnd = included(end);
        span = rangeEnd - rangeStart;
        if numel(included) > 1 && span > 0
            gap = max(diff(included)) / span;
        end
    end
    value(end + 1, :) = {runId, transforms.source_timebase_key(index), ...
        height(rows), numel(included), nnz(rows.included_in_fit == 0), ...
        rangeStart, rangeEnd, span, gap}; %#ok<AGROW>
end
end

function value = uncertaintyNote()
value = "A segment's uncertainty_s is the largest recorded anchor " + ...
    "uncertainty among the anchors that determined it, on the reference " + ...
    "clock. It is uncalibrated: not a confidence interval, a standard error, " + ...
    "or a probability, and it is never combined with rmse_s.";
end

function value = dispersionNote()
value = "Replicate spread is derived from alignment_anchor_observations on " + ...
    "read and is never stored. A replicate is evidence about how consistently " + ...
    "a marker was read, never an extra statistical anchor. An anchor read " + ...
    "once has no dispersion and appears in no row here.";
end

function value = normalizeResiduals(rows)
value = table(zeros(0, 1), strings(0, 1), strings(0, 1), zeros(0, 1), ...
    zeros(0, 1), zeros(0, 1), zeros(0, 1), zeros(0, 1), zeros(0, 1), ...
    zeros(0, 1), strings(0, 1), ...
    VariableNames=["alignment_run_id", "source_timebase_key", "anchor_key", ...
    "source_observation_id", "reference_observation_id", ...
    "observed_source_time", "observed_reference_time", ...
    "predicted_reference_time", "residual_s", "included_in_fit", ...
    "exclusion_reason"]);
for index = 1:height(rows)
    value(end + 1, :) = {double(rows.alignment_run_id(index)), ...
        presentText(rows.source_timebase_key(index)), ...
        presentText(rows.anchor_key(index)), ...
        double(rows.source_observation_id(index)), ...
        double(rows.reference_observation_id(index)), ...
        double(rows.observed_source_time(index)), ...
        double(rows.observed_reference_time(index)), ...
        double(rows.predicted_reference_time(index)), ...
        double(rows.residual_s(index)), ...
        double(rows.included_in_fit(index)), ...
        presentText(rows.exclusion_reason(index))}; %#ok<AGROW>
end
end

function value = sentinelNumber(raw)
value = double(raw);
if value >= 1e307
    value = NaN;
end
end

function value = negativeSentinel(raw)
value = double(raw);
if value < 0
    value = NaN;
end
end

function value = presentText(value)
value = string(value);
value(ismissing(value)) = "";
end
