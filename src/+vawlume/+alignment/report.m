    value(end + 1, :) = {double(rows.alignment_run_id(index)), ...
        presentText(rows.source_timebase_key(index)), ...
        double(rows.breakpoint_index(index)), ...
        double(rows.source_time(index)), ...
        presentText(rows.declared_by(index))}; %#ok<AGROW>
