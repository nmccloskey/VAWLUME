function [ir, root] = parsedIR(repoRoot, profileId, relativePath)
root = string(tempname);
mkdir(root);
touchFile(fullfile(root, relativePath));
ir = vawlume.source_mapping.parse(projectProfilePath(repoRoot), root, ...
    ProfileId=profileId, RepoRoot=repoRoot);
end

function value = projectSpec(suffix)
value = struct(project_key="transaction_test_" + string(suffix), ...
    project_name="Transaction test " + string(suffix), ...
    description="Pass 5 transaction/provenance integration case.");
end

function value = targetCounts(conn)
value = struct( ...
    projects=scalar(conn, "SELECT COUNT(*) AS n FROM projects"), ...
    config_profiles=scalar(conn, ...
    "SELECT COUNT(*) AS n FROM config_profiles"), ...
    config_profile_versions=scalar(conn, ...
    "SELECT COUNT(*) AS n FROM config_profile_versions"), ...
    project_profile_assignments=scalar(conn, ...
    "SELECT COUNT(*) AS n FROM project_profile_assignments"), ...
    ingestion_runs=scalar(conn, ...
    "SELECT COUNT(*) AS n FROM ingestion_runs"), ...
    ingestion_files=scalar(conn, ...
    "SELECT COUNT(*) AS n FROM ingestion_files"), ...
    source_files=scalar(conn, "SELECT COUNT(*) AS n FROM source_files"), ...
    entity_types=scalar(conn, "SELECT COUNT(*) AS n FROM entity_types"), ...
    entities=scalar(conn, ...
    "SELECT COUNT(*) AS n FROM experimental_entities"), ...
    entity_relationships=scalar(conn, ...
    "SELECT COUNT(*) AS n FROM entity_relationships"), ...
    recordings=scalar(conn, "SELECT COUNT(*) AS n FROM recordings"), ...
    recording_entity_links=scalar(conn, ...
    "SELECT COUNT(*) AS n FROM recording_entity_links"), ...
    recording_profile_assignments=scalar(conn, ...
    "SELECT COUNT(*) AS n FROM recording_profile_assignments"));
end

function value = zeroTargetCounts()
value = struct( ...
    projects=0, config_profiles=0, config_profile_versions=0, ...
    project_profile_assignments=0, ingestion_runs=0, ingestion_files=0, ...
    source_files=0, entity_types=0, entities=0, entity_relationships=0, ...
    recordings=0, recording_entity_links=0, ...
    recording_profile_assignments=0);
end

function [conn, dbFile, repoRoot] = createDisposableDatabase()
repoRoot = repoRootForTest();
addpath(fullfile(repoRoot, "src"));
dbFile = string(tempname) + ".sqlite";
conn = sqlite(char(dbFile), "create");
vawlume.db.applySchema(conn, fullfile(repoRoot, "schema", "schema.sql"));
end

function value = scalar(conn, sql)
rows = fetch(conn, sql);
value = double(rows.n(1));
end

function cleanupDatabase(conn, dbFile)
if isopen(conn)
    close(conn);
end
deleteIfExists(dbFile);
deleteIfExists(dbFile + "-journal");
deleteIfExists(dbFile + "-wal");
deleteIfExists(dbFile + "-shm");
end

function touchFile(path)
parent = string(fileparts(path));
if ~isfolder(parent)
    mkdir(parent);
end
fileId = fopen(path, "w");
assert(fileId ~= -1, "Test fixture file could not be created.");
cleanupFile = onCleanup(@() fclose(fileId));
fwrite(fileId, uint8([]));
clear cleanupFile
end

function removeTree(root)
if isfolder(root)
    rmdir(root, "s");
end
end

function deleteIfExists(path)
if isfile(path)
    delete(path);
end
end

function path = linkagePath(repoRoot)
path = fullfile(repoRoot, "config", "04_examples", ...
    "profile_linkage_example.json");
end

function path = projectProfilePath(repoRoot)
path = fullfile(repoRoot, "config", "01_mapping_profiles", ...
    "project_inputs", "project_input_source_mapping_examples.json");
end

function repoRoot = repoRootForTest()
repoRoot = fileparts(fileparts(fileparts(mfilename("fullpath"))));
end
