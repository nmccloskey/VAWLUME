function tests = test_project_intake_transactions
tests = functiontests({ ...
    @testLateProfileAssignmentFailureRollsBackWholeIntake, ...
    @testWarningsCommitWithAuditStatus, ...
    @testDyadicRecordingProvenanceReadBack, ...
    @testTrackedDeviceSetupProvenanceReadBack});
end

function testLateProfileAssignmentFailureRollsBackWholeIntake(testCase)
[conn, dbFile, repoRoot] = createDisposableDatabase();
cleanupDb = onCleanup(@() cleanupDatabase(conn, dbFile));
[ir, sourceRoot] = parsedIR(repoRoot, ...
    "example.project.mouse_courtship.folder_driven", ...
    fullfile("control", "mouse_001", "baseline", ...
    "001_baseline_1.wav"));
cleanupRoot = onCleanup(@() removeTree(sourceRoot));
execute(conn, "CREATE TRIGGER force_profile_assignment_failure " + ...
    "BEFORE INSERT ON recording_profile_assignments BEGIN " + ...
    "SELECT RAISE(ABORT, 'forced profile assignment failure'); END");

didThrow = false;
try
    vawlume.ingest.project(conn, ir, projectSpec("rollback"), ...
        Apply=true, ProfileLinkagePath=linkagePath(repoRoot), ...
        RepoRoot=repoRoot);
catch exception
    didThrow = true;
    verifyTrue(testCase, contains(string(exception.message), ...
        "forced profile assignment failure"));
end

verifyTrue(testCase, didThrow);
verifyEqual(testCase, string(conn.AutoCommit), "on");
verifyEqual(testCase, targetCounts(conn), zeroTargetCounts());
verifyEqual(testCase, height(fetch(conn, "PRAGMA foreign_key_check")), 0);

clear cleanupRoot cleanupDb
rmpath(fullfile(repoRoot, "src"));
end

function testWarningsCommitWithAuditStatus(testCase)
[conn, dbFile, repoRoot] = createDisposableDatabase();
cleanupDb = onCleanup(@() cleanupDatabase(conn, dbFile));
[ir, sourceRoot] = parsedIR(repoRoot, ...
    "example.project.rat_self_admin.filename_driven", ...
    "OXY_PR_R03_SA07_001.wav");
cleanupRoot = onCleanup(@() removeTree(sourceRoot));

result = vawlume.ingest.project(conn, ir, projectSpec("warnings"), ...
    Apply=true);
run = fetch(conn, ...
    "SELECT status FROM ingestion_runs WHERE ingestion_run_id = " + ...
    string(result.ingestion_run_id));
file = fetch(conn, ...
    "SELECT parse_status, warning_count, error_count, parser_message " + ...
    "FROM ingestion_files WHERE ingestion_run_id = " + ...
    string(result.ingestion_run_id));

verifyEqual(testCase, result.status, "completed_with_warnings");
verifyTrue(testCase, result.committed);
verifyGreaterThanOrEqual(testCase, height(result.warnings), 1);
verifyEqual(testCase, string(run.status), "completed_with_warnings");
verifyEqual(testCase, string(file.parse_status), "parsed_with_warnings");
verifyGreaterThanOrEqual(testCase, double(file.warning_count), 1);
verifyEqual(testCase, double(file.error_count), 0);
verifyGreaterThan(testCase, strlength(string(file.parser_message)), 0);
verifyEqual(testCase, height(fetch(conn, "PRAGMA foreign_key_check")), 0);

clear cleanupRoot cleanupDb
rmpath(fullfile(repoRoot, "src"));
end

function testDyadicRecordingProvenanceReadBack(testCase)
[conn, dbFile, repoRoot] = createDisposableDatabase();
cleanupDb = onCleanup(@() cleanupDatabase(conn, dbFile));
relativeNative = fullfile("cohort_01", "dyad_004", ...
    "D004_M012_F031_courtship.wav");
relativePath = replace(string(relativeNative), string(filesep), "/");
[ir, sourceRoot] = parsedIR(repoRoot, ...
    "example.project.social_dyad.multi_subject", relativeNative);
cleanupRoot = onCleanup(@() removeTree(sourceRoot));

result = vawlume.ingest.project(conn, ir, projectSpec("dyadic"), ...
    Apply=true);
trace = fetch(conn, ...
    "SELECT r.recording_id, sf.relative_path, p.project_key, " + ...
    "cp.profile_key AS mapping_profile_key, " + ...
    "cpv.version_label AS mapping_version, " + ...
    "cpv.checksum_sha256 AS mapping_checksum, " + ...
    "ir.ingestion_run_id, ir.status AS ingestion_status, " + ...
    "rel.link_type, CASE WHEN rel.role_label IS NULL THEN '<empty>' " + ...
    "ELSE rel.role_label END AS role_label, et.native_name AS entity_type, " + ...
    "ee.native_id AS entity_native_id " + ...
    "FROM recordings r " + ...
    "JOIN source_files sf ON sf.source_file_id = r.source_file_id " + ...
    "JOIN projects p ON p.project_id = r.project_id " + ...
    "JOIN recording_entity_links rel ON rel.recording_id = r.recording_id " + ...
    "JOIN experimental_entities ee ON ee.entity_id = rel.entity_id " + ...
    "JOIN entity_types et ON et.entity_type_id = ee.entity_type_id " + ...
    "JOIN ingestion_files inf ON inf.source_file_id = sf.source_file_id " + ...
    "JOIN ingestion_runs ir ON ir.ingestion_run_id = inf.ingestion_run_id " + ...
    "JOIN config_profile_versions cpv ON cpv.profile_version_id = " + ...
    "ir.mapping_profile_version_id " + ...
    "JOIN config_profiles cp ON cp.profile_id = cpv.profile_id " + ...
    "WHERE ir.ingestion_run_id = " + string(result.ingestion_run_id) + ...
    " ORDER BY rel.link_type, role_label, ee.native_id");

verifyEqual(testCase, height(trace), 3);
verifyEqual(testCase, unique(string(trace.relative_path)), relativePath);
verifyEqual(testCase, unique(string(trace.project_key)), ...
    projectSpec("dyadic").project_key);
verifyEqual(testCase, unique(string(trace.mapping_profile_key)), ...
    "example.project.social_dyad.multi_subject");
verifyEqual(testCase, unique(string(trace.mapping_version)), "0.1.0");
verifyEqual(testCase, unique(string(trace.mapping_checksum)), ...
    "2a89d9de5e2e2d0da9d4c1f02dd487875c93aa989fd26cac2c2b72063165aa43");
verifyEqual(testCase, unique(double(trace.ingestion_run_id)), ...
    result.ingestion_run_id);
verifyEqual(testCase, unique(string(trace.ingestion_status)), "completed");
verifyEqual(testCase, string(trace.link_type), ...
    ["context"; "participant"; "participant"]);
verifyEqual(testCase, string(trace.role_label), ...
    ["<empty>"; "female_partner"; "male_partner"]);
verifyEqual(testCase, string(trace.entity_type), ...
    ["session"; "animal"; "animal"]);
verifyEqual(testCase, string(trace.entity_native_id), ...
    ["courtship"; "F031"; "M012"]);

memberships = fetch(conn, ...
    "SELECT er.role_label, child.native_id " + ...
    "FROM entity_relationships er " + ...
    "JOIN experimental_entities child ON child.entity_id = " + ...
    "er.child_entity_id " + ...
    "WHERE er.relationship_type = 'has_member' ORDER BY er.role_label");
verifyEqual(testCase, string(memberships.role_label), ...
    ["female_partner"; "male_partner"]);
verifyEqual(testCase, string(memberships.native_id), ["F031"; "M012"]);
verifyEqual(testCase, scalar(conn, ...
    "SELECT COUNT(*) AS n FROM entity_relationships WHERE ingestion_run_id = " + ...
    string(result.ingestion_run_id)), 5);
verifyEqual(testCase, height(fetch(conn, "PRAGMA foreign_key_check")), 0);

clear cleanupRoot cleanupDb
rmpath(fullfile(repoRoot, "src"));
end

