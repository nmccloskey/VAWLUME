function verifyThreeExtractorPopulation(testCase, conn)
project = sqlText("phase1_synthetic_fixture");
usvseg = "SELECT COUNT(*) AS n FROM v_detection_core WHERE project_key = " + project + ...
    " AND extraction_run_key = 'fixture_usvseg_social_v1'";
verifyEqual(testCase, scalar(conn, usvseg), 6);
verifyEqual(testCase, scalar(conn, usvseg + " AND native_recording_id <> 'REC_SOCIAL_DYAD_01'"), 0);

% The interpretable geometry the three pairwise analyses depend on. Native
% event id plus extraction run key is the stable selector; detection_id is a
% surrogate and is deliberately not asserted here.
geometry = fetch(conn, ...
    "SELECT native_event_id, start_time_s, end_time_s FROM v_detection_core " + ...
    "WHERE project_key = " + project + ...
    " AND extraction_run_key = 'fixture_usvseg_social_v1' " + ...
    "ORDER BY CAST(native_event_id AS INTEGER)");
verifyEqual(testCase, string(geometry.native_event_id), ["1"; "2"; "3"; "4"; "5"; "6"]);
verifyEqual(testCase, double(geometry.start_time_s), ...
    [10.0020; 20.0010; 30.0010; 40.0010; 40.0500; 50.0000], AbsTol=1e-12);
verifyEqual(testCase, double(geometry.end_time_s), ...
    [10.0490; 20.0410; 30.0360; 40.0430; 40.0990; 50.0600], AbsTol=1e-12);

% One extraction-run-scoped native id identifies exactly one detection, so
% later agreement work can select fixture events without surrogate ids.
verifyEqual(testCase, scalar(conn, ...
    "SELECT COUNT(*) AS n FROM (SELECT extraction_run_key, native_event_id " + ...
    "FROM v_detection_core WHERE project_key = " + project + ...
    " GROUP BY extraction_run_key, native_event_id HAVING COUNT(*) > 1)"), 0);

% USVSEG exports seven measurement columns per syllable, no detection score,
% and no curation state. None of the absent quantities may be synthesized.
verifyEqual(testCase, scalar(conn, ...
    "SELECT COUNT(*) AS n FROM v_event_measurements_long vml " + ...
    "JOIN v_detection_core vc ON vc.detection_id = vml.detection_id " + ...
    "WHERE vc.project_key = " + project + ...
    " AND vc.extraction_run_key = 'fixture_usvseg_social_v1'"), 42);
verifyEqual(testCase, scalar(conn, ...
    "SELECT COUNT(DISTINCT vml.native_name) AS n FROM v_event_measurements_long vml " + ...
    "JOIN v_detection_core vc ON vc.detection_id = vml.detection_id " + ...
    "WHERE vc.project_key = " + project + ...
    " AND vc.extraction_run_key = 'fixture_usvseg_social_v1'"), 7);
verifyEqual(testCase, scalar(conn, ...
    "SELECT COUNT(*) AS n FROM detections d " + ...
    "JOIN extraction_runs er ON er.extraction_run_id = d.extraction_run_id " + ...
    "WHERE er.run_key = 'fixture_usvseg_social_v1' AND d.detection_score IS NOT NULL"), 0);
verifyEqual(testCase, scalar(conn, ...
    "SELECT COUNT(*) AS n FROM curation_events ce " + ...
    "JOIN detections d ON d.detection_id = ce.detection_id " + ...
    "JOIN extraction_runs er ON er.extraction_run_id = d.extraction_run_id " + ...
    "WHERE er.run_key = 'fixture_usvseg_social_v1'"), 0);
verifyEqual(testCase, scalar(conn, ...
    "SELECT COUNT(*) AS n FROM v_event_measurements_long vml " + ...
    "JOIN v_detection_core vc ON vc.detection_id = vml.detection_id " + ...
    "WHERE vc.project_key = " + project + ...
    " AND vc.extraction_run_key = 'fixture_usvseg_social_v1' " + ...
    "AND vml.canonical_name IN ('frequency_min', 'frequency_max', " + ...
    "'frequency_bandwidth', 'native_detection_score', 'inter_call_interval')"), 0);

% USVSEG has no run-scoped settings artifact, so the run's settings profile
% stays NULL and its only artifact is the summary CSV.
verifyEqual(testCase, scalar(conn, ...
    "SELECT COUNT(*) AS n FROM extraction_runs " + ...
    "WHERE run_key = 'fixture_usvseg_social_v1' AND settings_profile_version_id IS NULL"), 1);
usvsegArtifacts = fetch(conn, ...
    "SELECT a.artifact_type, a.native_artifact_type, a.is_native, era.artifact_role " + ...
    "FROM extraction_run_artifacts era " + ...
    "JOIN extraction_runs er ON er.extraction_run_id = era.extraction_run_id " + ...
    "JOIN artifacts a ON a.artifact_id = era.artifact_id " + ...
    "WHERE er.run_key = 'fixture_usvseg_social_v1'");
verifyEqual(testCase, height(usvsegArtifacts), 1);
verifyEqual(testCase, string(usvsegArtifacts.native_artifact_type(1)), "usvseg_dat_csv");
verifyEqual(testCase, double(usvsegArtifacts.is_native(1)), 0);

% Native print precision is preserved as evidence rather than reformatted.
tokens = fetch(conn, ...
    "SELECT vml.native_name, vml.native_raw_token FROM v_event_measurements_long vml " + ...
    "JOIN v_detection_core vc ON vc.detection_id = vml.detection_id " + ...
    "WHERE vc.project_key = " + project + ...
    " AND vc.extraction_run_key = 'fixture_usvseg_social_v1' " + ...
