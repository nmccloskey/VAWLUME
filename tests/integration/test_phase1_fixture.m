verifyEqual(testCase, string(tokens.native_name), ...
    ["cvfreq"; "duration"; "end"; "maxamp"; "maxfreq"; "meanfreq"; "start"]);
verifyEqual(testCase, string(tokens.native_raw_token), ...
    ["0.0640"; "47.0"; "10.0490"; "-18.4"; "71.200"; "62.100"; "10.0020"]);

% The stored matching analysis stays the DeepSqueak/MUPET pair. Adding a third
% extractor to the fixture does not silently widen a pairwise analysis.
verifyEqual(testCase, scalar(conn, ...
    "SELECT COUNT(*) AS n FROM analysis_run_extraction_inputs arei " + ...
    "JOIN analysis_runs ar ON ar.analysis_run_id = arei.analysis_run_id " + ...
    "WHERE ar.run_key = 'fixture_cross_extractor_matching_v1'"), 2);
verifyEqual(testCase, scalar(conn, ...
    "SELECT COUNT(*) AS n FROM candidate_pairs cp " + ...
    "JOIN analysis_runs ar ON ar.analysis_run_id = cp.analysis_run_id " + ...
    "JOIN detections d ON d.detection_id IN (cp.detection_a_id, cp.detection_b_id) " + ...
    "JOIN extraction_runs er ON er.extraction_run_id = d.extraction_run_id " + ...
    "WHERE er.run_key = 'fixture_usvseg_social_v1'"), 0);
end

