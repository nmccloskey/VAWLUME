function setup(testCase)
file = string(tempname) + ".sqlite";
conn = sqlite(char(file), "create");
vawlume.db.applySchema(conn, fullfile(testCase.TestData.repoRoot, ...
    "schema", "schema.sql"));
seedFixture(conn);
run = vawlume.attribution.createRun(conn, struct(recording_id=1), ...
    nominalRunSpec(), Apply=true);
testCase.TestData.conn = conn;
testCase.TestData.file = file;
testCase.TestData.run = run;
testCase.TestData.targetId = run.targets.attribution_target_id(1);
end

function teardown(testCase)
if isfield(testCase.TestData, "conn")
    close(testCase.TestData.conn);
end
if isfield(testCase.TestData, "file") && isfile(testCase.TestData.file)
    delete(testCase.TestData.file);
end
end

function testThreeCandidatesPersistAndNoneIsPrivileged(testCase)
conn = testCase.TestData.conn;
targetRef = struct(attribution_target_id=testCase.TestData.targetId);
candidates = nominalCandidates();

preview = vawlume.attribution.addCandidates(conn, targetRef, candidates);
verifyEqual(testCase, preview.status, "planned");
verifyFalse(testCase, preview.committed);
verifyEqual(testCase, countOf(conn, "attribution_candidates"), 0);

created = vawlume.attribution.addCandidates(conn, targetRef, ...
    candidates, Apply=true);
verifyEqual(testCase, created.status, "created");
verifyTrue(testCase, created.committed);
verifyEqual(testCase, created.applied_count, 3);
verifyFalse(testCase, isfield(created, "winner"));
verifyFalse(testCase, isfield(created, "best_caller"));

rows = fetch(conn, "SELECT entity_id, candidate_status, candidate_rank, " + ...
    "score, score_semantics, probability, probability_semantics, source_label " + ...
    "FROM attribution_candidates WHERE attribution_target_id=" + ...
    string(testCase.TestData.targetId) + " ORDER BY entity_id");
% Read all three rows and their values. A count would not prove that all are
% reachable through the public representation.
verifyEqual(testCase, double(rows.entity_id), [1; 2; 3]);
verifyEqual(testCase, string(rows.candidate_status), ...
    repmat("candidate", 3, 1));
verifyEqual(testCase, double(rows.candidate_rank), [1; 2; 2]);
verifyEqual(testCase, double(rows.score), [42.7; 10.0; 10.0], ...
    AbsTol=1e-12);
verifyEqual(testCase, string(rows.score_semantics), ...
    repmat(scoreSemantics(), 3, 1));
verifyEqual(testCase, double(rows.probability), [0.81; 0.12; 0.07], ...
    AbsTol=1e-12);
verifyEqual(testCase, string(rows.probability_semantics), ...
    repmat(probabilitySemantics(), 3, 1));
verifyEqual(testCase, string(rows.source_label), [" native A "; "B"; "C"]);
verifyEqual(testCase, countOf(conn, "attribution_decisions"), 0);
verifyEqual(testCase, countOf(conn, "attribution_decision_candidates"), 0);

runRows = fetch(conn, "SELECT atr.status AS attribution_status, " + ...
    "ar.status AS analysis_status FROM attribution_runs atr " + ...
    "JOIN analysis_runs ar ON ar.analysis_run_id=atr.analysis_run_id " + ...
    "WHERE atr.attribution_run_id=" + ...
    string(testCase.TestData.run.run.attribution_run_id));
verifyEqual(testCase, string(runRows.attribution_status), "planned");
verifyEqual(testCase, string(runRows.analysis_status), "started");
end

