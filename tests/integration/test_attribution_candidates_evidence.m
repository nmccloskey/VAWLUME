function value = candidateFingerprint(conn)
rows = fetch(conn, "SELECT attribution_candidate_id, entity_id, " + ...
    "candidate_rank, score, probability FROM attribution_candidates " + ...
    "ORDER BY attribution_candidate_id");
value = strjoin(compose("%d|%d|%d|%.17g|%.17g", ...
    double(rows.attribution_candidate_id), double(rows.entity_id), ...
    double(rows.candidate_rank), double(rows.score), ...
    double(rows.probability)), ";");
end

function text = attributionSourceText(repoRoot)
files = dir(fullfile(repoRoot, "src", "+vawlume", "+attribution", ...
    "**", "*.m"));
text = "";
for index = 1:numel(files)
    text = text + newline + ...
        string(fileread(fullfile(files(index).folder, files(index).name)));
end
end

function offenders = combinedDimensionArithmetic(text)
dimensions = ["temporal_alignment", "pose_localization", ...
    "visual_identity", "acoustic"];
lines = splitlines(text);
offenders = strings(0, 1);
for index = 1:numel(lines)
    code = regexprep(lines(index), "%.*$", "");
    named = dimensions(arrayfun(@(dimension) ...
        contains(code, dimension), dimensions));
    hasArithmetic = ~isempty(regexp(char(code), ...
        '[A-Za-z0-9_)]\s*[+*/-]\s*[A-Za-z_(]', 'once'));
    if numel(named) >= 2 && hasArithmetic
        offenders(end + 1, 1) = strtrim(code); %#ok<AGROW>
    end
end
end

