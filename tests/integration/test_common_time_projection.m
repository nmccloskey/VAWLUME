function value = alignmentRef()
value = struct(run_key="align", project_key="common_time_fixture");
end

function value = nativeFingerprint(conn)
value = struct(detections=fetch(conn, "SELECT detection_id,start_time_s,end_time_s " + ...
    "FROM detections ORDER BY detection_id"), ...
    consensus=fetch(conn, "SELECT consensus_event_id,start_time_s,end_time_s " + ...
    "FROM consensus_events ORDER BY consensus_event_id"), ...
    external=fetch(conn, "SELECT external_event_id,start_time_native," + ...
    "IFNULL(end_time_native,-1) AS end_time_native FROM external_events " + ...
    "ORDER BY external_event_id"), ...
    coverage=fetch(conn, "SELECT external_stream_coverage_id,start_time_native," + ...
    "end_time_native FROM external_stream_coverage ORDER BY external_stream_coverage_id"));
end

function value = rowCount(conn, tableName)
rows = fetch(conn, "SELECT COUNT(*) AS n FROM " + tableName);
value = double(rows.n(1));
end

function tearDown(conn, workspace, sourcePath)
if isopen(conn), close(conn); end
if isfolder(workspace), rmdir(workspace, "s"); end
rmpath(sourcePath);
end
