function testDetectionAndExternalEventsProjectWithoutMutation(testCase)
[fixture, cleanup] = setUpFixture(); %#ok<ASGLU>
before = nativeFingerprint(fixture.conn);
view = vawlume.alignment.commonTime(fixture.conn, alignmentRef(), ...
    VocalizationSource="detections", VocalizationRunId=1);

detection = view.events(view.events.event_source_kind == "detection", :);
verifyEqual(testCase, detection.native_start, [1; 2]);
verifyEqual(testCase, detection.aligned_start, [101.1; 102.2], AbsTol=1e-12);
verifyEqual(testCase, detection.alignment_kind, repmat("stored_transform", 2, 1));

video = view.events(view.events.source_stream_id == 1, :);
verifyEqual(testCase, video.aligned_start, [102; 140], AbsTol=1e-12);
verifyEqual(testCase, video.aligned_end(1), 104, AbsTol=1e-12);
verifyTrue(testCase, isnan(video.aligned_end(2)));

neural = view.events(view.events.source_stream_id == 2, :);
verifyEqual(testCase, neural.native_start, neural.aligned_start);
verifyEqual(testCase, neural.alignment_kind, "identity");
verifyTrue(testCase, isnan(neural.alignment_run_id));

videoCoverage = view.coverage(view.coverage.source_stream_id == 1, :);
verifyEqual(testCase, videoCoverage.aligned_start, [100; 140]);
verifyEqual(testCase, videoCoverage.aligned_end, [120; 160]);
verifyEqual(testCase, nativeFingerprint(fixture.conn), before);
verifyEqual(testCase, rowCount(fixture.conn, "aligned_external_events"), 0);
verifyEqual(testCase, rowCount(fixture.conn, "sequences"), 0);
verifyEqual(testCase, rowCount(fixture.conn, "sequence_members"), 0);
clear cleanup
end

