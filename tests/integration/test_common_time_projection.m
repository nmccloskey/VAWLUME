function testMixedTimelineUsesProjectedCoverage(testCase)
[fixture, cleanup] = setUpFixture(); %#ok<ASGLU>
view = vawlume.alignment.commonTime(fixture.conn, alignmentRef(), ...
    VocalizationSource="detections", VocalizationRunId=1);
channels = [struct(name="call_count", event_source_kind="detection", ...
    normalized_event_key="vocalization", coverage_key="recording:1", ...
    aggregation="onset_count"), ...
    struct(name="entry_present", event_source_kind="external_event", ...
    normalized_event_key="female_entry", coverage_key="external_stream:1", ...
    aggregation="any_overlap"), ...
    struct(name="ttl_count", event_source_kind="external_event", ...
    normalized_event_key="sync_marker", coverage_key="external_stream:2", ...
    aggregation="onset_count")];
result = vawlume.sequence.regularizeTimeline(view, channels, ...
    WindowStart=100, WindowEnd=162, BinWidth=2, BinOrigin=100);
verifyEqual(testCase, result.timeline.call_count(1:2), [1; 1]);
verifyEqual(testCase, result.timeline.entry_present(2), 1);
verifyEqual(testCase, result.timeline.entry_present(10), 0);
verifyTrue(testCase, isnan(result.timeline.entry_present(11)));
verifyFalse(testCase, result.timeline.entry_present_covered(11));
verifyEqual(testCase, result.timeline.ttl_count(6), 1);
clear cleanup
end

function testMissingTransformAndOutsideCoverageRaiseControlledErrors(testCase)
[fixture, cleanup] = setUpFixture(); %#ok<ASGLU>
execute(fixture.conn, "INSERT INTO external_events(external_stream_id, " + ...
    "native_event_id, event_type, start_time_native) " + ...
    "VALUES (1, 'outside', 'investigation', 15)");
verifyError(testCase, @() vawlume.alignment.commonTime( ...
    fixture.conn, alignmentRef()), ...
    "vawlume:alignment:EventOutsideCoverage");
execute(fixture.conn, "DELETE FROM external_events WHERE native_event_id='outside'");
execute(fixture.conn, "DELETE FROM alignment_segments WHERE alignment_run_id=2");
verifyError(testCase, @() vawlume.alignment.commonTime( ...
    fixture.conn, alignmentRef()), ...
    "vawlume:alignment:TransformSegmentMissing");
execute(fixture.conn, "INSERT INTO alignment_segments(alignment_run_id, " + ...
    "segment_index, scale, offset_s) VALUES (2,1,2,100)");
execute(fixture.conn, "UPDATE time_alignment_runs SET status='rejected' " + ...
    "WHERE alignment_run_id=2");
verifyError(testCase, @() vawlume.alignment.commonTime( ...
    fixture.conn, alignmentRef()), ...
    "vawlume:alignment:TransformNotUsable");
clear cleanup
end

function [fixture, cleanup] = setUpFixture()
repoRoot = string(fileparts(fileparts(fileparts(mfilename("fullpath")))));
sourcePath = fullfile(repoRoot, "src");
addpath(sourcePath);
workspace = fullfile(tempdir, "vawlume_common_time_" + ...
    string(java.util.UUID.randomUUID));
mkdir(workspace);
conn = sqlite(char(fullfile(workspace, "common_time.sqlite")), "create");
cleanup = onCleanup(@() tearDown(conn, workspace, sourcePath));
vawlume.db.applySchema(conn, fullfile(repoRoot, "schema", "schema.sql"));
seed(conn);
fixture = struct(conn=conn);
end

