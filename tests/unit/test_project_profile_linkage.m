function [ir, root] = parsedIR(repoRoot, profileId, relativePath)
root = string(tempname);
mkdir(root);
touchFile(fullfile(root, relativePath));
ir = vawlume.source_mapping.parse(projectProfilePath(repoRoot), root, ...
    ProfileId=profileId, RepoRoot=repoRoot);
end

function value = projectSpec()
