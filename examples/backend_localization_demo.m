function demonstration = backend_localization_demo(options)
%BACKEND_LOCALIZATION_DEMO Demonstrate the integrated Phase 5 backend/localization path.
%
% DEMONSTRATION = BACKEND_LOCALIZATION_DEMO() creates a disposable synthetic
% session and carries a localization backend's export through the whole
% attribution path: a recording with participating entities, two microphone
% channels, and a coordinate system shared with the tracking data; a backend
% export on the backend's own clock, previewed before it is imported; a fitted
% piecewise transform relating that clock to the recording's; correspondence
% across it; localization estimates with their frames; explicit promotion of the
% backend's caller scores into candidates and of its estimate, per-channel value
% and track reference into evidence; all five evidence dimensions side by side
% with no combined value; and a decision for every status the vocabulary has.
%
% A second, structurally different backend -- 3D, localization only, several
% ranked sources per window, covariance instead of a scalar confidence -- is
% imported over the same recording and read back through the same function, so
% optional z is visible both absent and present.
%
% The refusals are demonstrated beside the successes, in a harness that fails
% the example if a refusal stops refusing: an evidence row citing an estimate
% without declaring its frame, a backend export naming another project's frame,
% a caller label resolving outside the run's participants, a correspondence with
% no clock declaration, and a second apply.
%
% Nothing here is calibrated and nothing is validated. Every number is
% synthetic, both backends are invented, VAWLUME computes no distance and
% estimates no caller, and no result is evidence that any animal called. All
% inputs are created under the system temporary directory and removed before
% return.
%
% Name-value options:
%   Print     print compact developer-facing read-backs (default true)
%   RepoRoot  repository root, inferred from this file by default
%
% See also CALLER_ATTRIBUTION_DEMO, MULTIMODAL_INTEGRATION_DEMO

arguments
    options.Print (1,1) logical = true
    options.RepoRoot (1,1) string = ""
end

repoRoot = normalizedRepoRoot(options.RepoRoot);
sourcePath = fullfile(repoRoot, "src");
removeSourcePath = ~pathContains(sourcePath);
if removeSourcePath, addpath(sourcePath); end
cleanupPath = onCleanup(@() restoreSourcePath(sourcePath, removeSourcePath));

workspace = fullfile(tempdir, "VAWLUME phase 5 backend localization demo " + ...
    string(java.util.UUID.randomUUID));
mkdir(workspace);
cleanupWorkspace = onCleanup(@() removeTree(workspace));
databasePath = fullfile(workspace, "backend_localization_demo.sqlite");
conn = sqlite(char(databasePath), "create");
cleanupConnection = onCleanup(@() closeConnection(conn));

vawlume.db.applySchema(conn, fullfile(repoRoot, "schema", "schema.sql"));
vawlume.db.registerBuiltinSemantics(conn, repoRoot);

session = seedSession(conn, workspace);
geometry = declareGeometry(conn);
backendClock = establishBackendClock(conn, workspace, repoRoot);
tracking = registerTracking(conn, workspace, repoRoot);
profilePath = writeBackendProfile(workspace, repoRoot, "arena_2d", "demo");

refusals = emptyRefusals();

% --- Run 1: the caller-scoring backend, on its own clock ----------------------

mainRun = createRun(conn, session, "session01-backend", ...
    "Synthetic Localization Backend 1.0.0");

[refusals, ~] = recordRefusal(refusals, ...
    "a backend export whose positions name a frame declared only for another project", ...
    @() vawlume.ingest.backendAttribution(conn, runRef("session01-backend"), ...
        writeExport(workspace), RepoRoot=repoRoot, Apply=true, ...
        ProfilePath=writeBackendProfile(workspace, repoRoot, "other_lab_arena", ...
            "foreign-frame")));
[refusals, ~] = recordRefusal(refusals, ...
    "a backend caller label resolving to an animal outside the run's participants", ...
    @() vawlume.ingest.backendAttribution(conn, runRef("session01-backend"), ...
        writeOutsiderExport(workspace), ProfilePath=profilePath, ...
        RepoRoot=repoRoot, Apply=true));

exportPath = writeExport(workspace);
importPreview = vawlume.ingest.backendAttribution(conn, runRef("session01-backend"), ...
    exportPath, ProfilePath=profilePath, RepoRoot=repoRoot);
importResult = vawlume.ingest.backendAttribution(conn, runRef("session01-backend"), ...
    exportPath, ProfilePath=profilePath, RepoRoot=repoRoot, Apply=true);

[refusals, ~] = recordRefusal(refusals, ...
    "a second apply of the same backend export to the same run", ...
    @() vawlume.ingest.backendAttribution(conn, runRef("session01-backend"), ...
        exportPath, ProfilePath=profilePath, RepoRoot=repoRoot, Apply=true));
[refusals, ~] = recordRefusal(refusals, ...
    "a correspondence that did not say how the backend's clock relates to the recording's", ...
    @() vawlume.attribution.correspondWindows(conn, runRef("session01-backend")));

correspondence = vawlume.attribution.correspondWindows(conn, runRef("session01-backend"), ...
    AlignmentRun=backendClock.alignment_run_id, RepoRoot=repoRoot, Apply=true);

candidates = promoteClaimsToCandidates(conn, mainRun.target_ids);
anchorCandidate = candidateFor(conn, mainRun.target_ids(1), 1);
estimateId = estimateFor(conn, mainRun.attribution_run_id, "b1");

[refusals, ~] = recordRefusal(refusals, ...
    "a source-localization evidence row citing an estimate without declaring its frame", ...
    @() vawlume.attribution.addEvidence(conn, ...
        struct(attribution_candidate_id=anchorCandidate), ...
        struct(evidence_dimension="source_localization", ...
            evidence_kind="backend_source_location", ...
            attribution_localization_estimate_id=estimateId), Apply=true));

evidence = addFiveDimensionEvidence(conn, anchorCandidate, estimateId, ...
    mainRun, backendClock, tracking);

decision = vawlume.attribution.decide(conn, runRef("session01-backend"), struct(), ...
    RepoRoot=repoRoot, Apply=true, Targets=mainRun.target_ids(1:5));
mainReport = vawlume.attribution.report(conn, runRef("session01-backend"));

% --- Run 2: a structurally different backend over the same recording -----------

arrayRun = createRun(conn, session, "session01-array", "Synthetic Array Localizer 0.3");
arrayImport = vawlume.ingest.backendAttribution(conn, runRef("session01-array"), ...
    writeArrayExport(workspace), RepoRoot=repoRoot, Apply=true, ...
    ProfilePath=fullfile(repoRoot, "config", "01_mapping_profiles", "attribution", ...
        "generic_array_backend_attribution_profile.json"));
arrayCorrespondence = vawlume.attribution.correspondWindows(conn, ...
    runRef("session01-array"), SameClock=true, RepoRoot=repoRoot, Apply=true);
arrayReport = vawlume.attribution.report(conn, runRef("session01-array"));

% --- Read-back, QC and the boundaries -------------------------------------------

inventory = databaseInventory(conn);
foreignKeyCheck = fetch(conn, "PRAGMA foreign_key_check");

demonstration = struct( ...
    calibration_boundary="Every coordinate, confidence, score and threshold here " + ...
        "is a synthetic illustrative value from an invented backend. VAWLUME " + ...
        "computes no distance, transforms no frame, estimates no caller, and no " + ...
        "decision below means an animal called.", ...
    session=session, geometry=geometry, backend_clock=backendClock, ...
    tracking=tracking, ...
    main_run=struct(attribution_run_id=mainRun.attribution_run_id, ...
        target_count=numel(mainRun.target_ids)), ...
    import_preview=struct(status=importPreview.status, ...
        wrote_nothing=~importPreview.committed, ...
        window_count=height(importPreview.windows), ...
        claim_count=height(importPreview.claims), ...
        estimate_count=height(importPreview.estimates), ...
        unmapped_rows=importPreview.unmapped_rows, ...
        issues=importPreview.issues, ...
        resolutions=importPreview.resolutions), ...
    import=struct(status=importResult.status, ...
        applied_counts=importResult.applied_counts, ...
        exporting_system=importResult.exporting_system, ...
        profile=importResult.profile, ...
        source_checksum=importResult.source.checksum_sha256, ...
        not_written=importResult.not_written), ...
    correspondence=struct(iou_basis=correspondence.iou_basis, ...
        alignment_run_id=correspondence.alignment_run_id, ...
        rows=correspondence.correspondences(:, ["native_window_id", ...
            "attribution_target_id", "iou_basis", "aligned_start_s", ...
            "aligned_end_s", "temporal_iou"])), ...
    candidates=candidates, evidence=evidence, ...
    decisions=struct(rows=decision.decisions(:, ["attribution_target_id", ...
            "decision_status", "applied_threshold", "selected_count"]), ...
        run_completed=decision.run_completed), ...
    main_report=compactReport(mainReport), ...
    array_run=struct(attribution_run_id=arrayRun.attribution_run_id, ...
        import_status=arrayImport.status, ...
        applied_counts=arrayImport.applied_counts, ...
        correspondence_count=height(arrayCorrespondence.correspondences)), ...
    array_report=compactReport(arrayReport), ...
    same_read_surface=isequal(sort(string(fieldnames(mainReport))), ...
        sort(string(fieldnames(arrayReport)))), ...
    refusals=refusals, ...
    separation=struct(combined_value_computed=false, caller_estimated=false, ...
        distance_computed=false, ...
        evidence_dimensions_present=height(mainReport.qc.evidence_by_dimension), ...
        note="Five evidence dimensions -- temporal alignment, pose " + ...
            "localization, visual identity, acoustic and source localization -- " + ...
            "are stored, read and displayed side by side with their own units " + ...
            "and semantics. Nothing here combines them, and the decision policy " + ...
            "reads one candidate column and no evidence row."), ...
    database_inventory=inventory, foreign_key_check=foreignKeyCheck, ...
    proves=["a localization backend's export lands in the same canonical " + ...
        "attribution representation as an imported one, through one intake " + ...
        "function and one read surface"; ...
        "a localization estimate is stored once, in a declared frame, keyed " + ...
        "to the backend's own window, and reaches a target only by explicit " + ...
        "promotion"; ...
        "the backend's coordinates, confidences and scores keep their values, " + ...
        "their semantics and their producer"; ...
        "a backend window reaches a VAWLUME event only through a declared clock"; ...
        "five evidence dimensions sit on one candidate and nothing combines them"; ...
        "two structurally different backends read back through the same fields"; ...
        "the path refuses by name where guessing would look like success"], ...
    does_not_prove=["that any localized source was an animal, or the right one"; ...
        "that any backend's coordinates, confidences or scores are accurate or calibrated"; ...
        "that any real backend's export maps: both backends here are invented"; ...
        "that the backend and the tracker measured in the frame they both cite"; ...
        "that any caller was estimated: VAWLUME estimates none"; ...
        "that this representation is legible at realistic session scale"], ...
    temporary_artifacts_removed=false);

close(conn);
clear cleanupConnection
removeTree(workspace);
clear cleanupWorkspace
demonstration.temporary_artifacts_removed = ...
    ~isfolder(workspace) && ~isfile(databasePath);

if options.Print, printDemonstration(demonstration); end
clear cleanupPath
end

