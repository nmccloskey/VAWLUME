function value = promoteClaimsToCandidates(conn, targetIds)
%PROMOTECLAIMSTOCANDIDATES The explicit step from a backend claim to a candidate.
%
% A claim belongs to (backend window, entity); a candidate to (VAWLUME target,
% entity). Here every claim over a window that corresponds to a target becomes a
% candidate of that target, with the backend's number and semantics copied
% unchanged. That rule is THIS demonstration's choice -- a policy decision the
% caller makes -- which is why VAWLUME never makes it implicitly.
perTarget = table(zeros(0,1), zeros(0,1), VariableNames=["attribution_target_id", ...
    "candidate_count"]);
for target = targetIds
    claims = fetch(conn, "SELECT cl.entity_id AS entity_id, " + ...
        "IFNULL(cl.score,-999.0) AS score, IFNULL(cl.score_semantics,'') AS semantics, " + ...
        "cl.source_caller_label AS label FROM imported_attribution_claims cl " + ...
        "JOIN attribution_window_correspondences wc " + ...
        "ON wc.imported_attribution_window_id = cl.imported_attribution_window_id " + ...
        "WHERE wc.attribution_target_id=" + string(target) + " ORDER BY cl.entity_id");
    if height(claims) == 0
        perTarget(end + 1, :) = {target, 0}; %#ok<AGROW>
        continue
    end
    scored = double(claims.score) ~= -999.0;
    if all(scored)
        batch = table(double(claims.entity_id), double(claims.score), ...
            string(claims.semantics), string(claims.label), ...
            VariableNames=["entity_id", "score", "score_semantics", "source_label"]);
    else
        batch = table(double(claims.entity_id), string(claims.label), ...
            VariableNames=["entity_id", "source_label"]);
    end
    vawlume.attribution.addCandidates(conn, struct(attribution_target_id=target), ...
        batch, Apply=true);
    perTarget(end + 1, :) = {target, height(batch)}; %#ok<AGROW>
end
value = struct(per_target=perTarget, ...
    note="Candidates were promoted explicitly from the backend's claims; " + ...
        "neither intake nor correspondence created one.");
end

