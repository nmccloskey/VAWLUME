% ============================================================ backend clock ===

function value = establishBackendClock(conn, workspace, repoRoot)
%ESTABLISHBACKENDCLOCK Relate the backend's clock to the recording's.
%
% The Phase 4 demonstration's recipe: synchronization anchors observed on both
% clocks, a manifest, intake, and a piecewise-affine fit through the public
% alignment layer. Attribution reaches the result only through that layer.
truth = backendClockTruth();
writeAnchorTable(fullfile(workspace, "sync_anchors.csv"), truth);
anchorProfilePath = writeAnchorProfile(workspace, repoRoot);
manifestPath = writeManifest(workspace, anchorProfilePath);
vawlume.ingest.alignment(conn, manifestPath, RepoRoot=repoRoot, ...
    SourceRoot=workspace, Apply=true);
fitResult = vawlume.alignment.fit(conn, alignmentRef(), ...
    SourceTimebase="backend_native", Breakpoints=truth.breakpoint, Apply=true);
qc = vawlume.alignment.report(conn, alignmentRef());
transform = qc.transforms(qc.transforms.source_timebase_key == "backend_native", :);
value = struct(source_timebase="backend_native", ...
    reference_timebase=string(qc.reference_timebase.timebase_key(1)), ...
    alignment_run_id=double(transform.alignment_run_id(1)), ...
    method=string(transform.method(1)), status=string(transform.status(1)), ...
    fit_status=string(fitResult.status), breakpoint=truth.breakpoint, ...
    note="A fitted transform is estimated, never validated.");
end

function truth = backendClockTruth()
truth = struct();
truth.breakpoint = 35;
truth.scale = [1.002; 0.998];
truth.offset_s = [5.00; (truth.scale(1) - truth.scale(2)) * truth.breakpoint + 5.00];
truth.source_times = [3; 15; 25; 35; 45; 60];
segment = 1 + double(truth.source_times >= truth.breakpoint);
truth.reference_times = truth.scale(segment) .* truth.source_times + truth.offset_s(segment);
truth.anchor_keys = "sync" + compose("%02d", (1:numel(truth.source_times))');
end

function writeAnchorTable(pathValue, truth)
count = numel(truth.anchor_keys);
markers = strings(2 * count, 1);
streams = strings(2 * count, 1);
timestamps = strings(2 * count, 1);
row = 0;
for index = 1:count
    row = row + 1;
    markers(row) = truth.anchor_keys(index);
    streams(row) = "backend";
    timestamps(row) = compose("%.9f", truth.source_times(index));
    row = row + 1;
    markers(row) = truth.anchor_keys(index);
    streams(row) = "audio";
    timestamps(row) = compose("%.9f", truth.reference_times(index));
end
writetable(table(markers, streams, timestamps, repmat("primary", 2 * count, 1), ...
    repmat("true", 2 * count, 1), repmat("device_level", 2 * count, 1), ...
    VariableNames=["marker", "stream", "timestamp_s", "role", "include", ...
    "evidence_class"]), pathValue, QuoteStrings="minimal");
end

