function value = addFiveDimensionEvidence(conn, candidateId, estimateId, run, clock, tracking)
%ADDFIVEDIMENSIONEVIDENCE Five dimensions, five rows, and no sixth combined row.
%
% Three rows promote backend material stored at intake: the source localization
% cites its estimate; the acoustic row is the backend's folded per-channel value,
% now naming its recording channel; the visual-identity row cites the association
% the backend's track reference was checked against. The temporal-alignment and
% pose rows come from VAWLUME's own upstream layers, as in Phase 4.
channel = fetch(conn, "SELECT a.value_real AS value, a.unit AS unit, " + ...
    "a.source_locator AS locator, s.value_text AS semantics " + ...
    "FROM attribution_native_attributes a JOIN attribution_native_attributes s " + ...
    "ON s.imported_attribution_window_id = a.imported_attribution_window_id " + ...
    "AND s.attribute_name = a.attribute_name || ':semantics' " + ...
    "JOIN imported_attribution_windows w ON w.imported_attribution_window_id = a.imported_attribution_window_id " + ...
    "WHERE w.attribution_run_id=" + string(run.attribution_run_id) + ...
    " AND w.native_window_id='b1' AND a.attribute_name='channel:1:backend_channel_power'");
channelId = fetch(conn, "SELECT recording_channel_id AS id FROM recording_channels " + ...
    "WHERE recording_id=1 AND channel_index=1");
ref = struct(attribution_candidate_id=candidateId);
rows = { ...
    struct(evidence_dimension="temporal_alignment", evidence_kind="propagated_bound", ...
        value_real=0.0020, value_units="s", ...
        value_semantics="Largest contributing anchor uncertainty on the reference clock; uncalibrated; not a confidence interval", ...
        alignment_run_id=clock.alignment_run_id)
    struct(evidence_dimension="pose_localization", evidence_kind="keypoint_confidence", ...
        value_real=0.7300, value_units="upstream_score", ...
        value_semantics="Tracker-exported snout keypoint localization confidence; producer=Tracker X; uncalibrated; where a bodypart is, not where a sound came from", ...
        source_locator="tracking.csv#time=10.0")
    struct(evidence_dimension="visual_identity", evidence_kind="reidentification_similarity", ...
        value_real=0.55, value_units="cosine_similarity", ...
        value_semantics="Appearance-embedding cosine similarity behind the backend's track_a reference; producer=ReID X; uncalibrated", ...
        identity_statement_kind="identity_association", ...
        tracking_identity_association_id=tracking.association_id)
    struct(evidence_dimension="acoustic", evidence_kind="backend_channel_power", ...
        value_real=double(channel.value(1)), value_units=string(channel.unit(1)), ...
        value_semantics=string(channel.semantics(1)), ...
        recording_channel_id=double(channelId.id(1)), ...
        source_locator=string(channel.locator(1)))
    struct(evidence_dimension="source_localization", evidence_kind="backend_source_location", ...
        attribution_localization_estimate_id=estimateId, coordinate_system_key="arena_2d")};
for index = 1:numel(rows)
    vawlume.attribution.addEvidence(conn, ref, rows{index}, Apply=true);
end
display = fetch(conn, "SELECT ev.evidence_dimension AS evidence_dimension, " + ...
    "ev.evidence_kind AS evidence_kind, " + ...
    "IFNULL(ev.value_real, -999.0) AS value_real, " + ...
    "IFNULL(ev.value_units, cs.unit) AS units, " + ...
    "IFNULL(rc.channel_label, '') AS channel, " + ...
    "IFNULL(cs.coordinate_system_key, '') AS frame, " + ...
    "IFNULL(le.position_x, -999.0) AS x, IFNULL(le.position_y, -999.0) AS y, " + ...
    "IFNULL(le.confidence, -999.0) AS confidence, " + ...
    "IFNULL(ev.value_semantics, le.position_semantics) AS semantics " + ...
    "FROM attribution_evidence ev " + ...
    "LEFT JOIN recording_channels rc ON rc.recording_channel_id = ev.recording_channel_id " + ...
    "LEFT JOIN attribution_localization_estimates le " + ...
    "ON le.attribution_localization_estimate_id = ev.attribution_localization_estimate_id " + ...
    "LEFT JOIN coordinate_systems cs ON cs.coordinate_system_id = le.coordinate_system_id " + ...
    "WHERE ev.attribution_candidate_id=" + string(candidateId) + ...
    " ORDER BY ev.attribution_evidence_id");
for name = ["value_real", "x", "y", "confidence"]
    values = double(display.(name));
    values(values == -999.0) = NaN;
    display.(name) = values;
end
for name = ["channel", "frame", "units", "semantics"]
    values = string(display.(name));
    values(ismissing(values)) = "";
    display.(name) = values;
end
confidenceSemantics = fetch(conn, "SELECT confidence_semantics AS s " + ...
    "FROM attribution_localization_estimates WHERE attribution_localization_estimate_id=" + ...
    string(estimateId));
value = struct(applied_count=numel(rows), ...
    display=display(:, ["evidence_dimension", "evidence_kind", "value_real", ...
        "units", "channel", "frame", "x", "y", "confidence"]), ...
    semantics=display(:, ["evidence_dimension", "semantics"]), ...
    confidence_semantics=string(confidenceSemantics.s(1)), ...
    combined_value_present=false, ...
    note="Five rows on five scales. The source-localization row carries no " + ...
        "value of its own; its position, frame and confidence are the estimate's.");
end

