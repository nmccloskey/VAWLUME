first = fetch(conn, "SELECT MIN(d.policy_profile_version_id) AS id FROM attribution_decisions d " + ...
    "JOIN attribution_targets g ON g.attribution_target_id = d.attribution_target_id " + ...
    "WHERE g.attribution_run_id=" + string(nativeId));
referencePolicy = double(first.id(1));
refusals = emptyRefusals();
refusals = recordRefusal(refusals, "a score comparison across paths (imported against native)", ...
    "vawlume:attribution:ScoreNotComparable", ...
    @() compareRuns(conn, m, "imported", "native_detections", ...
        RightPolicy=referencePolicy, CompareScores=true));
