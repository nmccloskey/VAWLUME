    "a native-score comparison across settings-profile versions", ...
    "vawlume:attribution:ScoreNotComparable", ...
    @() vawlume.attribution.compare(conn, struct(attribution_run_id=nativeId), ...
        struct(attribution_run_id=settingsVariant), LeftPolicy=referencePolicy, ...
        CompareScores=true));
refusals = recordRefusal(refusals, ...
    "a comparison across event sets with no named analysis", ...
    "vawlume:attribution:CorrespondenceAnalysisRequired", ...
    @() vawlume.attribution.compare(conn, allRuns.ds, allRuns.mupet));

% A fresh native run with one target and no candidate, so each probe reaches its
% rule for its own reason (as test_canonical_write_enforcement does).
settings = vawlume.estimator.loadSettings(RepoRoot=repoRoot);
created = vawlume.attribution.createRun(conn, struct(recording_id=m.recording_id), struct( ...
    run_key="p716-native-refusal-probe", attribution_path="native_estimate", ...
    method="vawlume.estimator.level_difference_consistency 1.0.0", ...
    settings_profile_version_id=m.profiles.estimator_settings_version_id, ...
