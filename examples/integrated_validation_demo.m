function value = emptyRefusals()
value = table('Size', [0 4], 'VariableTypes', ["string", "string", "string", "string"], ...
    'VariableNames', ["what_was_attempted", "expected_identifier", "identifier", "message"]);
end

function refusals = recordRefusal(refusals, description, expected, action)
%RECORDREFUSAL Exercise a path that must refuse, and check WHICH refusal fired.
%
% If the action succeeds, or fails under any other identifier, the example
% fails: a refusal that stopped refusing, or one that now refuses for another
% reason, is a regression, and showing it as a success would teach the opposite.
try
    action();
    error("vawlume:examples:RefusalNotRaised", "Expected a refusal for: %s", description);
catch exception
    if exception.identifier == "vawlume:examples:RefusalNotRaised"
        rethrow(exception);
    end
    if exception.identifier ~= expected
        error("vawlume:examples:RefusalIdentifierChanged", ...
            "Expected %s for: %s; got %s (%s)", expected, description, ...
            exception.identifier, exception.message);
    end
    captured = exception;
end
refusals = [refusals; table(string(description), string(expected), ...
    string(captured.identifier), firstSentence(captured.message), VariableNames=[ ...
    "what_was_attempted", "expected_identifier", "identifier", "message"])];
end

function value = firstSentence(message)
value = string(message);
stop = strfind(value, ". ");
if ~isempty(stop)
    value = extractBefore(value, stop(1) + 1);
end
end

