function demonstration = integrated_validation_demo(options)
%INTEGRATED_VALIDATION_DEMO Demonstrate Phase 7's integrated validation on one synthetic session.
%
% Status: experimental (usage guide, "Status of public functions").
%
% DEMONSTRATION = INTEGRATED_VALIDATION_DEMO() builds the shared integrated
% fixture (vawlume.db.buildIntegratedFixture: one recording, three extractors,
% three attribution paths) in a disposable folder and carries it through every
% Phase 7 public function, composing them and computing nothing itself:
%
%   * the scene: each path's run, and each read-back table's grain beside its
%     row count;
%   * cross-path comparison (vawlume.attribution.compare): imported, backend and
%     native on shared targets, with a disagreement reported as disagreement,
%     imported "simultaneous" against native shown as a structural empty, and
%     the imported run's declared inputs shown as unknown;
%   * cross-event-set comparison: native runs over every DeepSqueak, MUPET and
%     USVSEG detection and every consensus event, joined only through a NAMED
%     stored analysis, with a one_to_many (split), a many_to_one (merge) and an
%     unmatched unit printed with the splitting side named;
%   * attribution-side sensitivity (vawlume.eda.attributionSensitivity): one
%     variant per handle against a reference declared up front, including a
%     generated tone-family normalization and an alignment variant whose
%     out-of-bracket call carries bracket_extrapolated = true, plus the handles
%     method 1.0.0 does not let vary, as rows;
%   * upstream sensitivity (vawlume.eda.correspondenceSensitivity): a temporal
%     matching variant that moves the event sets, and a spectral one that moves
%     none of them;
%   * QC facts (vawlume.estimator.qcFacts) for the separable, symmetric,
%     out-of-range and model-mismatch scenes, with the undetectable-class
%     statement;
%   * the integrated database exported as a CSV package (vawlume.export.database),
%     its manifest and counts printed and a strict read checked against SQLite.
%
% The refusals are demonstrated in a harness that fails the example if a
% refusal stops refusing OR refuses under another identifier: a value
% comparison across paths, a native-score comparison across settings versions,
% a cross-event-set comparison with no named analysis, a hand-written
% probability on a native candidate (invariant 24), and a label-only pose row on
% a native run (invariant 26).
%
% EVERYTHING IS SYNTHETIC AND CIRCULAR. The fixture wrote every path's input, so
% agreement between paths shows that the machinery joins correctly, never that
% any path is accurate. Sensitivity selects nothing. No score is a probability.
% All files are created under the system temporary directory and removed before
% return.
%
% Name-value options:
%   Print     print compact developer-facing read-backs (default true)
%   RepoRoot  repository root, inferred from this file by default
%
% See also NATIVE_ESTIMATOR_DEMO, BACKEND_LOCALIZATION_DEMO,
% VAWLUME.ATTRIBUTION.COMPARE, VAWLUME.EDA.SENSITIVITYSUMMARY

arguments
    options.Print (1,1) logical = true
    options.RepoRoot (1,1) string = ""
end

repoRoot = normalizedRepoRoot(options.RepoRoot);
sourcePath = fullfile(repoRoot, "src");
removeSourcePath = ~pathContains(sourcePath);
if removeSourcePath, addpath(sourcePath); end
cleanupPath = onCleanup(@() restoreSourcePath(sourcePath, removeSourcePath));

workspace = string(fullfile(tempdir, "VAWLUME phase 7 integrated validation demo " + ...
    string(java.util.UUID.randomUUID)));
mkdir(workspace);
cleanupWorkspace = onCleanup(@() removeTree(workspace));

[fixture, cleanupFixture] = vawlume.db.buildIntegratedFixture( ...
    Root=fullfile(workspace, "fixture"), RepoRoot=repoRoot);
conn = fixture.conn;
m = fixture.manifest;
policyPath = fullfile(repoRoot, "config", "08_attribution_policies", ...
    "native_level_difference_decision_policy.json");
nativeBefore = nativeCounts(conn);

% --- The scene -----------------------------------------------------------------

scene = sceneSummary(conn, m);

% --- Cross-path comparison -----------------------------------------------------

paths = crossPath(conn, m);

% --- Cross-event-set comparison --------------------------------------------------

allRuns = struct( ...
    ds=allEventRun(conn, m, repoRoot, policyPath, "p716-native-ds-all", ...
        "detection_ids", detectionsOf(conn, "p7-ds")), ...
    mupet=allEventRun(conn, m, repoRoot, policyPath, "p716-native-mupet-all", ...
        "detection_ids", detectionsOf(conn, "p7-mupet")), ...
    usvseg=allEventRun(conn, m, repoRoot, policyPath, "p716-native-usvseg-all", ...
        "detection_ids", detectionsOf(conn, "p7-usvseg")), ...
    consensus=allEventRun(conn, m, repoRoot, policyPath, "p716-native-consensus-all", ...
        "consensus_event_ids", consensusOf(conn, m.correspondence.consensus_source.analysis_run_id)));
eventSets = crossEventSet(conn, m, allRuns);

% --- Attribution-side sensitivity ------------------------------------------------

offsetRun = offsetAudioFit(conn, fixture.root, repoRoot, m.project_key);
familySpec = attributionFamily(fixture, m, policyPath, offsetRun, workspace);
before = state(conn);
attributionPlan = vawlume.eda.attributionSensitivity(conn, familySpec, Print=false, ...
    RepoRoot=repoRoot);
attributionPlanWroteNothing = isequal(state(conn), before);
attributionApplied = vawlume.eda.attributionSensitivity(conn, familySpec, Apply=true, ...
    Print=false, RepoRoot=repoRoot);
attributionSummary = vawlume.eda.sensitivitySummary(conn, ...
    struct(analysis_run_id=attributionApplied.family_analysis_run_id));
attribution = attributionDisplay(conn, m, attributionPlan, attributionPlanWroteNothing, ...
    attributionApplied, attributionSummary, offsetRun);

% --- Upstream (matching-side) sensitivity ----------------------------------------

matchingSpec = matchingFamily(fixture, m, policyPath, workspace);
before = state(conn);
matchingPlan = vawlume.eda.correspondenceSensitivity(conn, matchingSpec, Print=false, ...
    RepoRoot=repoRoot);
matchingPlanWroteNothing = isequal(state(conn), before);
matchingApplied = vawlume.eda.correspondenceSensitivity(conn, matchingSpec, Apply=true, ...
    Print=false, RepoRoot=repoRoot);
matchingSummary = vawlume.eda.sensitivitySummary(conn, ...
    struct(analysis_run_id=matchingApplied.family_analysis_run_id));
matching = matchingDisplay(matchingPlan, matchingPlanWroteNothing, matchingSummary);

% --- QC facts --------------------------------------------------------------------

qc = qcDisplay(conn, m);

% --- Refusals --------------------------------------------------------------------

refusals = demonstrateRefusals(conn, m, allRuns, attributionApplied, repoRoot);

% --- Export ----------------------------------------------------------------------

exported = exportAndRead(conn, fixture.database_path, fullfile(workspace, "export"), m);

nativeAfter = nativeCounts(conn);
demonstration = struct( ...
    calibration_boundary="Every value here is synthetic and was written by the " + ...
        "fixture builder. Agreement between paths on this fixture is circular: it " + ...
        "shows that the machinery joins correctly, never that any path is accurate. " + ...
        "No score is a probability, and sensitivity selects nothing.", ...
    scene=scene, ...
    cross_path=paths, ...
    cross_event_set=eventSets, ...
    attribution_sensitivity=attribution, ...
    matching_sensitivity=matching, ...
    qc_facts=qc, ...
    refusals=refusals, ...
    export=exported, ...
    native_rows_unchanged=isequal(nativeAfter.rows, nativeBefore.rows), ...
    foreign_key_check=fetch(conn, "PRAGMA foreign_key_check"), ...
    proves=["three attribution paths on one recording read back through one " + ...
        "result structure and compare target by target, with a disagreement " + ...
        "reported as one, a status a path cannot produce kept as a structural " + ...
        "empty, and an undeclared input kept as unknown"; ...
        "runs over different event sets meet only through a named stored " + ...
        "analysis, and a split, a merge and an unmatched target each keep their " + ...
        "own category"; ...
        "a declared input of a native run, or the matching configuration, varies " + ...
        "one at a time as ordinary runs recorded as one family against a " + ...
        "reference declared up front, and the summary counts what moved"; ...
        "handles method 1.0.0 cannot vary are reported as rows, not as gaps"; ...
        "the native method's margin is stated per call, and the class of failure " + ...
        "it cannot see is stated beside it"; ...
        "the integrated database exports as a faithful CSV package"; ...
        "every comparison that would need a value across a scale boundary, or a " + ...
        "join nobody stored, is refused by name"], ...
    does_not_prove=["that any path, variant or setting is right: every agreement " + ...
        "here is circular, because one builder wrote every path's input"; ...
        "that any animal called, or that any assigned animal did"; ...
        "that sensitivity selects anything: no variant is better than another, " + ...
        "and moving or not moving is not evidence of correctness"; ...
        "that the model-mismatch failure is detectable: the QC facts state the " + ...
        "margin, and the wrong animal still looks ordinary"; ...
        "anything on real data: no real paired session, tracking, geometry or " + ...
        "ground truth for who called exists. Real-data acceptance (7.14-7.14b) " + ...
        "used four right-microphone recordings with no tracking, where native " + ...
        "attribution was refused as not applicable"; ...
        "that a disagreement between paths could arise that the fixture did not " + ...
        "author: every disagreement shown was constructed"], ...
    temporary_artifacts_removed=false);

clear cleanupFixture
removeTree(workspace);
clear cleanupWorkspace
demonstration.temporary_artifacts_removed = ~isfolder(workspace);

if options.Print, printDemonstration(demonstration); end
clear cleanupPath
end

% ================================================================== scene ===

function value = sceneSummary(conn, m)
runs = ["imported", "backend", "native_detections", "native_consensus"];
rows = table();
for name = runs
    report = vawlume.attribution.report(conn, ...
        struct(attribution_run_id=m.runs.(name).attribution_run_id));
    rows = [rows; table(name, string(report.attribution_path), ...
        height(report.targets), height(report.candidates), height(report.evidence), ...
        height(report.windows), height(report.decisions), VariableNames=["run", ...
        "attribution_path", "targets", "candidates", "evidence", "windows", ...
        "decisions"])]; %#ok<AGROW>
end
grain = table(["targets"; "candidates"; "evidence"; "windows"; "decisions"], ...
    ["attribution target"; "(target, candidate entity)"; "stored evidence record"; ...
    "imported or backend window"; "(target, policy version)"], ...
    VariableNames=["table", "one_row_per"]);
extractors = fetch(conn, "SELECT er.run_key, COUNT(d.detection_id) AS detections " + ...
    "FROM extraction_runs er LEFT JOIN detections d " + ...
    "ON d.extraction_run_id = er.extraction_run_id GROUP BY er.run_key ORDER BY er.run_key");
extractors.run_key = string(extractors.run_key);
value = struct(recording_id=m.recording_id, extraction_runs=extractors, runs=rows, ...
    grain=grain, scenes=m.scenes(:, ["scene", "start_s", "built_how"]));
end

% ============================================================= cross path ===

function value = crossPath(conn, m)
pairs = ["imported", "backend"; "imported", "native_detections"; "backend", "native_detections"];
counts = table();
results = struct();
for k = 1:size(pairs, 1)
    c = compareRuns(conn, m, pairs(k, 1), pairs(k, 2));
    s = c.status_counts;
    counts = [counts; table(pairs(k, 1) + " vs " + pairs(k, 2), ...
        s.one_to_one_units(1), unitCount(s, "agree"), unitCount(s, "disagree"), ...
        unitCount(s, "structural_empty"), unitCount(s, "excluded"), ...
        unitCount(s, "undecided"), string(c.units.score_comparability(1)), ...
        VariableNames=["pair", "one_to_one_units", "agree", "disagree", ...
        "structural_empty", "excluded", "undecided", "score_comparability"])]; %#ok<AGROW>
    results.(pairs(k, 1) + "_" + pairs(k, 2)) = c;
end
separable = m.scenes.deepsqueak_detection_id(m.scenes.scene == "separable");
symmetric = m.scenes.deepsqueak_detection_id(m.scenes.scene == "symmetric");
who = table();
for k = 1:size(pairs, 1)
    c = results.(pairs(k, 1) + "_" + pairs(k, 2));
    u = c.units(c.units.event_id == separable, :);
    who = [who; table(pairs(k, 1) + " vs " + pairs(k, 2), u.top_entity_agreement, ...
        u.selected_set_relation, u.left_decision_status, u.right_decision_status, ...
        VariableNames=["pair", "top_entity_agreement", "selected_set_relation", ...
        "left_status", "right_status"])]; %#ok<AGROW>
end
in = results.imported_native_detections;
cell_ = in.status_crosstab(in.status_crosstab.left_decision_status == "simultaneous" & ...
    in.status_crosstab.right_decision_status == "ambiguous", :);
ib = results.imported_backend;
cellBackend = ib.status_crosstab(ib.status_crosstab.left_decision_status == "simultaneous" & ...
    ib.status_crosstab.right_decision_status == "ambiguous", :);
dims = ["temporal_alignment", "pose_localization", "visual_identity", "acoustic"];
declared = table(dims', arrayfun(@(d) strjoin(unique(in.units.("left_declared_" + d))', ","), dims'), ...
    arrayfun(@(d) strjoin(unique(in.units.("right_declared_" + d))', ","), dims'), ...
    VariableNames=["dimension", "imported", "native"]);
value = struct(counts=counts, separable_event_id=separable, separable=who, ...
    symmetric_event_id=symmetric, ...
    symmetric_imported_vs_native=struct(cell_kind=string(cell_.cell_kind), ...
        unit_count=double(cell_.unit_count)), ...
    symmetric_imported_vs_backend=struct(cell_kind=string(cellBackend.cell_kind), ...
        unit_count=double(cellBackend.unit_count)), ...
    native_producible_statuses=in.sides.producible_statuses(2), ...
    declared_inputs=declared, ...
    guards=["E1 test_attribution_compare/testTheOutputIsAClosedVocabularyAndCombinesNothing"; ...
        "E2 test_attribution_compare/testSimultaneousAgainstANativeStatusIsAStructuralEmpty"; ...
        "R1 test_attribution_compare/testEveryPathPairHasTheSameOutputShape"]);
end

function n = unitCount(s, kind)
n = double(s.unit_count(s.cell_kind == kind));
if isempty(n), n = 0; end
end

function c = compareRuns(conn, m, left, right, varargin)
c = vawlume.attribution.compare(conn, ...
    struct(attribution_run_id=m.runs.(left).attribution_run_id), ...
    struct(attribution_run_id=m.runs.(right).attribution_run_id), varargin{:});
end

% ========================================================= cross event set ===

function ref = allEventRun(conn, m, repoRoot, policyPath, key, column, eventIds)
% A native_estimate run over every event of one set, written through the
% canonical writers with SYNTHETIC scores and decided under the shipped native
% policy, exactly as test_attribution_compare_correspondence does. Its scores
% mean nothing; it exists to exercise the join.
settings = vawlume.estimator.loadSettings(RepoRoot=repoRoot);
created = vawlume.attribution.createRun(conn, struct(recording_id=m.recording_id), struct( ...
    run_key=key, attribution_path="native_estimate", ...
    method="vawlume.estimator.level_difference_consistency 1.0.0", ...
    settings_profile_version_id=m.profiles.estimator_settings_version_id, ...
    target_set=struct(column, eventIds(:)'), participating_entity_ids=[m.entities.A m.entities.B], ...
    sources=struct(analysis_run_ids=m.correspondence.consensus_source.analysis_run_id), ...
    declared_inputs=settings.declared_inputs), Apply=true);
for k = 1:height(created.targets)
    id = created.targets.attribution_target_id(k);
    a = -mod(id, 3) * 0.5;
    vawlume.attribution.addCandidates(conn, struct(attribution_target_id=id), ...
        struct(entity_id={m.entities.A; m.entities.B}, score={a; a - 1 - mod(id, 5)}, ...
        score_semantics={"synthetic dB; not a probability"; "synthetic dB; not a probability"}), ...
        Apply=true);
end
ref = struct(attribution_run_id=created.run.attribution_run_id);
vawlume.attribution.decide(conn, ref, policyPath, Apply=true, RepoRoot=repoRoot);
end

function value = crossEventSet(conn, m, runs)
structure = m.correspondence.structure;
rows = table();
for k = 1:height(structure)
    s = structure(k, :);
    other = "mupet";
    if s.pair == "deepsqueak_usvseg", other = "usvseg"; end
    c = vawlume.attribution.compare(conn, runs.ds, runs.(other), ...
        Correspondence=struct(analysis_run_id=s.analysis_run_id));
    left = targetsOf(conn, runs.ds, "detection_id", s.left_detection_ids{1});
    unit = c.units(cellfun(@(ids) any(ismember(left, ids)), c.units.left_target_ids), :);
    rows = [rows; table(string(s.scene), "deepsqueak", other, ...
        string(unit.correspondence_unit), splittingSide(unit.correspondence_unit, other), ...
        numel(unit.left_target_ids{1}), numel(unit.right_target_ids{1}), ...
        string(unit.left_decision_status), string(unit.right_decision_status), ...
        string(c.correspondence.analysis_run_key), string(c.correspondence.kind), ...
        VariableNames=["scene", "left", "right", "unit", "splitting_side", ...
        "left_targets", "right_targets", "left_status", "right_status", ...
        "named_analysis", "join"])]; %#ok<AGROW>
end
overall = table();
analyses = m.correspondence.matching_analyses;
cases = ["ds", "mupet", "p7-match-ds-mupet"; "ds", "usvseg", "p7-match-ds-usvseg"; ...
    "mupet", "usvseg", "p7-match-mupet-usvseg"];
for k = 1:size(cases, 1)
    id = analyses.analysis_run_id(analyses.run_key == cases(k, 3));
    c = vawlume.attribution.compare(conn, runs.(cases(k, 1)), runs.(cases(k, 2)), ...
        Correspondence=struct(analysis_run_id=id));
    overall = [overall; unitRow(cases(k, 1) + " vs " + cases(k, 2), cases(k, 3), c)]; %#ok<AGROW>
end
c = vawlume.attribution.compare(conn, runs.ds, runs.consensus, ...
    Correspondence=struct(analysis_run_id=m.correspondence.consensus_source.analysis_run_id));
overall = [overall; unitRow("ds vs consensus", ...
    string(m.correspondence.consensus_source.run_key), c)];
value = struct(scenes=rows, units=overall, ...
    note="Runs over every event of each set, written through the canonical writers " + ...
        "with synthetic scores: they exercise the join, and their scores mean nothing.", ...
    guards="E3 test_attribution_compare_correspondence/testSplitMergeAndMissAreTheManifestsUnits");
end

function side = splittingSide(unit, other)
switch unit
    case "one_to_many", side = other + " splits one deepsqueak call";
    case "many_to_one", side = "deepsqueak splits one " + other + " call";
    case "unmatched_left", side = other + " reports nothing";
    otherwise, side = "";
end
end

function row = unitRow(label, analysis, c)
u = string(c.units.correspondence_unit);
row = table(label, analysis, nnz(u == "one_to_one"), nnz(u == "one_to_many"), ...
    nnz(u == "many_to_one"), nnz(u == "many_to_many"), nnz(u == "unmatched_left"), ...
    nnz(u == "unmatched_right"), VariableNames=["runs", "named_analysis", ...
    "one_to_one", "one_to_many", "many_to_one", "many_to_many", ...
    "unmatched_left", "unmatched_right"]);
end

function ids = targetsOf(conn, run, column, eventIds)
targets = vawlume.attribution.report(conn, run, Tables="targets").targets;
ids = targets.attribution_target_id(ismember(targets.(column), eventIds));
end

