function id = offsetAudioFit(conn, root, repoRoot, projectKey)
% A second alignment set over the same audio anchors, declared with the offset
% model, ingested and fitted through the public path: the alternative the
% alignment_run handle names.
folder = fullfile(root, "alignment");
manifest = jsondecode(fileread(fullfile(folder, "audio_alignment_manifest.json")));
manifest.manifest.alignment_key = 'p716_audio_clock_offset';
manifest.method = 'offset';
path = fullfile(folder, "audio_offset_alignment_manifest.json");
writeText(path, string(jsonencode(manifest, PrettyPrint=true)));
vawlume.ingest.alignment(conn, path, RepoRoot=repoRoot, SourceRoot=string(folder), Apply=true);
ref = struct(project_key=projectKey, run_key="p716_audio_clock_offset");
vawlume.alignment.fit(conn, ref, SourceTimebase="audio_native", Apply=true);
qc = vawlume.alignment.report(conn, ref);
id = double(qc.transforms.alignment_run_id(qc.transforms.source_timebase_key == "audio_native"));
end

function spec = attributionFamily(fixture, m, policyPath, offsetRun, workspace)
runSpec = struct(run_key="p7-native-ds", ...
    settings_profile_version_id=m.profiles.estimator_settings_version_id, ...
    target_set=struct(detection_ids=m.scenes.deepsqueak_detection_id'), ...
    participating_entity_ids=[m.entities.A m.entities.B], ...
    clock=struct(clock_relation="alignment_run", reference_timebase_key="neural_native", ...
        audio_alignment_run_id=m.alignment.audio.alignment_run_id), ...
    tracking=struct(stream=struct(project_key=m.project_key, stream_name="arena_tracking"), ...
        alignment_run_id=m.alignment.tracking.alignment_run_id, ...
        source_root=fullfile(fixture.root, "tracking")), ...
    normalization_runs=m.acoustic.detection_normalization_runs(:, ["detection_id", "analysis_run_id"]));
spec = struct(family_key="p716-attribution-family", ...
    output_root=fullfile(workspace, "attribution_family"), ...
    reference=struct(attribution_run_id=m.runs.native_detections.attribution_run_id, ...
        run_spec=runSpec, decision_policy=policyPath), ...
    variants=[struct(handle="decision_policy", value=struct(selection_threshold=-1)), ...
        struct(handle="estimator_settings", value=struct(primary_instant_basis="onset")), ...
        struct(handle="normalization_policy", value=struct(reference_type="tone")), ...
        struct(handle="alignment_run", value=struct(audio_alignment_run_id=offsetRun))]);
end

function value = attributionDisplay(conn, m, plan, wroteNothing, applied, summary, offsetRun)
rows = summary.rows;
variants = rows(rows.status == "variant", ["handle", "handle_value", "variant_kind", ...
    "score_comparability", "one_to_one_units", "top_same", "top_different", ...
    "sets_equal", "sets_differ", "status_agree", "status_disagree", ...
    "reasons_changed", "scores_changed"]);
reported = rows(rows.status ~= "variant", ["handle", "status", "reason"]);
target = m.scenes.native_detection_target_id(m.scenes.scene == "out_of_bracket");
variant = applied.variants(applied.variants.handle == "alignment_run", :);
id = applied.variants.configuration_id(applied.variants.handle == "alignment_run");
c = summary.comparisons([summary.comparisons.configuration_id] == id).comparison;
unit = c.units(cellfun(@(ids) isequal(ids, target), c.units.left_target_ids), :);
evidence = fetch(conn, "SELECT value_semantics FROM attribution_evidence WHERE " + ...
    "attribution_target_id=" + string(unit.right_target_ids{1}) + ...
    " AND evidence_kind='bodypoint_microphone_distance'");
used = fetch(conn, "SELECT DISTINCT e.alignment_run_id FROM attribution_evidence e " + ...
    "JOIN attribution_targets g ON g.attribution_target_id = e.attribution_target_id " + ...
    "WHERE g.attribution_run_id=" + string(variant.attribution_run_id) + ...
    " AND e.alignment_run_id IS NOT NULL");
value = struct( ...
    reference=struct(attribution_run_id=m.runs.native_detections.attribution_run_id, ...
        declared="before any variant was planned"), ...
    plan_variants=plan.variants(:, ["handle", "configuration_id"]), ...
    plan_wrote_nothing=wroteNothing, ...
    family_analysis_run_id=applied.family_analysis_run_id, ...
    variants=variants, ...
    reported_not_varied=reported, ...
    tone_family_generated=any(variants.handle == "normalization_policy"), ...
    alignment_variant_cites_offset_fit=ismember(offsetRun, double(used.alignment_run_id)), ...
    out_of_bracket_extrapolated=any(contains(string(evidence.value_semantics), ...
        "bracket_extrapolated=true")), ...
    guards=["E4 test_attribution_sensitivity/testTheSummarySelectsNothing"; ...
        "E8 test_attribution_sensitivity/testTheSensitivityRunsLeaveEveryNativeTableUnchanged"]);
end

% ===================================================== matching sensitivity ===

function spec = matchingFamily(fixture, m, policyPath, workspace)
runSpec = struct(settings_profile_version_id=m.profiles.estimator_settings_version_id, ...
    participating_entity_ids=[m.entities.A m.entities.B], ...
    clock=struct(clock_relation="alignment_run", reference_timebase_key="neural_native", ...
        audio_alignment_run_id=m.alignment.audio.alignment_run_id), ...
    tracking=struct(stream=struct(project_key=m.project_key, stream_name="arena_tracking"), ...
        alignment_run_id=m.alignment.tracking.alignment_run_id, ...
        source_root=fullfile(fixture.root, "tracking")));
spec = struct(family_key="p716-matching-family", ...
    output_root=fullfile(workspace, "matching_family"), ...
    recording_id=m.recording_id, extraction_runs=["p7-ds", "p7-mupet", "p7-usvseg"], ...
    consensus_pair=["p7-ds", "p7-mupet"], ...
    reference=struct(run_spec=runSpec, decision_policy=policyPath, ...
        measurement=struct(channels=[1 2], band_hz=[200 300], ...
