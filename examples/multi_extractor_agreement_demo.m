function demonstration = multi_extractor_agreement_demo(options)
%MULTI_EXTRACTOR_AGREEMENT_DEMO Demonstrate three-extractor agreement end to end.
%
% DEMONSTRATION = MULTI_EXTRACTOR_AGREEMENT_DEMO() runs the complete Phase 1
% arbitrary-N workflow over one synthetic recording:
%
%   1. import DeepSqueak, MUPET, and USVSEG through their public importers;
%   2. run all three pairwise comparisons under one versioned matching
%      specification;
%   3. compose those pairwise analyses into arbitrary-N agreement groups;
%   4. query an exact extractor-pair edge pattern;
%   5. query a coarse K-of-possible support count.
%
% Steps 4 and 5 are the point of the demonstration. They are independent
% dimensions: two components can both support two of three possible extractor
% pairs while supporting *different* pairs, and only the coarse query merges
% them. The exact query keeps them apart.
%
% Pairwise matching remains the primitive. Agreement is derived from compatible
% pairwise analyses and preserves their exact supporting edges; it never
% synthesizes a transitive edge to make a component look complete, never
% collapses a split/merge component into one event, and never invents consensus
% timing.
%
% Every artifact and the SQLite database live under the system temporary
% directory and are removed before return. The detections and every threshold
% they meet are illustrative prototype fixtures. Agreement strength is
% methodological evidence, not a calibrated confidence probability and not a
% biological truth label.
%
% Name-value options:
%   Print     print compact developer-facing read-backs (default true)
%   RepoRoot  repository root, inferred from this file by default
%
% See also VAWLUME.AGREEMENT.COMPOSE, VAWLUME.AGREEMENT.SELECTPOPULATION,
% VAWLUME.MATCHING.COMPARE, USVSEG_IMPORT_DEMO, AGREEMENT_FILTER_DEMO.

arguments
    options.Print (1,1) logical = true
    options.RepoRoot (1,1) string = ""
end

repoRoot = normalizedRepoRoot(options.RepoRoot);
sourcePath = fullfile(repoRoot, "src");
removeSourcePath = ~pathContains(sourcePath);
if removeSourcePath, addpath(sourcePath); end
cleanupPath = onCleanup(@() restoreSourcePath(sourcePath, removeSourcePath));

workspaceRoot = fullfile(tempdir, ...
    "VAWLUME multi extractor agreement demo " + string(java.util.UUID.randomUUID));
mkdir(workspaceRoot);
cleanupWorkspace = onCleanup(@() removeTree(workspaceRoot));
databasePath = fullfile(workspaceRoot, "multi_extractor_agreement_demo.sqlite");
conn = sqlite(char(databasePath), "create");
cleanupConnection = onCleanup(@() closeConnection(conn));

vawlume.db.applySchema(conn, fullfile(repoRoot, "schema", "schema.sql"));
vawlume.db.registerBuiltinSemantics(conn, repoRoot);

% 1. One recording, three extractor runs. Separate extraction runs are never
%    implicitly pooled as though they were one biological event set.
[project, recordingRef] = establishProject(conn, workspaceRoot, repoRoot);
imports = importAllThreeExtractors(conn, workspaceRoot, repoRoot, recordingRef);
upstreamBefore = upstreamFingerprint(conn);

% 2. All three pairwise comparisons. Every source analysis must cite the same
%    versioned matching specification, so a missing supporting edge cannot be
%    confused with a pair that was assessed under different thresholds.
matchSpecPath = fullfile(repoRoot, "config", "05_matching_profiles", ...
    "prototype_matching_consilience_spec.json");
pairwise = runPairwiseComparisons(conn, recordingRef, repoRoot, matchSpecPath);

% 3. Compose the arbitrary-N agreement run from those three analyses. Sources
%    are analyses, not a run signature; order carries no meaning.
agreementSources = ["demo-match-ds-mupet"; "demo-match-ds-usvseg"; ...
    "demo-match-mupet-usvseg"];
composed = vawlume.agreement.compose(conn, recordingRef, agreementSources, ...
    struct(run_key="demo-agreement", ...
    run_label="Synthetic three-extractor agreement"), ...
    RepoRoot=repoRoot, Apply=true);
assert(composed.committed, "Agreement composition did not commit: %s", ...
    composed.status);

agreementRef = struct(project_key=project.project_key, run_key="demo-agreement");
allGroups = vawlume.agreement.selectPopulation(conn, agreementRef);

% 4. Exact edge-pattern queries. Both of these components support exactly two
%    of three possible extractor pairs, and they support different pairs.
chainThroughMupet = vawlume.agreement.selectPopulation(conn, agreementRef, ...
    ExactSupportPattern=chainThroughMupetPattern());
chainThroughUsvseg = vawlume.agreement.selectPopulation(conn, agreementRef, ...
    ExactSupportPattern=chainThroughUsvsegPattern());
completeTriplePattern = vawlume.agreement.selectPopulation(conn, agreementRef, ...
    ExactSupportPattern=allPairPattern());

% 5. Coarse K-of-possible queries. ExactSupportedPairCount=2 deliberately
%    returns both open chains as one population; the exact queries above are
%    the only way to keep their shapes apart.
atLeastTwoPairs = vawlume.agreement.selectPopulation(conn, agreementRef, ...
    MinSupportedPairCount=2);
exactlyTwoPairs = vawlume.agreement.selectPopulation(conn, agreementRef, ...
    ExactSupportedPairCount=2);

% Independent shape dimensions over the same run.
triple = "deepsqueak|mupet|usvseg";
cleanCompleteTriple = vawlume.agreement.selectPopulation(conn, agreementRef, ...
    ExtractorSetKey=triple, Completeness="complete", Cleanliness="clean", ...
    Multiplicity="one_per_extractor");
completeAmbiguous = vawlume.agreement.selectPopulation(conn, agreementRef, ...
    ExtractorSetKey=triple, Completeness="complete", ...
    Multiplicity="multiple_per_extractor");
singleExtractorPairOnly = vawlume.agreement.selectPopulation(conn, ...
    agreementRef, ExactPossiblePairCount=1);
extractorUnique = vawlume.agreement.selectPopulation(conn, agreementRef, ...
    Uniqueness="extractor_unique");

populations = struct( ...
    all_groups=allGroups, ...
    exact_all_three_pairs=completeTriplePattern, ...
    exact_chain_through_mupet=chainThroughMupet, ...
    exact_chain_through_usvseg=chainThroughUsvseg, ...
    coarse_at_least_two_pairs=atLeastTwoPairs, ...
    coarse_exactly_two_pairs=exactlyTwoPairs, ...
    clean_complete_triple=cleanCompleteTriple, ...
    complete_ambiguous=completeAmbiguous, ...
    two_extractor_pair_only=singleExtractorPairOnly, ...
    extractor_unique=extractorUnique);

% The exact-versus-coarse claim, stated as a check rather than as prose only.
exactVersusCoarse = struct( ...
    coarse_group_count=exactlyTwoPairs.selected_group_count, ...
    exact_pattern_group_counts=[chainThroughMupet.selected_group_count; ...
        chainThroughUsvseg.selected_group_count], ...
    exact_patterns=[chainThroughMupetPattern(); chainThroughUsvsegPattern()], ...
    exact_patterns_are_disjoint=isempty(intersect( ...
        chainThroughMupet.agreement_group_ids, ...
        chainThroughUsvseg.agreement_group_ids)), ...
    exact_partition_recovers_coarse= ...
        chainThroughMupet.selected_group_count + ...
        chainThroughUsvseg.selected_group_count == ...
        exactlyTwoPairs.selected_group_count);

demonstration = struct( ...
    architecture=["public project intake"; "DeepSqueak import"; ...
        "MUPET import"; "USVSEG import"; "three pairwise matching analyses"; ...
        "arbitrary-N agreement composition"; "exact edge-pattern query"; ...
        "coarse K-of-possible query"], ...
    calibration_boundary="Illustrative synthetic prototype settings. " + ...
        "Agreement strength is methodological evidence, not a calibrated " + ...
        "confidence probability or a biological truth label.", ...
    project=project, imports=imports, pairwise=pairwise, ...
    agreement=struct(run_key=composed.analysis.run_key, ...
        analysis_run_id=composed.analysis.analysis_run_id, ...
        status=composed.status, source_analysis_count=numel(agreementSources), ...
        group_count=allGroups.selected_group_count, ...
        native_member_count=allGroups.selected_member_count), ...
    populations=populations, ...
    population_summary=populationSummary(populations), ...
    group_shapes=groupShapes(allGroups), ...
    exact_versus_coarse=exactVersusCoarse, ...
    denominator_note="Group counts and native-member counts are different " + ...
        "denominators. The split/merge component below is one agreement " + ...
        "group and four native observations; downstream summaries must say " + ...
        "which denominator they used.", ...
    identity=struct( ...
        detections_partitioned=allGroups.selected_member_count == ...
            imports.total_detection_count, ...
        member_detections_unique=numel(unique(allGroups.detection_ids)) == ...
            allGroups.selected_member_count, ...
        native_detections_unchanged=isequal(upstreamBefore, ...
            upstreamFingerprint(conn))), ...
    foreign_key_check=fetch(conn, "PRAGMA foreign_key_check"), ...
    proves=[ ...
        "three extractors reach one relational model and one derived agreement run"; ...
        "arbitrary-N agreement is composed from compatible pairwise analyses, not measured directly"; ...
        "exact extractor-pair patterns stay distinct from coarse K-of-possible counts"; ...
        "split/merge components remain one group with several native observations"; ...
        "an extractor-unique detection survives as a single-member group"], ...
    does_not_prove=[ ...
        "biological truth, caller attribution, or that any extractor is correct"; ...
        "empirical calibration of the matching threshold these edges depend on"; ...
        "that agreement strength is a confidence probability"], ...
    workspace_root=workspaceRoot, database_path=databasePath, ...
    temporary_artifacts_removed=false);

close(conn);
clear cleanupConnection
removeTree(workspaceRoot);
clear cleanupWorkspace
demonstration.temporary_artifacts_removed = ...
    ~isfolder(workspaceRoot) && ~isfile(databasePath);

if options.Print, printDemonstration(demonstration); end
clear cleanupPath
end

% -------------------------------------------------------------- workflow ---

function [project, recordingRef] = establishProject(conn, workspaceRoot, repoRoot)
profilePath = fullfile(repoRoot, "config", "01_mapping_profiles", ...
    "project_inputs", "project_input_source_mapping_examples.json");
sourceRoot = fullfile(workspaceRoot, "project");
audioPath = fullfile(sourceRoot, "control", "mouse_001", "baseline", ...
    "001_baseline_1.wav");
writeText(audioPath, "synthetic audio stand-in; no recorded sound is involved");
ir = vawlume.source_mapping.parse(profilePath, sourceRoot, ...
    ProfileId="example.project.mouse_courtship.folder_driven", RepoRoot=repoRoot);
preview = vawlume.source_mapping.preview(ir);
intake = vawlume.ingest.project(conn, ir, struct( ...
    project_key="demo_multi_extractor_agreement", ...
    project_name="Three-extractor agreement demonstration", ...
    description="Disposable Phase 1 arbitrary-N agreement demonstration."), ...
    Apply=true, RepoRoot=repoRoot);
recording = fetch(conn, "SELECT r.recording_id, p.project_key, " + ...
    "sf.relative_path FROM recordings r " + ...
    "JOIN projects p ON p.project_id=r.project_id " + ...
    "JOIN source_files sf ON sf.source_file_id=r.source_file_id");
recordingId = double(recording.recording_id(1));
recordingRef = struct(recording_id=recordingId);
project = struct(intake_status=intake.status, preview_verdict=preview.verdict, ...
    project_key=string(recording.project_key(1)), recording_id=recordingId, ...
    source_relative_path=string(recording.relative_path(1)));
end

function value = importAllThreeExtractors(conn, workspaceRoot, repoRoot, recordingRef)
dsRoot = fullfile(workspaceRoot, "deepsqueak");
dsPath = fullfile(dsRoot, "exports", "REC_A_Stats.xlsx");
writeCells(dsPath, deepSqueakCells());
ds = vawlume.ingest.deepsqueak(conn, dsPath, recordingRef, ...
    struct(run_key="demo-ds", extractor_version="3.2.1"), ...
    RepoRoot=repoRoot, ArtifactRoot=dsRoot, Apply=true);
assert(ds.committed, "DeepSqueak import did not commit.");

mupetRoot = fullfile(workspaceRoot, "mupet");
mupetPath = fullfile(mupetRoot, "CSV", "REC_A.csv");
configPath = fullfile(mupetRoot, "config.csv");
writeCells(mupetPath, mupetCells());
writeText(configPath, strjoin(mupetConfigLines(), newline) + newline);
mupet = vawlume.ingest.mupet(conn, mupetPath, recordingRef, ...
    struct(run_key="demo-mupet", extractor_version="2.1", ...
    settings=struct(config_path=configPath)), ...
    RepoRoot=repoRoot, ArtifactRoot=mupetRoot, Apply=true);
assert(mupet.committed, "MUPET import did not commit.");

usvsegRoot = fullfile(workspaceRoot, "usvseg");
usvsegPath = fullfile(usvsegRoot, "REC_A_dat.csv");
writeLines(usvsegPath, usvsegLines());
usvseg = vawlume.ingest.usvseg(conn, usvsegPath, recordingRef, ...
    struct(run_key="demo-usvseg", extractor_version="0.9r2"), ...
    RepoRoot=repoRoot, ArtifactRoot=usvsegRoot, Apply=true);
assert(usvseg.committed, "USVSEG import did not commit.");

runKey = ["demo-ds"; "demo-mupet"; "demo-usvseg"];
extractor = ["DeepSqueak"; "MUPET"; "USVSEG"];
detectionCount = [ds.applied_counts.detections; ...
    mupet.applied_counts.detections; usvseg.applied_counts.detections];
value = struct( ...
    runs=table(runKey, extractor, detectionCount, ...
        VariableNames=["run_key", "extractor", "detection_count"]), ...
    total_detection_count=sum(detectionCount));
end

function value = runPairwiseComparisons(conn, recordingRef, repoRoot, specPath)
pairs = { ...
    {"demo-match-ds-mupet", "demo-ds", "demo-mupet"}
    {"demo-match-ds-usvseg", "demo-ds", "demo-usvseg"}
    {"demo-match-mupet-usvseg", "demo-mupet", "demo-usvseg"}};
runKey = strings(numel(pairs), 1);
runA = strings(numel(pairs), 1);
runB = strings(numel(pairs), 1);
candidateCount = zeros(numel(pairs), 1);
groupCount = zeros(numel(pairs), 1);
consensusCount = zeros(numel(pairs), 1);
for index = 1:numel(pairs)
    pair = pairs{index};
    result = vawlume.matching.compare(conn, recordingRef, ...
        struct(run_a=pair{2}, run_b=pair{3}), ...
        struct(run_key=pair{1}, profile_path=specPath), ...
        RepoRoot=repoRoot, Apply=true);
    assert(result.committed, "Matching '%s' did not commit: %s", ...
        pair{1}, result.status);
    runKey(index) = pair{1};
    runA(index) = pair{2};
    runB(index) = pair{3};
    candidateCount(index) = height(result.candidates);
    groupCount(index) = height(result.groups);
    consensusCount(index) = height(result.consensus_events);
end
value = table(runKey, runA, runB, candidateCount, groupCount, consensusCount, ...
    VariableNames=["run_key", "run_a", "run_b", "candidate_pair_count", ...
    "match_group_count", "consensus_event_count"]);
end

% ------------------------------------------------------------ read-backs ---

function rows = populationSummary(populations)
fields = string(fieldnames(populations));
filterKey = fields;
groupCount = zeros(numel(fields), 1);
memberCount = zeros(numel(fields), 1);
for index = 1:numel(fields)
    population = populations.(fields(index));
    groupCount(index) = population.selected_group_count;
    memberCount(index) = population.selected_member_count;
end
rows = table(filterKey, groupCount, memberCount, ...
    VariableNames=["filter_key", "group_count", "native_member_count"]);
end

function rows = groupShapes(population)
groups = population.groups;
rows = table(string(groups.group_key), double(groups.member_count), ...
    double(groups.extractor_count), string(groups.extractor_set_key), ...
    double(groups.supported_extractor_pair_count), ...
    double(groups.possible_extractor_pair_count), ...
    string(groups.supported_extractor_pair_pattern), ...
    string(groups.unsupported_extractor_pair_pattern), ...
    logical(groups.is_extractor_pair_support_complete), ...
    logical(groups.is_one_detection_per_extractor), ...
    logical(groups.is_unambiguous_one_to_one), ...
    logical(groups.is_extractor_unique), ...
    VariableNames=["group_key", "native_member_count", "extractor_count", ...
    "extractor_set_key", "supported_pairs", "possible_pairs", ...
    "supported_pair_pattern", "unsupported_pair_pattern", ...
    "support_complete", "one_detection_per_extractor", ...
    "unambiguous_one_to_one", "extractor_unique"]);
rows = sortrows(rows, "group_key");
end

function value = upstreamFingerprint(conn)
value = fetch(conn, "SELECT d.detection_id, d.extraction_run_id, " + ...
    "d.native_event_id, d.start_time_s, d.end_time_s, " + ...
    "COUNT(em.event_measurement_id) AS measurements " + ...
    "FROM detections d LEFT JOIN event_measurements em " + ...
    "ON em.detection_id=d.detection_id " + ...
    "GROUP BY d.detection_id ORDER BY d.detection_id");
end

