% -------------------------------------------------------------- utilities ---

function writeCells(path, cells)
makeParent(path);
if isfile(path), delete(path); end
writecell(cells, path);
end

function writeLines(path, lines)
makeParent(path);
fileId = fopen(path, "w");
if fileId < 0
    error("vawlume:examples:FixtureCreationFailed", ...
        "Could not create demonstration input: %s", path);
end
cleanupFile = onCleanup(@() fclose(fileId));
fprintf(fileId, "%s\n", lines);
clear cleanupFile
end

function writeText(path, value)
makeParent(path);
fileId = fopen(path, "w");
if fileId < 0
    error("vawlume:examples:FixtureCreationFailed", ...
        "Could not create demonstration input: %s", path);
end
cleanupFile = onCleanup(@() fclose(fileId));
fprintf(fileId, "%s", value);
clear cleanupFile
end

function makeParent(path)
parent = fileparts(path);
if ~isfolder(parent), mkdir(parent); end
end

function root = normalizedRepoRoot(root)
if strlength(root) == 0, root = fileparts(fileparts(mfilename("fullpath"))); end
try
    root = string(java.io.File(char(root)).getCanonicalPath());
catch
end
end

function value = pathContains(target)
value = any(split(string(path), pathsep) == string(target));
end

function restoreSourcePath(sourcePath, shouldRemove)
if shouldRemove && pathContains(sourcePath), rmpath(sourcePath); end
end

function closeConnection(conn)
try
    if isopen(conn), close(conn); end
catch
end
end

function removeTree(root)
if isfolder(root), rmdir(root, "s"); end
end

function printDemonstration(value)
disp("VAWLUME THREE-EXTRACTOR AGREEMENT DEMONSTRATION")
disp(value.calibration_boundary)
disp("Imported extraction runs (never implicitly pooled):")
disp(value.imports.runs)
disp("Pairwise matching analyses (the primitive):")
disp(value.pairwise)
fprintf("Composed agreement run '%s': %d groups over %d native members\n", ...
    value.agreement.run_key, value.agreement.group_count, ...
    value.agreement.native_member_count);
disp("Agreement group shapes:")
disp(value.group_shapes)
disp("Selected populations:")
disp(value.population_summary)
fprintf(['Exact versus coarse: %d groups support exactly two of three ' ...
    'pairs;\n  the two exact patterns split them %d and %d, disjointly: %d\n'], ...
    value.exact_versus_coarse.coarse_group_count, ...
    value.exact_versus_coarse.exact_pattern_group_counts(1), ...
    value.exact_versus_coarse.exact_pattern_group_counts(2), ...
    value.exact_versus_coarse.exact_patterns_are_disjoint);
disp(value.denominator_note)
fprintf(['Detections partitioned: %d; member detections unique: %d; ' ...
    'native detections unchanged: %d\n'], ...
    value.identity.detections_partitioned, ...
    value.identity.member_detections_unique, ...
    value.identity.native_detections_unchanged);
fprintf("Foreign-key violations: %d; temporary artifacts removed: %d\n", ...
    height(value.foreign_key_check), value.temporary_artifacts_removed);
fprintf("Proves:\n  %s\n", strjoin(value.proves, newline + "  "));
fprintf("Does not prove:\n  %s\n", ...
    strjoin(value.does_not_prove, newline + "  "));
end
