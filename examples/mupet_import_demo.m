function demonstration = mupet_import_demo(options)
%MUPET_IMPORT_DEMO Demonstrate the MUPET import path end to end.
%
% DEMONSTRATION = MUPET_IMPORT_DEMO() establishes one project recording through
% the real project-intake path, generates a small MUPET per-syllable CSV and its
% native config.csv, maps and previews the CSV, plans and applies the import with
% the public MUPET importer, and returns relational read-back tables covering run
% and artifact provenance, captured settings, syllable detections, native and
% canonical measurements, and the preserved terminal inter-syllable NA. It then
% reruns the identical import, relocates the artifacts under a second absolute
% root, and imports a small DeepSqueak export onto the same recording to show the
% two extractors coexisting.
%
% Every input is generated under the system temporary directory and removed
% before this function returns. No private data is involved and no database edit
% is made by hand.
%
% The flow is:
%
%   synthetic source tree
%       -> project-input JSON profile
%       -> source_mapping.parse + preview
%       -> vawlume.ingest.project(..., Apply=true)
%       -> synthetic MUPET per-syllable .csv + native config.csv
%       -> vawlume.ingest.mupetExport + source_mapping.preview
%       -> vawlume.ingest.mupet (plan)
%       -> vawlume.ingest.mupet (Apply=true)
%       -> relational read-back
%       -> unchanged rerun, artifact relocation, DeepSqueak co-residence
%
% Name-value options:
%   Print     print a concise developer-facing summary (default true)
%   RepoRoot  repository root; inferred from this file's location by default
%
% What this demonstrates is bounded. It covers the MUPET per-syllable CSV for the
% tracked v2.1 output mapping profile, and nothing else: not every MUPET version,
% not dataset summary or repertoire exports, not native .mat parsing, and not
% cross-extractor matching, consensus, or consilience. The co-residence appendix
% shows two populations sharing one recording; it computes no correspondence
% between them, because none is implemented.
%
% Two MUPET behaviours shown here are contract rather than omission. Settings
% provenance is required to apply, and a MUPET import creates zero curation rows
% and zero classification assignments, because the per-syllable CSV exports no
% review state, no class label, and no detector score.
%
% From the repository root:
%
%   addpath("examples")
%   mupet_import_demo
%
% See also VAWLUME.INGEST.MUPET, DEEPSQUEAK_IMPORT_DEMO, PROJECT_INTAKE_DEMO.

arguments
    options.Print (1,1) logical = true
    options.RepoRoot (1,1) string = ""
end

repoRoot = normalizedRepoRoot(options.RepoRoot);
sourcePath = fullfile(repoRoot, "src");
removeSourcePath = ~pathContains(sourcePath);
if removeSourcePath
    addpath(sourcePath);
end
cleanupPath = onCleanup(@() restoreSourcePath(sourcePath, removeSourcePath));

workspaceRoot = fullfile(tempdir, ...
    "VAWLUME mupet import demo " + string(java.util.UUID.randomUUID));
mkdir(workspaceRoot);
cleanupWorkspace = onCleanup(@() removeTree(workspaceRoot));
databasePath = fullfile(workspaceRoot, "mupet_import_demo.sqlite");
conn = sqlite(char(databasePath), "create");
cleanupConnection = onCleanup(@() closeConnection(conn));

vawlume.db.applySchema(conn, fullfile(repoRoot, "schema", "schema.sql"));
vawlume.db.registerBuiltinSemantics(conn, repoRoot);

% --- Phase 3: establish one project recording through the public path --------
projectProfilePath = fullfile(repoRoot, "config", "01_mapping_profiles", ...
    "project_inputs", "project_input_source_mapping_examples.json");
sourceRoot = fullfile(workspaceRoot, "project");
audioPath = fullfile(sourceRoot, "control", "mouse_001", "baseline", ...
    "001_baseline_1.wav");
makeParentFolder(audioPath);
writeText(audioPath, "synthetic audio stand-in; no recorded sound is involved");

projectIR = vawlume.source_mapping.parse(projectProfilePath, sourceRoot, ...
    ProfileId="example.project.mouse_courtship.folder_driven", RepoRoot=repoRoot);
projectPreview = vawlume.source_mapping.preview(projectIR);
intake = vawlume.ingest.project(conn, projectIR, struct( ...
    project_key="demo_mupet_import", ...
    project_name="MUPET import demonstration", ...
    description="Disposable Phase 5 demonstration project."), Apply=true, ...
    ProfileLinkagePath=fullfile(repoRoot, "config", "04_examples", ...
    "profile_linkage_example.json"), RepoRoot=repoRoot);

recording = fetch(conn, ...
    "SELECT r.recording_id, IFNULL(r.native_recording_id,'') AS native_recording_id, " + ...
    "IFNULL(sf.relative_path,'') AS source_relative_path " + ...
    "FROM recordings r JOIN source_files sf ON sf.source_file_id = r.source_file_id");
recordingId = double(recording.recording_id(1));

% --- Phase 5: generate a deterministic per-syllable CSV and its config -------
artifactRoot = fullfile(workspaceRoot, "mupet");
exportPath = fullfile(artifactRoot, "CSV", "MOUSE001_BASELINE.csv");
makeParentFolder(exportPath);
writecell(demonstrationExport(), exportPath);

% Settings are generated as demonstration inputs, not copied from any published
% default. MUPET reprocesses a recording when its configuration changes, so the
% importer refuses to apply without this evidence and substitutes nothing.
configPath = fullfile(artifactRoot, "config.csv");
writeText(configPath, strjoin(demonstrationConfigLines(), newline) + newline);

% The processed .mat is registered and hashed as native provenance. It is never
% parsed, and it is never accepted in place of the settings above.
nativePath = fullfile(artifactRoot, "mat", "MOUSE001_BASELINE.mat");
writeText(nativePath, "synthetic stand-in for MUPET processed state; never parsed");

runSpec = struct( ...
    run_key="demo_mupet_run_1", ...
    extractor_version="2.1", ...
    run_label="Demonstration MUPET segmentation run", ...
    settings=struct(config_path=configPath, relative_path="config.csv"), ...
    native_artifact=struct(artifact_path=nativePath, ...
        relative_path="mat/MOUSE001_BASELINE.mat"), ...
    dataset=struct(workspace_name="demo_workspace", dataset_name="demo_dataset"));

% --- Adapter, IR, and preview before any database write ---------------------
adapter = vawlume.ingest.mupetExport(exportPath, RepoRoot=repoRoot, ...
    ArtifactRoot=artifactRoot, ExtractorVersion="2.1", ...
    SettingsConfigPath=configPath, SettingsArtifactRoot=artifactRoot, ...
    SettingsRelativePath="config.csv");
adapterPreview = vawlume.source_mapping.preview(adapter.ir);

recordingRef = struct(recording_id=recordingId);
plan = vawlume.ingest.mupet(conn, exportPath, recordingRef, runSpec, ...
    RepoRoot=repoRoot, ArtifactRoot=artifactRoot);
imported = vawlume.ingest.mupet(conn, exportPath, recordingRef, runSpec, ...
    RepoRoot=repoRoot, ArtifactRoot=artifactRoot, Apply=true);

% --- Rerun and relocation ---------------------------------------------------
beforeRerun = scientificInventory(conn);
rerun = vawlume.ingest.mupet(conn, exportPath, recordingRef, runSpec, ...
    RepoRoot=repoRoot, ArtifactRoot=artifactRoot, Apply=true);
rerunSummary = struct( ...
    committed=rerun.committed, ...
    extraction_run_action=rerun.extraction_run.action, ...
    extraction_run_id_stable=rerun.extraction_run.extraction_run_id == ...
        imported.extraction_run.extraction_run_id, ...
    detections_created=rerun.applied_counts.detections, ...
    detections_reused=rerun.detections.detections_reuse, ...
    measurements_created=rerun.applied_counts.event_measurements, ...
    measurements_reused=rerun.detections.measurements_reuse, ...
    curation_rows_expected=rerun.detections.curation_rows_expected, ...
    classification_rows_expected=rerun.detections.classification_rows_expected, ...
    scientific_rows_unchanged=isequal(scientificInventory(conn), beforeRerun));

relocatedRoot = fullfile(workspaceRoot, "relocated");
relocatedExport = fullfile(relocatedRoot, "CSV", "MOUSE001_BASELINE.csv");
relocatedConfig = fullfile(relocatedRoot, "config.csv");
relocatedNative = fullfile(relocatedRoot, "mat", "MOUSE001_BASELINE.mat");
copyTo(exportPath, relocatedExport);
copyTo(configPath, relocatedConfig);
copyTo(nativePath, relocatedNative);
relocatedSpec = runSpec;
relocatedSpec.settings.config_path = relocatedConfig;
relocatedSpec.native_artifact.artifact_path = relocatedNative;
relocated = vawlume.ingest.mupet(conn, relocatedExport, recordingRef, ...
    relocatedSpec, RepoRoot=repoRoot, ArtifactRoot=relocatedRoot, Apply=true);
storedArtifactPath = scalarText(conn, ...
    "SELECT path_or_uri FROM artifacts WHERE artifact_type = 'extractor_event_export'");
relocationSummary = struct( ...
    committed=relocated.committed, ...
    extraction_run_action=relocated.extraction_run.action, ...
    artifact_actions=strjoin(sort(string(relocated.artifacts.action)), ", "), ...
    runtime_path_changed=relocated.export.runtime_path ~= imported.export.runtime_path, ...
    stored_portable_path=storedArtifactPath, ...
    scientific_rows_unchanged=isequal(scientificInventory(conn), beforeRerun));

% --- Co-residence appendix: a DeepSqueak run on the same recording ----------
% This shows two extractor populations sharing one recording. It deliberately
% computes no candidate pairs, no overlap, and no consensus: matching is Phase 6
% and does not exist yet.
deepsqueakSummary = importDeepSqueak(conn, workspaceRoot, repoRoot, recordingRef);
coResidence = coResidenceRows(conn, recordingId);
crossExtractorConcepts = broadConceptRows(conn);

inventory = scientificInventory(conn);
foreignKeyViolations = fetch(conn, "PRAGMA foreign_key_check");

demonstration = struct( ...
    architecture=[ ...
        "synthetic project source tree"; ...
        "project intake with tracked device/setup linkage"; ...
        "synthetic MUPET per-syllable CSV and native config.csv"; ...
        "adapter read + source_mapping IR + dry-run preview"; ...
        "extraction run/artifact/settings provenance"; ...
        "syllable detections and native/canonical measurements"; ...
        "explicit terminal interval missingness"; ...
        "idempotent relational read-back"], ...
    boundaries=prototypeBoundaries(), ...
    project_intake=struct( ...
        status=intake.status, committed=intake.committed, ...
        project_id=intake.project_id, ...
        preview_verdict=projectPreview.verdict, ...
        recording_id=recordingId, ...
        native_recording_id=string(recording.native_recording_id(1)), ...
        source_relative_path=string(recording.source_relative_path(1))), ...
    recording_context=recordingContextRows(conn, recordingId), ...
    adapter_summary=struct( ...
        row_count=adapter.artifact.row_count, ...
        column_count=adapter.artifact.column_count, ...
        lexical_columns=joinText(adapter.artifact.lexical_columns), ...
        checksum_sha256=shortHash(adapter.artifact.checksum_sha256), ...
        extractor_version_status=adapter.extractor_version.status, ...
        adapter_errors=adapter.adapter_error_count, ...
        adapter_warnings=adapter.adapter_warning_count, ...
        valid_for_ingest=adapter.valid_for_ingest), ...
    preview_summary=struct( ...
        verdict=adapterPreview.verdict, ...
        ir_value_count=height(adapter.ir.values), ...
        ir_record_count=height(adapter.ir.records), ...
        ir_issue_count=height(adapter.ir.issues), ...
        ir_issue_codes=joinText(unique(string(adapter.ir.issues.code)))), ...
    settings_summary=settingsSummary(imported, adapter), ...
    settings_capture=adapter.settings.entries(:, ["native_name", "raw_value", ...
        "canonical_setting", "native_unit", "status"]), ...
    import_summary=struct( ...
        ir_valid=imported.plan.export.ir.valid_for_ingest, ...
        ir_source_rows=imported.export.row_count, ...
        plan_status=plan.status, ...
        plan_conflicts=numel(plan.conflicts), ...
        planned_detections=plan.detections.planned, ...
        planned_measurements=plan.detections.measurements_create, ...
        apply_status=imported.status, ...
        committed=imported.committed, ...
        provenance_complete=imported.plan.provenance_complete, ...
        validation_valid=imported.validation.is_valid, ...
        validation_warnings=height(imported.validation.warnings)), ...
    planned_events=plan.events, ...
    validation=imported.validation, ...
    extraction_run_provenance=extractionRunRows(conn), ...
    artifact_provenance=artifactRows(conn), ...
    detections=detectionRows(conn), ...
    measurements=measurementRows(conn), ...
    interval_evidence=intervalRows(conn), ...
    capability_absence=capabilityAbsence(conn, imported), ...
    rerun=rerunSummary, ...
    relocation=relocationSummary, ...
    deepsqueak_appendix=deepsqueakSummary, ...
    co_residence=coResidence, ...
    cross_extractor_concepts=crossExtractorConcepts, ...
    database_inventory=inventory, ...
    foreign_key_violations=foreignKeyViolations, ...
    workspace_root=workspaceRoot, database_path=databasePath, ...
    temporary_artifacts_removed=false);

close(conn);
clear cleanupConnection
removeTree(workspaceRoot);
clear cleanupWorkspace
demonstration.temporary_artifacts_removed = ...
    ~isfolder(workspaceRoot) && ~isfile(databasePath);

if options.Print
    printDemonstration(demonstration);
end
clear cleanupPath
end

