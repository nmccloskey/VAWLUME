function summary = importDeepSqueak(conn, workspaceRoot, repoRoot, recordingRef)
artifactRoot = fullfile(workspaceRoot, "deepsqueak");
exportPath = fullfile(artifactRoot, "exports", "MOUSE001_BASELINE_Stats.xlsx");
makeParentFolder(exportPath);
writecell(deepsqueakExportCells(), exportPath);

settingsPath = fullfile(artifactRoot, "deepsqueak_detection_settings.json");
writeText(settingsPath, jsonencode(struct( ...
    profile=struct(id="demo.deepsqueak.settings.v1", ...
    name="Demonstration DeepSqueak detection settings", ...
    kind="extractor_settings", profile_version="1.0.0"), ...
    detection=struct(score_threshold=0.15, frequency_range_khz=[15, 115]))));

runSpec = struct(run_key="demo_deepsqueak_run_1", extractor_version="3.2.1", ...
    run_label="Demonstration DeepSqueak detection run", ...
    settings=struct(profile_path=settingsPath));
