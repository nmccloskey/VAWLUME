function rows = extractionRunRows(conn)
%EXTRACTIONRUNROWS Run identity, exact versions, and where settings actually live.
%
% The settings column distinguishes three genuinely different states rather than
% collapsing two of them. A profile key means a VAWLUME settings profile version
% is linked to the run. `<native settings artifact>` means the exact native
% config.csv is registered, hashed, and faithfully captured, but the schema has
% no clean edge from that source artifact to a synthesized profile version, so
% none is invented. `<not recoverable>` means the settings are genuinely lost,
% which the MUPET contract never permits at apply time.
rows = fetch(conn, ...
    "SELECT er.run_key, sf.filename AS recording_source, e.extractor_name, " + ...
    "ev.version_label AS extractor_version, " + ...
    "ocp.profile_key AS output_mapping_profile, " + ...
    "ocv.version_label AS profile_version, " + ...
    "substr(ocv.checksum_sha256, 1, 12) AS profile_checksum, " + ...
    "CASE WHEN scp.profile_key IS NOT NULL THEN scp.profile_key " + ...
    "WHEN EXISTS (SELECT 1 FROM extraction_run_artifacts ra " + ...
    "JOIN artifacts a ON a.artifact_id = ra.artifact_id " + ...
    "WHERE ra.extraction_run_id = er.extraction_run_id " + ...
    "AND a.artifact_type = 'extractor_settings') " + ...
    "THEN '<native settings artifact>' " + ...
    "ELSE '<not recoverable>' END AS settings_provenance, " + ...
    "substr(IFNULL(scv.checksum_sha256, ''), 1, 12) AS settings_profile_checksum " + ...
    "FROM extraction_runs er " + ...
    "JOIN extraction_run_inputs eri ON eri.extraction_run_id = er.extraction_run_id " + ...
    "JOIN recordings r ON r.recording_id = eri.recording_id " + ...
    "JOIN source_files sf ON sf.source_file_id = r.source_file_id " + ...
    "JOIN extractor_versions ev ON ev.extractor_version_id = er.extractor_version_id " + ...
    "JOIN extractors e ON e.extractor_id = ev.extractor_id " + ...
    "JOIN config_profile_versions ocv ON ocv.profile_version_id = er.output_mapping_profile_version_id " + ...
    "JOIN config_profiles ocp ON ocp.profile_id = ocv.profile_id " + ...
    "LEFT JOIN config_profile_versions scv ON scv.profile_version_id = er.settings_profile_version_id " + ...
    "LEFT JOIN config_profiles scp ON scp.profile_id = scv.profile_id " + ...
    "ORDER BY er.run_key");
end

function rows = artifactRows(conn)
rows = fetch(conn, ...
    "SELECT e.extractor_name, ra.artifact_role, a.artifact_type, a.path_or_uri, " + ...
    "IFNULL(a.file_format,'') AS file_format, a.is_native, " + ...
    "substr(IFNULL(a.checksum_sha256,''), 1, 12) AS checksum " + ...
    "FROM extraction_run_artifacts ra " + ...
    "JOIN artifacts a ON a.artifact_id = ra.artifact_id " + ...
    "JOIN extraction_runs er ON er.extraction_run_id = ra.extraction_run_id " + ...
    "JOIN extractor_versions ev ON ev.extractor_version_id = er.extractor_version_id " + ...
    "JOIN extractors e ON e.extractor_id = ev.extractor_id " + ...
    "ORDER BY e.extractor_name, ra.artifact_role");
end

function rows = detectionRows(conn)
%DETECTIONROWS MUPET syllables with the exported duration beside the boundaries.
%
% The exported pre-noise-reduction duration is shown next to, never in place of,
% the boundary span. They are different quantities and the import keeps both.
rows = fetch(conn, ...
    "SELECT c.detection_id, c.native_event_id, c.start_time_s, c.end_time_s, " + ...
    "c.duration_s AS boundary_span_s, em.canonical_value_real AS exported_duration_s, " + ...
    "IFNULL(em.operational_variant,'') AS duration_variant, " + ...
    "CASE WHEN c.detection_score IS NULL THEN '<none exported>' " + ...
    "ELSE CAST(c.detection_score AS TEXT) END AS detection_score " + ...
    "FROM v_detection_core c " + ...
    "JOIN event_measurements em ON em.detection_id = c.detection_id " + ...
    "JOIN extractor_features xf ON xf.extractor_feature_id = em.extractor_feature_id " + ...
    "WHERE c.extractor_name = 'MUPET' AND xf.native_name = 'syllable duration (msec)' " + ...
    "ORDER BY CAST(c.native_event_id AS INTEGER)");
end

function rows = measurementRows(conn)
% A compact representative set: the unit-transformed duration with its
% operational variant, three frequency features, and one energy and one
% amplitude measure. Missing values are rendered as missing, because printing a
% numeric zero here would display exactly the fabricated value the storage
% contract exists to prevent.
rows = fetch(conn, ...
    "SELECT d.native_event_id, m.native_name, " + ...
    "CASE WHEN m.native_value_real IS NULL THEN '<missing>' " + ...
    "ELSE CAST(m.native_value_real AS TEXT) END AS native_value, " + ...
    "IFNULL(m.native_unit,'') AS native_unit, " + ...
    "IFNULL(m.canonical_name,'') AS canonical_feature, " + ...
    "CASE WHEN m.canonical_value_real IS NULL THEN '<missing>' " + ...
    "ELSE CAST(m.canonical_value_real AS TEXT) END AS canonical_value, " + ...
    "IFNULL(m.canonical_unit,'') AS canonical_unit, " + ...
    "IFNULL(m.transform_key,'') AS transform_key, " + ...
    "IFNULL(m.operational_variant,'') AS operational_variant, " + ...
    "IFNULL(m.derivation_stage,'') AS derivation_stage " + ...
    "FROM v_event_measurements_long m " + ...
    "JOIN detections d ON d.detection_id = m.detection_id " + ...
    "JOIN v_detection_core c ON c.detection_id = d.detection_id " + ...
    "WHERE c.extractor_name = 'MUPET' AND d.native_event_id = '1' " + ...
    "AND m.native_name IN ('syllable duration (msec)', 'minimum frequency (kHz)', " + ...
    "'maximum frequency (kHz)', 'mean frequency (kHz)', " + ...
    "'total syllable energy (dB)', 'peak syllable amplitude (dB)') " + ...
    "ORDER BY m.native_name");
end

function rows = intervalRows(conn)
%INTERVALROWS The exported inter-syllable interval for every syllable.
%
% The terminal syllable has no following syllable. Its exported NA is kept as
% the raw token with no typed value, rather than becoming a zero interval or a
% VAWLUME-computed substitute.
rows = fetch(conn, ...
    "SELECT d.native_event_id, em.native_value_type, " + ...
    "IFNULL(em.native_raw_token,'') AS native_raw_token, " + ...
    "CASE WHEN em.native_value_real IS NULL THEN '<missing>' " + ...
    "ELSE CAST(em.native_value_real AS TEXT) END AS native_value, " + ...
    "CASE WHEN em.canonical_value_real IS NULL THEN '<missing>' " + ...
    "ELSE CAST(em.canonical_value_real AS TEXT) END AS canonical_value, " + ...
    "IFNULL(xf.derivation_stage,'') AS derivation_stage " + ...
    "FROM event_measurements em " + ...
    "JOIN detections d ON d.detection_id = em.detection_id " + ...
    "JOIN extractor_features xf ON xf.extractor_feature_id = em.extractor_feature_id " + ...
    "WHERE xf.native_name = 'inter-syllable interval (sec)' " + ...
    "ORDER BY CAST(d.native_event_id AS INTEGER)");
end

