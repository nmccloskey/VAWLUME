function rows = coResidenceRows(conn, recordingId)
rows = fetch(conn, ...
    "SELECT c.extractor_name, c.extractor_version, c.extraction_run_key, " + ...
    "COUNT(*) AS detections, " + ...
    "SUM(CASE WHEN c.detection_score IS NULL THEN 0 ELSE 1 END) AS scored, " + ...
    "(SELECT COUNT(*) FROM curation_events ce JOIN detections d2 " + ...
    "ON d2.detection_id = ce.detection_id " + ...
    "WHERE d2.extraction_run_id = c.extraction_run_id) AS curation_rows, " + ...
    "(SELECT COUNT(*) FROM classification_assignments ca JOIN detections d3 " + ...
    "ON d3.detection_id = ca.detection_id " + ...
    "WHERE d3.extraction_run_id = c.extraction_run_id) AS class_assignments " + ...
    "FROM v_detection_core c WHERE c.recording_id = " + string(recordingId) + " " + ...
    "GROUP BY c.extraction_run_id ORDER BY c.extractor_name");
end

function rows = broadConceptRows(conn)
%BROADCONCEPTROWS Which broad canonical concepts each extractor populates.
%
% Availability, not comparison. No pair, overlap, or agreement is computed
% anywhere in this demonstration. frequency_center is included deliberately: it
% is the one concept in this list that only MUPET populates by canonical name,
% because DeepSqueak's contour median is registered under its own canonical name
% rather than asserted to be the same statistic as a filterbank mean.
concepts = ["call_start_time", "call_end_time", "call_duration", ...
    "frequency_min", "frequency_max", "frequency_bandwidth", "frequency_center"];
rows = fetch(conn, ...
    "SELECT m.canonical_name, c.extractor_name, m.native_name, " + ...
    "m.native_unit, m.canonical_unit, m.transform_key " + ...
    "FROM v_event_measurements_long m " + ...
    "JOIN v_detection_core c ON c.detection_id = m.detection_id " + ...
    "WHERE m.canonical_name IN ('" + strjoin(concepts, "','") + "') " + ...
    "GROUP BY m.canonical_name, c.extractor_name " + ...
    "ORDER BY m.canonical_name, c.extractor_name");
end

