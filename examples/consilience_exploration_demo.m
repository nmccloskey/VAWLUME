    inactive_factor_names=string(resolution.inactive_factor_names(:))', ...
    factors=resolution.factors(:, ["factor_name", "is_active", ...
        "inactive_reason", "low_value", "high_value", "value_source", ...
        "strictness_direction", "reference_comparison"]));
end

