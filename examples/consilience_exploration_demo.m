diagnostics = exploration.diagnostics;
value = struct( ...
    candidate_count=diagnostics.surface.candidate_count, ...
    metric_count=numel(diagnostics.surface.metric_names), ...
    quantile_definition=diagnostics.distributions.quantile_definition, ...
    observation_policy=diagnostics.dependencies.observation_policy.mode, ...
    complete_case_n=diagnostics.dependencies.observation_policy.complete_case_n, ...
    redundant_pair_count=height(diagnostics.dependencies.redundancy), ...
