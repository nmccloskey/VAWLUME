    is_stratified=subset.is_stratified, ...
    stratum_field=subset.stratum_field, ...
    fallback_reason=subset.fallback_reason, ...
    requested_size=subset.requested_size, ...
    realized_size=subset.realized_size, ...
    selected_recording_ids=subset.selected_recording_ids(:)', ...
    allocation=subset.allocation, ...
