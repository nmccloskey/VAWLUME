    cross_pattern_comparable=string( ...
        support.comparable_features.cross_pattern_comparable(:))', ...
    extractor_restricted=string( ...
        support.comparable_features.extractor_restricted(:))', ...
    pair_pattern_row_count=height(support.primary.pair_patterns));
end

