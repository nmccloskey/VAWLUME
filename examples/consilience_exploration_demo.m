function value = degenerateCases(exploration)
%DEGENERATECASES The places this dataset is too thin, stated positively.
screen = exploration.screen;
patterns = exploration.support_patterns.primary.patterns;
value = struct( ...
    screen_makes_no_leverage_claim= ...
        ~any(ismember(screen.leverage.categories.category, ...
        ["high_leverage", "moderate_leverage", "low_leverage"])), ...
    screen_main_effects_are_aliased=screen.leverage.main_effects_are_aliased, ...
    empty_support_patterns=patterns.extractor_set_label(patterns.is_absent)', ...
    example_shortfall_pattern_count= ...
        height(exploration.examples.sample.short_patterns));
end

% ---------------------------------------------------------------- fixture ---
%
% Six recordings, each carrying one extraction run per extractor, plus a
% recording-level genotype attribute over five of them. The sizes differ on
% purpose: equal recordings would let a pooled fraction and an averaged one agree
% exactly, and the response layer's pooling rule would go untested here too. The
% sixth recording carries no genotype, so the stratified sample has to represent
% "(missing)" rather than drop it.

function extendProject(conn)
execute(conn, "INSERT INTO extraction_runs(extraction_run_id,project_id," + ...
    "extractor_version_id,run_key,status) VALUES" + ...
    "(80,1,2,'demo_mupet_baseline_v1','imported')," + ...
    "(81,1,3,'demo_usvseg_baseline_v1','imported')");
execute(conn, "INSERT INTO extraction_run_inputs(extraction_run_id," + ...
    "recording_id,input_role) VALUES(80,2,'source_audio'),(81,2,'source_audio')");
insertDetection(conn, 3, 2, "demo-ds-baseline-2", 20.000, 20.060);
insertDetection(conn, 80, 2, "demo-mupet-baseline-1", 20.004, 20.052);
insertDetection(conn, 81, 2, "demo-usvseg-baseline-1", 20.002, 20.049);
insertDetection(conn, 81, 2, "demo-usvseg-baseline-3", 30.000, 30.040);

sourceFileId = nextId(conn, "source_files", "source_file_id");
runId = 90;
for recordingId = 3:6
    native = sprintf("REC_DEMO_%02d", recordingId);
    execute(conn, "INSERT INTO source_files(source_file_id,project_id," + ...
        "file_role,path_or_uri,relative_path,filename) VALUES(" + ...
        string(sourceFileId) + ",1,'recording_audio','audio/" + native + ...
        ".wav','audio/" + native + ".wav','" + native + ".wav')");
    execute(conn, "INSERT INTO recordings(recording_id,project_id," + ...
        "source_file_id,native_recording_id) VALUES(" + string(recordingId) + ...
        ",1," + string(sourceFileId) + ",'" + native + "')");
    sourceFileId = sourceFileId + 1;
    for versionId = 1:3
        execute(conn, "INSERT INTO extraction_runs(extraction_run_id," + ...
            "project_id,extractor_version_id,run_key,status) VALUES(" + ...
            string(runId) + ",1," + string(versionId) + ",'demo_extra_r" + ...
            string(recordingId) + "_v" + string(versionId) + "','imported')");
        execute(conn, "INSERT INTO extraction_run_inputs(extraction_run_id," + ...
            "recording_id,input_role) VALUES(" + string(runId) + "," + ...
            string(recordingId) + ",'source_audio')");
        callCount = 2 + mod(recordingId + versionId, 3);
        for call = 1:callCount
            base = 5 * call + 0.01 * versionId;
            insertDetection(conn, runId, recordingId, ...
                sprintf("demo-r%d-v%d-%d", recordingId, versionId, call), ...
                base, base + 0.05 + 0.005 * versionId);
        end
        runId = runId + 1;
    end
end

genotype = ["WT", "KO", "WT", "KO", "WT"];
for recordingId = 1:numel(genotype)
    execute(conn, "INSERT INTO recording_attributes(recording_id," + ...
        "attribute_name,value_type,value_text) VALUES(" + ...
        string(recordingId) + ",'genotype','text','" + ...
        genotype(recordingId) + "')");
end
end

function path = writeGalleryAudio(conn, sourceRoot)
%WRITEGALLERYAUDIO A real WAV for the one recording the gallery draws from.
%
% The spectrogram is computed from the original audio, never from an
% extractor-rendered image, so the gallery needs a readable file. The recording's
% declared sample rate is lowered to match the file it is given, and the tone
% bursts sit where the fixture's detections are so the images show something.
sampleRate = 192000;
execute(conn, "UPDATE recordings SET sample_rate_hz=" + string(sampleRate) + ...
    " WHERE recording_id=1");
relative = string(fetch(conn, "SELECT sf.relative_path FROM recordings r " + ...
    "JOIN source_files sf ON sf.source_file_id=r.source_file_id " + ...
    "WHERE r.recording_id=1").relative_path(1));
path = fullfile(sourceRoot, replace(relative, "/", filesep));
if ~isfolder(fileparts(path)), mkdir(fileparts(path)); end

bursts = fetch(conn, "SELECT MIN(start_time_s) AS t0, MAX(end_time_s) AS t1 " + ...
    "FROM detections WHERE recording_id=1 GROUP BY " + ...
    "CAST(start_time_s AS INTEGER) / 5");
durationS = max(double(bursts.t1)) + 1;
n = round(durationS * sampleRate);
t = (0:(n - 1))' / sampleRate;
samples = zeros(n, 1);
for index = 1:height(bursts)
    window = t >= (double(bursts.t0(index)) - 0.01) & ...
        t <= (double(bursts.t1(index)) + 0.01);
    local = t(window) - t(find(window, 1));
    span = max(local(end) - local(1), eps);
    taper = sin(pi * local / span) .^ 2;
    samples(window) = 0.7 * taper .* sin(2 * pi * 62000 * t(window));
end
audiowrite(char(path), samples, sampleRate, BitsPerSample=16);
end

function value = nextId(conn, tableName, column)
rows = fetch(conn, "SELECT IFNULL(MAX(" + column + "),0) + 1 AS n FROM " + ...
    tableName);
value = double(rows.n(1));
end

function insertDetection(conn, runId, recordingId, nativeId, startS, endS)
execute(conn, "INSERT INTO detections(extraction_run_id,recording_id," + ...
    "native_event_id,start_time_s,end_time_s,timing_basis) VALUES(" + ...
    string(runId) + "," + string(recordingId) + ",'" + nativeId + "'," + ...
    sprintf("%.17g", startS) + "," + sprintf("%.17g", endS) + ...
    ",'profile_selected_event_geometry')");
end

% -------------------------------------------------------------- utilities ---

function value = splitJoined(values)
value = strings(0, 1);
for entry = string(values(:))'
    parts = split(entry, "|");
    value = [value; parts(strlength(parts) > 0)]; %#ok<AGROW>
end
value = unique(value);
end

function value = fileBytes(path)
value = 0;
listing = dir(path);
if ~isempty(listing)
    value = listing(1).bytes;
end
end

function root = normalizedRepoRoot(root)
if strlength(root) == 0, root = fileparts(fileparts(mfilename("fullpath"))); end
try
    root = string(java.io.File(char(root)).getCanonicalPath());
catch
end
end

function value = pathContains(target)
value = any(split(string(path), pathsep) == string(target));
end

function restoreSourcePath(sourcePath, shouldRemove)
if shouldRemove && pathContains(sourcePath), rmpath(sourcePath); end
end

function closeConnection(conn)
try
    if isopen(conn), close(conn); end
catch
end
end

function removeTree(root)
if isfolder(root), rmdir(root, "s"); end
end

function printDemonstration(value)
disp("VAWLUME EXTRACTOR-CONSILIENCE EXPLORATION DEMONSTRATION")
disp(value.calibration_boundary)
fprintf("Exploration run '%s': %s\n", value.exploration_run_key, value.status);
disp("Dataset:")
disp(value.dataset)
disp("Probe factors (the workflow chose these; none is optimal):")
disp(value.probe.factors)
fprintf(['Whole-dataset screen: %s, %d configurations, resolution %d, main ' ...
    'effects clear of two-factor interactions: %d\n'], ...
    value.screen.design_type, value.screen.configuration_count, ...
    value.screen.design_resolution, ...
    value.screen.main_effects_clear_of_two_factor_interactions);
fprintf("Subset: stratified=%d on '%s', %d of a requested %d recording(s)\n", ...
    value.subset.is_stratified, value.subset.stratum_field, ...
    value.subset.realized_size, value.subset.requested_size);
fprintf(['Subset probe: %s, %d configurations; %d effect(s) de-aliased by ' ...
    'the subset\n'], value.subset.probe.design_type, ...
    value.subset.probe.configuration_count, value.subset.de_aliased_count);
disp("Leverage categories, whole-dataset screen:")
disp(value.screen.leverage_counts)
disp("Leverage categories, subset probe:")
disp(value.subset.probe.leverage_counts)
fprintf("Probe concordance: %d factor-response rows, no composite score\n", ...
    value.concordance.comparison_row_count);
disp("Exact support patterns at the reference configuration:")
disp(value.support_patterns.patterns)
fprintf("Comparable across every pattern: %s\n", ...
    strjoin(value.support_patterns.cross_pattern_comparable, ", "));
fprintf("Extractor-restricted, within eligible patterns only: %s\n", ...
    strjoin(value.support_patterns.extractor_restricted, ", "));
fprintf(['Gallery: %d example(s), %d rendered, %d image(s), %d index ' ...
    'column(s); frequency extents: %s\n'], ...
    value.examples.example_count, value.examples.success_count, ...
    value.examples.image_count, value.examples.index_column_count, ...
    strjoin(value.examples.frequency_extent_sources, ", "));
if height(value.examples.short_patterns) > 0
    disp("Patterns with fewer examples than requested (reported, not padded):")
    disp(value.examples.short_patterns)
end
if height(value.examples.empty_patterns) > 0
    disp("Patterns with no members at all:")
    disp(value.examples.empty_patterns)
end
fprintf("Exports: %d table(s), %d figure(s), provenance written: %d\n", ...
    value.exports.table_count, value.exports.figure_count, ...
    value.exports.provenance_written);
if height(value.exports.figures_not_drawn) > 0
    disp("Figures not drawn (a vawlume:eda: identifier is a refusal on thin " + ...
        "data; anything else is a defect worth reporting):")
    disp(value.exports.figures_not_drawn)
end
fprintf("Stage skipping: requested '%s'; ran %s; probe executed: %d\n", ...
    value.stage_skipping.requested, ...
    strjoin(value.stage_skipping.stages_run, ", "), ...
    value.stage_skipping.probe_executed);
fprintf(['Pricing without running: %s; screen %s/%d cfg = %d analyses, ' ...
    'subset = %d analyses; nothing exported: %d\n'], ...
    value.planning.status, value.planning.screen_design_type, ...
    value.planning.screen_configuration_count, ...
    value.planning.screen_predicted_analyses, ...
    value.planning.subset_predicted_analyses, ...
    value.planning.nothing_exported);
fprintf("Temporary artifacts removed: %d\n", value.temporary_artifacts_removed);
fprintf("Proves:\n  %s\n", strjoin(value.proves, newline + "  "));
fprintf("Does not prove:\n  %s\n", ...
    strjoin(value.does_not_prove, newline + "  "));
fprintf("%s\n", strjoin(string(value.caution), newline));
end
