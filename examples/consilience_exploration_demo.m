function demonstration = consilience_exploration_demo(options)
%CONSILIENCE_EXPLORATION_DEMO Demonstrate the extractor-consilience exploration.
%
% DEMONSTRATION = CONSILIENCE_EXPLORATION_DEMO() runs the complete exploratory
% workflow over a disposable six-recording synthetic project:
%
%   1. resolve the dataset and apply the tracked reference configuration;
%   2. diagnose the candidate-metric space - distributions, Pearson, Spearman,
%      partial correlation, coverage and redundancy;
%   3. resolve which threshold dimensions to screen and at what values;
%   4. run a bounded interaction-aware screen over the whole dataset;
%   5. draw a seeded, metadata-stratified subset of recordings;
%   6. run a richer probe on it and compare the two probes;
%   7. characterize exact extractor-support patterns at the reference;
%   8. render a representative spectrogram gallery;
%   9. export tables, figures, the example index and provenance.
%
% It then runs the workflow again with Stages="diagnostics" to show that a stage
% can be run on its own without building a design or executing a probe.
%
% WHAT THE DEMONSTRATION IS FOR. It proves the path works on real public
% functions and that its automatic choices are reproducible. It proves nothing
% about vocalizations: the recordings are synthetic, the detections were written
% by hand to exercise the matcher, and every threshold in the tracked reference
% configuration is an illustrative demonstration value.
%
% IT DELIBERATELY SHOWS THIN DATA. The whole-dataset screen is capped at four
% configurations, which over three factors is a resolution-III fraction whose
% main effects are aliased with two-factor interactions - so the screen makes no
% leverage claim about any factor and says so, and the full-factorial subset
% probe de-aliases part of it. Several exact support patterns hold too few
% groups to sample the requested number of examples from, and the shortfall is
% reported rather than padded from a neighbouring pattern. A demonstration that
% only ever showed the happy path would teach users to be surprised by their own
% data.
%
% Name-value options:
%   Print     print compact developer-facing read-backs (default true)
%   RepoRoot  repository root, inferred from this file by default
%
% See also VAWLUME.EDA.RUNEXPLORATION, MULTI_EXTRACTOR_AGREEMENT_DEMO.

arguments
    options.Print (1,1) logical = true
    options.RepoRoot (1,1) string = ""
end

repoRoot = normalizedRepoRoot(options.RepoRoot);
sourcePath = fullfile(repoRoot, "src");
removeSourcePath = ~pathContains(sourcePath);
if removeSourcePath, addpath(sourcePath); end
cleanupPath = onCleanup(@() restoreSourcePath(sourcePath, removeSourcePath));

workspaceRoot = fullfile(tempdir, ...
    "VAWLUME consilience exploration demo " + string(java.util.UUID.randomUUID));
mkdir(workspaceRoot);
cleanupWorkspace = onCleanup(@() removeTree(workspaceRoot));
databasePath = fullfile(workspaceRoot, "consilience_exploration_demo.sqlite");

% 1. A disposable six-recording project. The tracked Phase 1 fixture supplies
%    one richly populated recording; the rest exist so a subset can be a subset
%    and a stratum can be a stratum.
[conn, ~] = vawlume.db.createPhase1FixtureDatabase(databasePath, repoRoot);
cleanupConnection = onCleanup(@() closeConnection(conn));
extendProject(conn);
sourceRoot = fullfile(workspaceRoot, "source");
audioPath = writeGalleryAudio(conn, sourceRoot);

% 2. The whole workflow, from one call. The user-facing configuration is the
%    light one: a seed, a subset size, and one factor switched off - the last
%    two only to keep the demonstration affordable enough to run as a test.
%    Everything else - which factors to screen, at what values, which metadata
%    field to stratify on, how the design is constructed - the workflow decides
%    and records.
explorationOptions = vawlume.eda.explorationOptions(struct( ...
    seed=20260918, ...
    subset_size=3, ...
    disabled_factors="max_abs_duration_difference_s"));
outputRoot = fullfile(workspaceRoot, "output");

exploration = vawlume.eda.runExploration(conn, ...
    struct(project_key="phase1_synthetic_fixture"), ...
    Options=explorationOptions, RepoRoot=repoRoot, OutputRoot=outputRoot, ...
    SourceRoot=sourceRoot, ...
    MaximumConfigurations=4, ...       % forces the fraction; see the note above
    ExamplesPerPattern=2, ExampleRecordingId=1, ...
    ResolutionDpi=96, Print=options.Print);

% 3. One stage on its own. The diagnostics need the reference run's candidate
%    pairs and nothing else, so no design is built and no probe is executed.
diagnosticsOnly = vawlume.eda.runExploration(conn, ...
    struct(project_key="phase1_synthetic_fixture"), ...
    Options=explorationOptions, RepoRoot=repoRoot, OutputRoot=outputRoot, ...
    Stages="diagnostics", Print=false);

% 4. Pricing a probe without running it. Apply=false builds both designs and
%    reports what executing them would cost, and writes no analysis, no export
%    and no provenance record. In practice a user does this BEFORE committing to
%    a probe; it comes last here only because the demonstration has one database
%    and the assertion worth making is that the estimate matches what step 2
%    actually executed. The diagnostics are pointed at the reference run's own
%    analyses so the probe values are the same ones step 2 resolved.
planned = vawlume.eda.runExploration(conn, ...
    struct(project_key="phase1_synthetic_fixture"), ...
    Options=explorationOptions, RepoRoot=repoRoot, OutputRoot=outputRoot, ...
    MaximumConfigurations=4, Apply=false, Print=false, ...
    DiagnosticAnalyses=exploration.reference.matching_run_keys);

demonstration = struct( ...
    architecture=["resolve dataset"; "apply reference configuration"; ...
        "full-dataset diagnostics"; "resolve probe values"; ...
        "bounded whole-dataset screen"; "stratified recording subset"; ...
        "richer subset probe"; "probe concordance"; ...
        "exact support-pattern characterization"; ...
        "representative spectrogram gallery"; ...
        "tables, figures, example index, provenance"], ...
    calibration_boundary="Illustrative synthetic prototype settings. No " + ...
        "configuration explored here is optimal, validated, recommended, or " + ...
        "calibrated, and agreement among extractors is methodological " + ...
        "evidence rather than ground truth.", ...
    exploration_run_key=exploration.exploration_run_key, ...
    status=exploration.status, ...
    stages=exploration.stages, ...
    dataset=datasetSummary(exploration), ...
    diagnostics=diagnosticsSummary(exploration), ...
    probe=probeSummary(exploration), ...
    screen=probeSummary2(exploration.screen), ...
    subset=subsetSummary(exploration), ...
    concordance=concordanceSummary(exploration), ...
    support_patterns=supportSummary(exploration), ...
    examples=exampleSummary(exploration), ...
    exports=exportSummary(exploration), ...
    stage_skipping=struct( ...
        requested="diagnostics", ...
        stages_run=diagnosticsOnly.stages.stage( ...
            diagnosticsOnly.stages.status == "completed")', ...
        design_built=isfield(diagnosticsOnly, "screen"), ...
        probe_executed=isfield(diagnosticsOnly, "subset"), ...
        status=diagnosticsOnly.status), ...
    planning=struct( ...
        status=planned.status, ...
        screen_design_type=planned.screen.design.design_type, ...
        screen_configuration_count=planned.screen.design.configuration_count, ...
        screen_predicted_analyses=planned.screen.cost.total_analyses, ...
        subset_predicted_analyses=planned.subset.cost.total_analyses, ...
        nothing_exported=~isfield(planned, "exports"), ...
        skipped_reasons=planned.stages.reason( ...
            planned.stages.status == "skipped")'), ...
    honest_degenerate_cases=degenerateCases(exploration), ...
    proves=[ ...
        "one call carries a dataset from diagnostics to an exported poster bundle"; ...
        "every automatic choice - factors, probe values, subset, seed, design - is recorded"; ...
        "the two sensitivity probes are compared as a table and never as a score"; ...
        "exact extractor-support patterns survive to the figures uncollapsed"; ...
        "USVSEG annotations carry a time extent and measured markers, never a synthesized band"; ...
        "a stage can be run on its own without executing a probe"], ...
    does_not_prove=[ ...
        "that any threshold is calibrated, recommended, or optimal"; ...
        "that agreement among extractors establishes that a detection is real"; ...
        "that an extractor-unique detection is false"; ...
        "that agreement between the two probes removes the need for calibration"; ...
        "anything about vocalizations: the fixture is synthetic"], ...
    caution=exploration.caution, ...
    workspace_root=workspaceRoot, database_path=databasePath, ...
    audio_path=audioPath, temporary_artifacts_removed=false);

close(conn);
clear cleanupConnection
removeTree(workspaceRoot);
clear cleanupWorkspace
demonstration.temporary_artifacts_removed = ...
    ~isfolder(workspaceRoot) && ~isfile(databasePath);

if options.Print, printDemonstration(demonstration); end
clear cleanupPath
end

% ------------------------------------------------------------- read-backs ---

function value = datasetSummary(exploration)
dataset = exploration.dataset;
value = struct( ...
    project_key=dataset.project_key, ...
    recording_count=dataset.recording_count, ...
    extractor_keys=string(dataset.extractor_keys(:))', ...
    pairs_per_recording=dataset.pairs_per_recording, ...
    excluded_recording_count=height(dataset.excluded_recordings));
end

