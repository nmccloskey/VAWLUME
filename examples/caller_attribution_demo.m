function value = deriveConsensusEvents(conn, repoRoot)
%DERIVECONSENSUSEVENTS The second target kind, derived rather than declared.
result = vawlume.matching.compare(conn, struct(recording_id=1), ...
    struct(run_a="demo-primary", run_b="demo-secondary"), ...
    struct(run_key="demo-attribution-match", ...
        run_label="Matching that supplies consensus targets"), ...
    RepoRoot=repoRoot, Apply=true);
rows = fetch(conn, "SELECT consensus_event_id, start_time_s, end_time_s, " + ...
    "derivation_method FROM consensus_events WHERE analysis_run_id=" + ...
    string(result.analysis.analysis_run_id) + ...
    " ORDER BY start_time_s LIMIT 2");
