    matching_analysis_run_id=double(result.analysis.analysis_run_id), ...
    matching_status=string(result.status), ...
    consensus_event_ids=double(rows.consensus_event_id), ...
    intervals=[double(rows.start_time_s), double(rows.end_time_s)], ...
    derivation_method=unique(string(rows.derivation_method)), ...
    events=rows);
end

% ============================================================ exporter clock ===

function value = establishExporterClock(conn, workspace, repoRoot)
%ESTABLISHEXPORTERCLOCK Relate the exporting system's clock to the recording's.
%
% The transform is fitted through the public alignment layer rather than written
% by hand, because the claim this example makes about clocks is that attribution
% reaches them through one shared API and adds no correction of its own.
truth = exporterClockTruth();
writeAnchorTable(fullfile(workspace, "sync_anchors.csv"), truth);
anchorProfilePath = writeAnchorProfile(workspace, repoRoot);
manifestPath = writeManifest(workspace, anchorProfilePath);

intake = vawlume.ingest.alignment(conn, manifestPath, ...
    RepoRoot=repoRoot, SourceRoot=workspace, Apply=true);
fitResult = vawlume.alignment.fit(conn, alignmentRef(), ...
    SourceTimebase="attribution_native", Breakpoints=truth.breakpoint, Apply=true);
qc = vawlume.alignment.report(conn, alignmentRef());
transform = qc.transforms(qc.transforms.source_timebase_key == ...
    "attribution_native", :);
segments = qc.segments(qc.segments.source_timebase_key == ...
    "attribution_native", :);

value = struct( ...
    source_timebase="attribution_native", ...
    reference_timebase=string(qc.reference_timebase.timebase_key(1)), ...
    alignment_run_id=double(transform.alignment_run_id(1)), ...
    method=string(transform.method(1)), ...
    status=string(transform.status(1)), ...
    anchor_count=double(intake.anchor_summary.anchor_count), ...
    anchored_source_range=[min(truth.source_times), max(truth.source_times)], ...
    breakpoint=truth.breakpoint, ...
    recovered=table(segments.segment_index, segments.scale, truth.scale, ...
        segments.offset_s, truth.offset_s, ...
        abs(segments.scale - truth.scale), ...
        abs(segments.offset_s - truth.offset_s), ...
        VariableNames=["segment_index", "scale", "expected_scale", ...
        "offset_s", "expected_offset_s", "scale_absolute_error", ...
        "offset_absolute_error_s"]), ...
    crossing_window=[34.90, 35.30], ...
    fit_status=string(fitResult.status), ...
    note="A fitted transform is estimated, never validated.");
end

function truth = exporterClockTruth()
truth = struct();
truth.breakpoint = 35;
truth.scale = [1.002; 0.998];
truth.offset_s = [5.00; (truth.scale(1) - truth.scale(2)) * truth.breakpoint + 5.00];
truth.source_times = [5; 15; 25; 35; 45; 55];
segment = 1 + double(truth.source_times >= truth.breakpoint);
truth.reference_times = truth.scale(segment) .* truth.source_times + ...
    truth.offset_s(segment);
truth.anchor_keys = "sync" + compose("%02d", (1:numel(truth.source_times))');
end

function writeAnchorTable(pathValue, truth)
count = numel(truth.anchor_keys);
markers = strings(2 * count, 1);
streams = strings(2 * count, 1);
timestamps = strings(2 * count, 1);
roles = repmat("primary", 2 * count, 1);
included = repmat("true", 2 * count, 1);
classes = repmat("device_level", 2 * count, 1);
row = 0;
for index = 1:count
    row = row + 1;
    markers(row) = truth.anchor_keys(index);
    streams(row) = "attribution";
    timestamps(row) = compose("%.9f", truth.source_times(index));
    row = row + 1;
    markers(row) = truth.anchor_keys(index);
    streams(row) = "audio";
    timestamps(row) = compose("%.9f", truth.reference_times(index));
end
writetable(table(markers, streams, timestamps, roles, included, classes, ...
    VariableNames=["marker", "stream", "timestamp_s", "role", "include", ...
    "evidence_class"]), pathValue, QuoteStrings="minimal");
end

