% ========================================================= identity evidence ===

function value = registerIdentityEvidence(conn, workspace, repoRoot)
%REGISTERIDENTITYEVIDENCE The statement the visual-identity evidence will cite.
%
% Registered through the Phase 2 tracking layer rather than asserted, because a
% candidate-level identity row must name the association it read. A native track
% label is not a canonical entity, and the association is where that distinction
% is recorded together with its uncertainty.
vawlume.geometry.registerCoordinateSystem(conn, ...
    struct(project_key="caller_attribution_demo"), struct( ...
    coordinate_system_key="arena_2d", coordinate_system_name="Synthetic arena", ...
    dimensionality=2, unit="cm"));

artifactPath = fullfile(workspace, "tracking.csv");
writetable(table([0; 10; 20; 40; 60; 80], repmat("track_a", 6, 1), ...
    repmat("snout", 6, 1), [0; 1; 2; 3; 4; 5], repmat(10, 6, 1), ...
    repmat(0.73, 6, 1), VariableNames=["time_s", "track", "bodypart", ...
    "x", "y", "likelihood"]), artifactPath, QuoteStrings="minimal");

profilePath = fullfile(workspace, "tracking_profile.json");
profile = jsondecode(fileread(fullfile(repoRoot, "config", ...
    "01_mapping_profiles", "tracking", "generic_tracking_mapping_profile.json")));
profile.profiles.columns.track_label.source_field = "track";
writeText(profilePath, string(jsonencode(profile, PrettyPrint=true)) + newline);

registration = vawlume.tracking.register(conn, struct(recording_id=1), ...
    struct(artifact_path="tracking.csv", profile_path=profilePath, ...
    timebase_key="audio_native"), Apply=true, RepoRoot=repoRoot, ...
    SourceRoot=workspace);
streamRef = struct(project_key="caller_attribution_demo", ...
    stream_name="tracking_primary");
association = vawlume.tracking.registerIdentityAssociation(conn, streamRef, ...
    struct(native_track_id="track_a", entity_native_id="A", ...
    start_time_native=0, end_time_native=80, ...
    assignment_state="candidate", evidence_kind="reidentification_score", ...
    identity_value=0.55, ...
    identity_value_semantics="cosine_similarity_of_appearance_embeddings", ...
    calibration_status="uncalibrated", review_state="unreviewed"));

alignmentRun = fetch(conn, "SELECT alignment_run_id FROM time_alignment_runs " + ...
    "ORDER BY alignment_run_id LIMIT 1");
value = struct( ...
    association_id=double(association.tracking_identity_association_id), ...
