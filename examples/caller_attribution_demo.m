function [refusals, captured] = recordRefusal(refusals, description, action)
%RECORDREFUSAL Exercise a path that must refuse, and keep what it said.
%
% The Phase 3 demonstration's most useful single element was a source clock that
% failed with a named reason beside two that succeeded. These are this phase's.
try
    action();
    error("vawlume:examples:RefusalNotRaised", ...
        "Expected a refusal for: %s", description);
catch exception
    if exception.identifier == "vawlume:examples:RefusalNotRaised"
        rethrow(exception);
    end
    captured = struct(raised=true, identifier=string(exception.identifier), ...
        message=string(exception.message));
end
refusals = [refusals; table(string(description), captured.identifier, ...
    firstSentence(captured.message), VariableNames=["what_was_attempted", ...
    "identifier", "message"])];
end

function value = firstSentence(message)
