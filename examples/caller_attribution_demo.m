function demonstration = caller_attribution_demo(options)
%CALLER_ATTRIBUTION_DEMO Demonstrate the integrated Phase 4 attribution path.
%
% DEMONSTRATION = CALLER_ATTRIBUTION_DEMO() creates a disposable synthetic
% session and exercises the whole caller-attribution path on it: a recording with
% three participating entities and two channels, VAWLUME detections and derived
% consensus events as the two target kinds, an external attribution export on the
% exporting system's own clock, a piecewise-affine transform relating that clock
% to the recording's, correspondence across it, multi-candidate results, evidence
% in four dimensions that is never combined, and decisions under two policies.
%
% The refusals are demonstrated beside the successes, because a path that shows
% only what works teaches a reader that everything works. Four are exercised by
% name: an imported caller label that resolves to no participating entity, a
% correspondence with no clock declaration, a second correspondence apply, and a
% candidate appended to a completed run.
%
% Nothing here is calibrated and nothing is validated. Every threshold is an
% illustrative prototype value, every number is synthetic, and no result is
% evidence that any animal called. All inputs are created under the system
% temporary directory and removed before return.
%
% Name-value options:
%   Print     print compact developer-facing read-backs (default true)
%   RepoRoot  repository root, inferred from this file by default
%
% See also TEMPORAL_ALIGNMENT_DEMO, MULTIMODAL_INTEGRATION_DEMO

arguments
    options.Print (1,1) logical = true
    options.RepoRoot (1,1) string = ""
end

repoRoot = normalizedRepoRoot(options.RepoRoot);
sourcePath = fullfile(repoRoot, "src");
removeSourcePath = ~pathContains(sourcePath);
if removeSourcePath, addpath(sourcePath); end
cleanupPath = onCleanup(@() restoreSourcePath(sourcePath, removeSourcePath));

workspace = fullfile(tempdir, "VAWLUME phase 4 caller attribution demo " + ...
    string(java.util.UUID.randomUUID));
mkdir(workspace);
cleanupWorkspace = onCleanup(@() removeTree(workspace));
databasePath = fullfile(workspace, "caller_attribution_demo.sqlite");
conn = sqlite(char(databasePath), "create");
cleanupConnection = onCleanup(@() closeConnection(conn));

vawlume.db.applySchema(conn, fullfile(repoRoot, "schema", "schema.sql"));
vawlume.db.registerBuiltinSemantics(conn, repoRoot);

session = seedSession(conn);
channels = registerChannels(conn);
consensus = deriveConsensusEvents(conn, repoRoot);
exporterClock = establishExporterClock(conn, workspace, repoRoot);
identity = registerIdentityEvidence(conn, workspace, repoRoot);
profilePath = writeExporterProfile(workspace, repoRoot);

refusals = emptyRefusals();

% --- Run A: the imported path over extractor-native detections --------------

detectionRun = createDetectionRun(conn);
[refusals, rejectedImport] = recordRefusal(refusals, ...
    "an imported label naming an animal that was not in this recording", ...
    @() vawlume.ingest.attribution(conn, detectionRunRef(), ...
        writeRejectedExport(workspace), ProfilePath=profilePath, ...
        RepoRoot=repoRoot, Apply=true));

exportPath = writeExport(workspace);
importPreview = vawlume.ingest.attribution(conn, detectionRunRef(), ...
    exportPath, ProfilePath=profilePath, RepoRoot=repoRoot);
importResult = vawlume.ingest.attribution(conn, detectionRunRef(), ...
    exportPath, ProfilePath=profilePath, RepoRoot=repoRoot, Apply=true);

refusals = recordRefusal(refusals, ...
    "a correspondence that did not say how the two clocks relate", ...
    @() vawlume.attribution.correspondWindows(conn, detectionRunRef()));

correspondence = vawlume.attribution.correspondWindows(conn, detectionRunRef(), ...
    AlignmentRun=exporterClock.alignment_run_id, RepoRoot=repoRoot, Apply=true);

refusals = recordRefusal(refusals, ...
    "a second correspondence apply over the same run", ...
    @() vawlume.attribution.correspondWindows(conn, detectionRunRef(), ...
        AlignmentRun=exporterClock.alignment_run_id, RepoRoot=repoRoot, Apply=true));

crossing = vawlume.alignment.applyTransformInterval(conn, ...
    exporterClock.alignment_run_id, exporterClock.crossing_window(1), exporterClock.crossing_window(2));

candidates = addDetectionCandidates(conn, detectionRun.target_ids);
evidence = addFourDimensionEvidence(conn, ...
    candidates.four_dimension_candidate_id, identity);

decidedTargets = detectionRun.target_ids([1 3 4 5 6 7]);
shippedDecision = vawlume.attribution.decide(conn, detectionRunRef(), ...
    struct(), RepoRoot=repoRoot, Apply=true, Targets=decidedTargets, ...
    Exclusions=struct(attribution_target_id=detectionRun.target_ids(6), ...
        reason="channel 2 clipped through this call"));

candidatesBefore = candidateFingerprint(conn, detectionRun.attribution_run_id);
relaxedPolicyPath = writeRelaxedPolicy(workspace, repoRoot);
relaxedDecision = vawlume.attribution.decide(conn, detectionRunRef(), ...
    struct(profile_path=relaxedPolicyPath), RepoRoot=repoRoot, Apply=true, ...
    Targets=decidedTargets);
candidatesAfter = candidateFingerprint(conn, detectionRun.attribution_run_id);
policyComparison = comparePolicies(shippedDecision, relaxedDecision, ...
    candidatesBefore, candidatesAfter);

detectionReport = vawlume.attribution.report(conn, detectionRunRef());

% --- Run B: the same representation over VAWLUME consensus events ----------

consensusRun = createConsensusRun(conn, consensus);
consensusExport = writeConsensusExport(workspace, consensus);
consensusImport = vawlume.ingest.attribution(conn, consensusRunRef(), ...
    consensusExport, ProfilePath=profilePath, RepoRoot=repoRoot, Apply=true);
consensusCorrespondence = vawlume.attribution.correspondWindows(conn, ...
    consensusRunRef(), SameClock=true, RepoRoot=repoRoot, Apply=true);
addConsensusCandidates(conn, consensusRun.target_ids);
consensusDecision = vawlume.attribution.decide(conn, consensusRunRef(), ...
    struct(), RepoRoot=repoRoot, Apply=true);

refusals = recordRefusal(refusals, ...
    "a candidate appended after the run's evidence was frozen", ...
    @() vawlume.attribution.addCandidates(conn, ...
        struct(attribution_target_id=consensusRun.target_ids(1)), ...
        table(3, VariableNames="entity_id"), Apply=true));

consensusReport = vawlume.attribution.report(conn, consensusRunRef());

% --- Read-back, QC and the boundaries -------------------------------------

inventory = databaseInventory(conn);
foreignKeyCheck = fetch(conn, "PRAGMA foreign_key_check");

demonstration = struct( ...
    calibration_boundary="Every threshold, score and probability here is a " + ...
        "synthetic illustrative value. Attribution is estimated, never " + ...
        "validated, and no decision below means an animal called.", ...
    session=session, channels=channels, ...
    exporter_clock=exporterClock, identity_evidence=identity, ...
    detection_run=struct(preview_status=detectionRun.preview_status, ...
        status=detectionRun.status, ...
        attribution_run_id=detectionRun.attribution_run_id, ...
        target_count=height(detectionRun.targets), ...
        stored_target_set_matches=detectionRun.stored_target_set_matches), ...
    consensus=consensus, ...
    mapping_profile=importResult.profile, ...
    rejected_import=rejectedImport, ...
    import_preview=struct(status=importPreview.status, ...
        window_count=height(importPreview.windows), ...
        claim_count=height(importPreview.claims), ...
        unmapped_rows=importPreview.unmapped_rows, ...
        issues=importPreview.issues, wrote_nothing=~importPreview.committed), ...
    import=struct(status=importResult.status, ...
        applied_counts=importResult.applied_counts, ...
        exporting_system=importResult.exporting_system, ...
        source_checksum=importResult.source.checksum_sha256), ...
    correspondence=struct(status=correspondence.status, ...
        iou_basis=correspondence.iou_basis, ...
        alignment_run_id=correspondence.alignment_run_id, ...
        rule=correspondence.rule, ...
        rows=correspondenceReadback(correspondence.correspondences), ...
        windows_without_correspondence= ...
            correspondence.windows_without_correspondence, ...
        ambiguous_window_count=correspondence.ambiguous_window_count), ...
    breakpoint_crossing=crossing, ...
    candidates=candidates, evidence=evidence, ...
    decisions=struct(shipped=decisionReadback(shippedDecision), ...
        relaxed=decisionReadback(relaxedDecision), ...
        comparison=policyComparison), ...
    detection_report=compactReport(detectionReport), ...
    consensus_run=struct(target_kind="consensus_event", ...
        target_count=height(consensusRun.targets), ...
        import_status=consensusImport.status, ...
        iou_basis=consensusCorrespondence.iou_basis, ...
        correspondence_count=height(consensusCorrespondence.correspondences), ...
        decision_status_counts=consensusReport.qc.decision_status_counts, ...
        run_completed=consensusDecision.run_completed, ...
        run_status=consensusReport.status, ...
        analysis_status=consensusReport.analysis_status), ...
    consensus_report=compactReport(consensusReport), ...
    refusals=refusals, ...
    separation=struct(combined_value_computed=false, ...
        caller_estimated=false, ...
        evidence_dimensions_present=height(detectionReport.qc.evidence_by_dimension), ...
        note="The four dimensions are stored, read and displayed side by " + ...
            "side with their own units and semantics. Nothing here combines " + ...
            "them, and the decision policy reads one candidate column and no " + ...
            "evidence row."), ...
    database_inventory=inventory, foreign_key_check=foreignKeyCheck, ...
    proves=["one canonical representation carries several candidate callers " + ...
        "per event, over both VAWLUME target kinds"; ...
        "an imported number keeps its own value, its semantics and its producer"; ...
        "an imported window reaches a VAWLUME event only through a declared " + ...
        "clock and a declared eligibility rule"; ...
        "the four uncertainty dimensions are represented separately and " + ...
        "combined by nothing"; ...
        "a decision moves with its policy while the candidates it read do not"; ...
        "ambiguous and simultaneous are recorded as opposite claims"; ...
        "the path refuses by name where guessing would look like success"], ...
    does_not_prove=["that any claimed or selected entity called"; ...
        "that the exporting system's scores or probabilities are calibrated"; ...
        "that any threshold in the shipped policy or mapping profile is tuned"; ...
        "that a window corresponding to nothing refers to a call VAWLUME missed"; ...
        "that this representation is legible at realistic session scale"], ...
    temporary_artifacts_removed=false);

close(conn);
clear cleanupConnection
removeTree(workspace);
clear cleanupWorkspace
demonstration.temporary_artifacts_removed = ...
    ~isfolder(workspace) && ~isfile(databasePath);

if options.Print, printDemonstration(demonstration); end
clear cleanupPath
end

