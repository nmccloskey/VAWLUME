% ------------------------------------------------------------- read-backs ---

function value = recoveredParameters(qc, truth)
audio = qc.segments(qc.segments.source_timebase_key == "audio_native", :);
video = qc.segments(qc.segments.source_timebase_key == "video_native", :);
expectedScale = [truth.audio_scale; repmat(truth.video_scale, height(video), 1)];
expectedOffset = [truth.audio_offset_s; repmat(truth.video_offset_s, height(video), 1)];
observedScale = [audio.scale; video.scale];
observedOffset = [audio.offset_s; video.offset_s];
value = table([repmat("audio_native", height(audio), 1); ...
    repmat("video_native", height(video), 1)], ...
    [audio.segment_index; video.segment_index], observedScale, expectedScale, ...
    observedOffset, expectedOffset, abs(observedScale - expectedScale), ...
    abs(observedOffset - expectedOffset), ...
    VariableNames=["source_timebase", "segment_index", "scale", ...
    "expected_scale", "offset_s", "expected_offset_s", ...
    "scale_absolute_error", "offset_absolute_error_s"]);
end

function value = demonstrateCoverage(conn, view, videoRunId, truth)
videoKey = unique(view.events.coverage_key( ...
    view.events.source_timebase_key == "video_native"));
assert(isscalar(videoKey), "Expected one video event stream.");
[edges, support] = vawlume.alignment.applyTransform(conn, videoRunId, [0; 30]);
binWidth = edges(2) - edges(1);
channels = struct(name="behavior_event_count", ...
    event_source_kind="external_event", normalized_event_key="female_entry", ...
    coverage_key=videoKey, aggregation="onset_count");
regularized = vawlume.sequence.regularizeTimeline(view, channels, ...
    WindowStart=edges(1), WindowEnd=edges(1) + 12 * binWidth, ...
    BinWidth=binWidth, BinOrigin=edges(1));
value = struct(timeline=regularized.timeline, ...
    specification=regularized.specification, ...
    first_bin_source_interval=[0 30], ...
    first_bin_extrapolated=any(support.extrapolated), ...
    first_bin_covered_empty=regularized.timeline.behavior_event_count(1) == 0, ...
    unavailable_bin_present=any(isnan(regularized.timeline.behavior_event_count)), ...
    projected_coverage=view.coverage( ...
        view.coverage.source_timebase_key == "video_native", :), ...
    note="Zero means covered and empty; NaN means unavailable. Transform support is separate.", ...
    video_breakpoint=truth.video_breakpoint);
end

function value = evidenceSummary(qc, trackingWindow, acousticPath)
withheld = qc.residuals(qc.residuals.source_timebase_key == "audio_native" & ...
    qc.residuals.anchor_key == "sync04", :);
identity = qc.anchor_identity_evidence(1, :);
acoustic = readtable(acousticPath, TextType="string");
value = table(["temporal_alignment"; "pose_localization"; ...
    "visual_identity"; "acoustic_channel_response"], ...
    [abs(withheld.residual_s(1)); trackingWindow.samples.pose_confidence(1); ...
        identity.identity_value(1); acoustic.value(1)], ...
    ["s"; "upstream score"; "similarity"; acoustic.unit(1)], ...
    ["held-out residual; reported, not judged"; ...
        "upstream keypoint localization confidence"; ...
        identity.identity_value_semantics(1); acoustic.semantics(1)], ...
    ["alignment_anchor_residuals"; "tracking artifact"; ...
        "tracking_identity_associations"; "synthetic acoustic evidence file"], ...
    VariableNames=["dimension", "value", "unit", "semantics", "queried_from"]);
end

function value = coefficientFingerprint(fit, sourceKey)
rows = fit.segments(fit.segments.source_timebase_key == sourceKey, :);
parts = compose("%.17g|%.17g|%.17g", rows.scale, rows.offset_s, rows.rmse_s);
value = join(parts, ";");
end

function value = alignmentRef()
value = struct(project_key="synthetic_alignment_session", ...
    run_key="phase3_alignment_demo");
end

function value = runIdFor(qc, sourceKey)
row = qc.transforms(qc.transforms.source_timebase_key == sourceKey, :);
assert(height(row) == 1, "Expected one transform for " + sourceKey);
value = double(row.alignment_run_id(1));
end

function value = anchorObservationId(conn, anchorKey, timebaseKey, role)
rows = fetch(conn, "SELECT o.anchor_observation_id FROM " + ...
    "alignment_anchor_observations o JOIN alignment_anchors a " + ...
    "ON a.alignment_anchor_id=o.alignment_anchor_id JOIN timebases t " + ...
    "ON t.timebase_id=o.timebase_id JOIN alignment_sets s " + ...
    "ON s.alignment_set_id=a.alignment_set_id " + ...
    "WHERE s.alignment_set_key='phase3_alignment_demo' AND a.anchor_key=" + ...
    sqlText(anchorKey) + " AND t.timebase_name=" + sqlText(timebaseKey) + ...
    " AND o.observation_role=" + sqlText(role));
assert(height(rows) == 1, "Anchor observation selector was not unique.");
value = double(rows.anchor_observation_id(1));
end

% ------------------------------------------------------------------ print ---

function printDemo(value)
fprintf('\nVAWLUME synthetic Phase 3 temporal-alignment demonstration\n');
fprintf(['All inputs and thresholds are synthetic. A fitted transform is ' ...
    'estimated, never validated.\n']);
fprintf('Reference clock: %s\n', value.qc.reference_timebase.timebase_key);

fprintf('\nSource-clock outcomes (one failure does not erase the successes):\n');
disp(value.qc.transforms(:, ["source_timebase_key", "method", "status", ...
    "segment_count", "failure_code"]));
fprintf('Recovered declared piecewise parameters:\n');
disp(value.recovered_parameters);

fprintf('Replicate dispersion (one logical anchor, not an extra fit row):\n');
disp(value.replicate_dispersion);
fprintf('Held-out residual (did not influence the coefficients):\n');
disp(value.withheld_residual);
fprintf('Anchor-configuration diagnostics for the deliberately clustered case:\n');
disp(value.anchor_configuration);

fprintf('Interval crossing the declared breakpoint:\n');
disp(value.interval_crossing);
fprintf('Anchored versus extrapolated point:\n');
disp(value.point_support);
fprintf('Propagated uncertainty (explicitly uncalibrated; NaN means absent):\n');
disp(value.uncertainty_propagation);

fprintf('Coverage-aware bins (0 = covered-empty, NaN = unavailable):\n');
disp(value.coverage_demonstration.timeline);
fprintf('  first covered-empty bin extrapolated: %d\n', ...
    value.coverage_demonstration.first_bin_extrapolated);

