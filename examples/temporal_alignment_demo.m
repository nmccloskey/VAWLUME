    "VALUES (1,'synthetic_alignment_session','Synthetic alignment demo')");
execute(conn, "INSERT INTO source_files(source_file_id,project_id,file_role," + ...
    "path_or_uri,relative_path) VALUES " + ...
    "(1,1,'recording_audio','synthetic/session01.wav','session01.wav')");
execute(conn, "INSERT INTO recordings(recording_id,project_id,source_file_id," + ...
    "native_recording_id,sample_rate_hz,duration_s) " + ...
    "VALUES (1,1,1,'REC_SESSION_01',250000,1600)");
execute(conn, "INSERT INTO extractors(extractor_key,extractor_name) " + ...
    "VALUES ('synthetic_calls','Synthetic call fixture')");
execute(conn, "INSERT INTO extractor_versions(extractor_id,version_label) " + ...
    "VALUES ((SELECT extractor_id FROM extractors " + ...
    "WHERE extractor_key='synthetic_calls'),'0.1-demo')");
execute(conn, "INSERT INTO extraction_runs(extraction_run_id,project_id," + ...
    "extractor_version_id,run_key) VALUES (1,1,(SELECT extractor_version_id " + ...
    "FROM extractor_versions ev JOIN extractors e ON " + ...
    "e.extractor_id=ev.extractor_id WHERE e.extractor_key='synthetic_calls')," + ...
    "'demo_calls')");
execute(conn, "INSERT INTO extraction_run_inputs(extraction_run_id,recording_id) " + ...
    "VALUES (1,1)");
execute(conn, "INSERT INTO detections(extraction_run_id,recording_id," + ...
    "native_event_id,start_time_s,end_time_s,timing_basis) VALUES " + ...
    "(1,1,'call01',60,60.08,'synthetic fixture')," + ...
    "(1,1,'call02',330,330.06,'synthetic fixture')");
execute(conn, "INSERT INTO entity_types(project_id,native_name,is_subject_like) " + ...
    "VALUES (1,'mouse',1)");
execute(conn, "INSERT INTO experimental_entities(project_id,entity_type_id," + ...
    "native_id) VALUES (1,(SELECT entity_type_id FROM entity_types " + ...
    "WHERE project_id=1 AND native_name='mouse'),'mouse_a')," + ...
    "(1,(SELECT entity_type_id FROM entity_types WHERE project_id=1 " + ...
    "AND native_name='mouse'),'mouse_b')");
end

function [truth, inputs] = writeSyntheticInputs(workspace, repoRoot)
truth = struct();
truth.audio_breakpoint = 900;
truth.audio_scale = [1.0015; 0.9990];
truth.audio_offset_s = [117.25; ...
    (truth.audio_scale(1) - truth.audio_scale(2)) * ...
        truth.audio_breakpoint + 117.25];
truth.video_scale = 0.9992;
truth.video_offset_s = 53.40;
truth.audio_times = [10; 20; 30; 900; 1200; 1500];
truth.anchor_keys = "sync" + compose("%02d", (1:numel(truth.audio_times))');
segment = 1 + double(truth.audio_times >= truth.audio_breakpoint);
truth.neural_times = truth.audio_scale(segment) .* truth.audio_times + ...
    truth.audio_offset_s(segment);
% The held-out observation is purposefully displaced. It is QC evidence and
% does not perturb either fitted transform.
truth.neural_times(4) = truth.neural_times(4) + 0.015;
truth.video_times = (truth.neural_times - truth.video_offset_s) / ...
    truth.video_scale;
truth.video_breakpoint = (truth.audio_scale(1) * truth.audio_breakpoint + ...
    truth.audio_offset_s(1) - truth.video_offset_s) / truth.video_scale;

behavior = table(["b1"; "b2"], ["Intruder enters"; "Sniffing"], ...
    ["60"; "330"], ["65"; missing], ["mouse_a"; "mouse_b"], ...
    ["door"; "center"], VariableNames=["event_id", "event", ...
    "start_time_s", "end_time_s", "subject", "zone"]);
writeTable(fullfile(workspace, "video_events.csv"), behavior);

ids = "n" + string(1:numel(truth.neural_times))';
neural = table(ids, repmat("TTL1_HIGH", numel(ids), 1), ...
    compose("%.9f", truth.neural_times * 1000), repmat("5", numel(ids), 1), ...
    repmat("1", numel(ids), 1), ...
    VariableNames=["pulse_id", "marker", "timestamp_ms", "amplitude_v", "channel"]);
writeTable(fullfile(workspace, "neural_events.csv"), neural);

writeTable(fullfile(workspace, "sync_anchors.csv"), anchorTable(truth));

profilePath = fullfile(workspace, "phase3_anchor_profile.json");
writeAnchorProfile(profilePath, repoRoot);
manifestPath = fullfile(workspace, "phase3_alignment_manifest.json");
writeManifest(manifestPath, profilePath, repoRoot);

acousticPath = fullfile(workspace, "acoustic_evidence.csv");
writeTable(acousticPath, table(0.42, "channel_1_to_2_rms_ratio", "ratio", ...
    VariableNames=["value", "semantics", "unit"]));
inputs = struct(manifest_path=string(manifestPath), ...
    anchor_profile_path=string(profilePath), acoustic_path=string(acousticPath));
end

function value = anchorTable(truth)
count = numel(truth.anchor_keys);
rowCount = 3 * count + 3;
markers = strings(rowCount, 1); streams = strings(rowCount, 1);
timestamps = strings(rowCount, 1); roles = strings(rowCount, 1);
included = strings(rowCount, 1); uncertainties = strings(rowCount, 1);
classes = strings(rowCount, 1); eventIds = strings(rowCount, 1);
row = 0;
for index = 1:count
    for item = [struct(stream="audio", time=truth.audio_times(index)), ...
            struct(stream="video", time=truth.video_times(index)), ...
            struct(stream="neural", time=truth.neural_times(index))]
        row = row + 1;
        markers(row) = truth.anchor_keys(index);
        streams(row) = item.stream;
        timestamps(row) = compose("%.9f", item.time);
        roles(row) = "primary";
        included(row) = "true";
        classes(row) = "device_level";
        if item.stream == "audio"
            uncertainties(row) = "0.002";
        elseif item.stream == "neural"
            eventIds(row) = "n" + string(index);
        end
        if index == 3
            classes(row) = "identity_dependent";
        end
    end
end
% A replicate is preserved as dispersion evidence and explicitly excluded.
row = row + 1;
markers(row) = truth.anchor_keys(1);
streams(row) = "audio";
timestamps(row) = compose("%.9f", truth.audio_times(1) + 0.006);
roles(row) = "replicate";
included(row) = "false";
uncertainties(row) = "0.002";
classes(row) = "device_level";
% Two readings establish that a controller clock participated, but no
% breakpoint is declared for its piecewise model, producing a named failure.
for index = 1:2
    row = row + 1;
    markers(row) = truth.anchor_keys(index);
    streams(row) = "controller";
    timestamps(row) = compose("%.9f", 2 * truth.audio_times(index));
    roles(row) = "primary";
    included(row) = "true";
    classes(row) = "device_level";
end
value = table(markers, streams, timestamps, roles, included, uncertainties, ...
    classes, eventIds, VariableNames=["marker", "stream", "timestamp_s", ...
    "role", "include", "uncertainty_s", "evidence_class", "event_id"]);
end

function writeAnchorProfile(pathValue, repoRoot)
document = jsondecode(fileread(fullfile(repoRoot, "config", ...
    "01_mapping_profiles", "alignment_anchors", ...
    "long_anchor_mapping_profile.json")));
document.profile.id = "vawlume.alignment.anchor.long.phase3_demo.v1";
document.profile.name = "Synthetic Phase 3 integrated anchor profile";
declared = cellstr(string(document.context.declared_timebases));
declared{end + 1} = 'controller_native';
document.context.declared_timebases = declared;
mapping = document.context.stream_timebases(1);
mapping.native_value = "controller";
mapping.stream_key = "controller_sync";
mapping.timebase_key = "controller_native";
document.context.stream_timebases(end + 1) = mapping;
pair = document.context.fit_pairs(1);
pair.source_timebase_key = "controller_native";
pair.reference_timebase_key = "neural_native";
document.context.fit_pairs(end + 1) = pair;
writeText(pathValue, string(jsonencode(document, PrettyPrint=true)) + newline);
end

