function demonstration = temporal_alignment_demo(options)
%TEMPORAL_ALIGNMENT_DEMO Demonstrate the integrated Phase 3 alignment layer.
%
% DEMONSTRATION = TEMPORAL_ALIGNMENT_DEMO() creates a disposable synthetic
% audio/video/controller/neural session. It fits continuous piecewise-affine
% transforms from declared breakpoints, leaves one source clock in a named
% failure state, reads alignment QC, transforms points and intervals, projects
% coverage, and lets tracking consume the stored piecewise transform.
%
% The fixture deliberately contains a redundant observation, a held-out anchor,
% anchors clustered toward one end of the source range, one identity-dependent
% anchor, and both recorded and absent anchor uncertainty. All inputs are created
% under the system temporary directory and removed before return.
%
% Four evidence dimensions are displayed side by side and never combined:
% temporal-alignment residual/QC, pose confidence, visual-identity evidence,
% and acoustic/channel evidence. No caller is named or inferred.
%
% Name-value options:
%   Print     print compact developer-facing read-backs (default true)
%   RepoRoot  repository root, inferred from this file by default

arguments
    options.Print (1,1) logical = true
    options.RepoRoot (1,1) string = ""
end

repoRoot = options.RepoRoot;
if strlength(repoRoot) == 0
    repoRoot = string(fileparts(fileparts(mfilename("fullpath"))));
end
sourcePath = fullfile(repoRoot, "src");
removePath = ~contains(path, sourcePath);
if removePath, addpath(sourcePath); end
cleanupPath = onCleanup(@() restorePath(sourcePath, removePath));

workspace = fullfile(tempdir, "VAWLUME phase 3 alignment demo " + ...
    string(java.util.UUID.randomUUID));
mkdir(workspace);
databasePath = fullfile(workspace, "temporal_alignment_demo.sqlite");
conn = sqlite(char(databasePath), "create");
cleanupConnection = onCleanup(@() closeConnection(conn));
cleanupWorkspace = onCleanup(@() removeTree(workspace));
vawlume.db.applySchema(conn, fullfile(repoRoot, "schema", "schema.sql"));
vawlume.db.registerBuiltinSemantics(conn, repoRoot);

seedSession(conn);
[truth, inputs] = writeSyntheticInputs(workspace, repoRoot);
intake = vawlume.ingest.alignment(conn, inputs.manifest_path, ...
    RepoRoot=repoRoot, SourceRoot=workspace, Apply=true);

% Exclusion is a declared decision. The anchor remains available for a residual
% against the transform it did not influence.
withheld = table();
for timebase = ["audio_native", "video_native"]
    observationRef = struct(project_key="synthetic_alignment_session", ...
        run_key="phase3_alignment_demo", anchor_key="sync04", ...
        timebase_key=timebase, observation_role="primary");
    decision = vawlume.alignment.setAnchorInclusion(conn, observationRef, false, ...
        Reason="synthetic held-out check; not automatic outlier rejection");
    withheld = [withheld; struct2table(decision)]; %#ok<AGROW>
end

tracking = registerTrackingAndIdentity(conn, workspace, repoRoot);

% Planning is read-only, so the sharp identity-separation claim can be observed
% directly: the exact same solve is performed before and after evidence is linked.
beforeIdentity = vawlume.alignment.fit(conn, alignmentRef(), ...
    SourceTimebase="audio_native", Breakpoints=truth.audio_breakpoint);
identityLink = vawlume.alignment.linkAnchorIdentityEvidence(conn, ...
    anchorObservationId(conn, "sync03", "audio_native", "primary"), ...
    tracking.identity_association_id, ...
    Notes="Synthetic identity evidence qualifying the biological anchor.");
afterIdentity = vawlume.alignment.fit(conn, alignmentRef(), ...
    SourceTimebase="audio_native", Breakpoints=truth.audio_breakpoint);
identityInvariant = coefficientFingerprint(beforeIdentity, "audio_native") == ...
    coefficientFingerprint(afterIdentity, "audio_native");

audioFit = vawlume.alignment.fit(conn, alignmentRef(), ...
    SourceTimebase="audio_native", Breakpoints=truth.audio_breakpoint, Apply=true);
videoFit = vawlume.alignment.fit(conn, alignmentRef(), ...
    SourceTimebase="video_native", Breakpoints=truth.video_breakpoint, Apply=true);
% This source deliberately has too little declared segmentation information.
% Its named failure is persisted without disturbing the two successful clocks.
controllerFit = vawlume.alignment.fit(conn, alignmentRef(), ...
    SourceTimebase="controller_native", Apply=true);

qc = vawlume.alignment.report(conn, alignmentRef());
audioRunId = runIdFor(qc, "audio_native");
videoRunId = runIdFor(qc, "video_native");

recovered = recoveredParameters(qc, truth);
crossing = vawlume.alignment.applyTransformInterval(conn, audioRunId, 800, 1000);
[supportTimes, support] = vawlume.alignment.applyTransform(conn, audioRunId, ...
    [900; 1600]);
pointSupport = table([900; 1600], supportTimes, support.segment_index, ...
    support.extrapolated, support.uncertainty_s, ...
    VariableNames=["source_time", "reference_time", "segment_index", ...
    "extrapolated", "uncertainty_s"]);

[~, audioUncertainty] = vawlume.alignment.applyTransform(conn, audioRunId, 900);
[~, videoUncertainty] = vawlume.alignment.applyTransform(conn, videoRunId, ...
    truth.video_breakpoint);
uncertaintyPropagation = table(["audio_native"; "video_native"], ...
    [audioUncertainty.uncertainty_s; videoUncertainty.uncertainty_s], ...
    [audioUncertainty.uncertainty_semantics; ...
        videoUncertainty.uncertainty_semantics], ...
    ["recorded anchor uncertainty"; "no anchor uncertainty recorded"], ...
    VariableNames=["source_timebase", "uncertainty_s", "semantics", "case"]);

view = vawlume.alignment.commonTime(conn, alignmentRef(), ...
    VocalizationSource="detections", VocalizationRunId=1, ...
    ErrorOnOutsideCoverage=false);
coverageExample = demonstrateCoverage(conn, view, videoRunId, truth);

trackingWindow = vawlume.tracking.readWindow(conn, tracking.stream_ref, ...
    [800 1000], SourceRoot=workspace, RepoRoot=repoRoot, ...
    ReferenceTimebaseKey="neural_native");

separateEvidence = evidenceSummary(qc, trackingWindow, inputs.acoustic_path);
audioDiagnostics = qc.anchor_diagnostics( ...
    qc.anchor_diagnostics.source_timebase_key == "audio_native", :);
replicateDispersion = qc.anchor_dispersion( ...
    qc.anchor_dispersion.timebase_key == "audio_native" & ...
    qc.anchor_dispersion.anchor_key == "sync01", :);
withheldResidual = qc.residuals( ...
    qc.residuals.source_timebase_key == "audio_native" & ...
    qc.residuals.anchor_key == "sync04", :);

inventory = struct( ...
    aligned_external_events=rowCount(conn, "aligned_external_events"), ...
    sequences=rowCount(conn, "sequences"), ...
    sequence_members=rowCount(conn, "sequence_members"), ...
    caller_attribution_rows=0);
foreignKeyCheck = fetch(conn, "PRAGMA foreign_key_check");

demonstration = struct( ...
    synthetic_truth=truth, inputs=inputs, intake=intake, ...
    fits=struct(audio=audioFit, video=videoFit, controller=controllerFit), ...
    qc=qc, recovered_parameters=recovered, ...
    identity=struct(link=identityLink, coefficients_before= ...
        coefficientFingerprint(beforeIdentity, "audio_native"), ...
        coefficients_after=coefficientFingerprint(afterIdentity, "audio_native"), ...
        coefficients_identical=identityInvariant), ...
    withheld_decisions=withheld, withheld_residual=withheldResidual, ...
    replicate_dispersion=replicateDispersion, ...
    anchor_configuration=audioDiagnostics, ...
    interval_crossing=crossing, point_support=pointSupport, ...
    uncertainty_propagation=uncertaintyPropagation, ...
    common_time_events=view.events, projected_coverage=view.coverage, ...
    coverage_demonstration=coverageExample, ...
    tracking=tracking, tracking_window=trackingWindow, ...
    separate_evidence=separateEvidence, ...
    separation=struct(combined_value_computed=false, caller_named=false, ...
        note="The four evidence values retain distinct sources, semantics, and units."), ...
    database_inventory=inventory, foreign_key_check=foreignKeyCheck, ...
    proves=["declared piecewise drift is recovered through the public fit API"; ...
        "source clocks succeed or fail independently against one reference"; ...
        "replicates, withheld anchors, coverage, and extrapolation remain distinct evidence"; ...
        "tracking consumes the shared stored piecewise transform"; ...
        "identity evidence is visible and coefficient-invariant"], ...
    does_not_prove=["real-device synchronization accuracy"; ...
        "calibrated uncertainty or residual acceptance thresholds"; ...
        "which animal produced any detected vocalization"], ...
    temporary_artifacts_removed=false);

if options.Print, printDemo(demonstration); end
close(conn);
clear cleanupConnection
removeTree(workspace);
clear cleanupWorkspace
demonstration.temporary_artifacts_removed = ...
    ~isfolder(workspace) && ~isfile(databasePath);
clear cleanupPath
end

