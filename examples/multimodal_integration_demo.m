function windows = readTrackingWindows(conn, repoRoot, workspace, layout)
%READTRACKINGWINDOWS Three coverage states, read from the artifact each time.
readOptions = {"SourceRoot", workspace, "RepoRoot", repoRoot};
covered = vawlume.tracking.readWindow(conn, streamRef(), [0 2], readOptions{:});
crossing = vawlume.tracking.readWindow(conn, streamRef(), ...
    [layout.crossing_s(1) + 0.2, layout.crossing_s(2) - 0.2], readOptions{:});
partial = vawlume.tracking.readWindow(conn, streamRef(), [9 12], readOptions{:});
uncovered = vawlume.tracking.readWindow(conn, streamRef(), [14 16], readOptions{:});

windows = struct( ...
    covered=covered, crossing=crossing, partial=partial, uncovered=uncovered, ...
    coverage_states=table(["covered"; "crossing"; "partial"; "uncovered"], ...
        [string(covered.coverage_status); string(crossing.coverage_status); ...
            string(partial.coverage_status); string(uncovered.coverage_status)], ...
        [string(covered.sample_status); string(crossing.sample_status); ...
            string(partial.sample_status); string(uncovered.sample_status)], ...
        [height(covered.samples); height(crossing.samples); ...
            height(partial.samples); height(uncovered.samples)], ...
        VariableNames=["window", "coverage_status", "sample_status", "sample_rows"]), ...
    pose_confidence_nominal=unique(covered.samples.pose_confidence), ...
    pose_confidence_crossing=unique(crossing.samples.pose_confidence), ...
    identity_boundary=covered.identity_boundary);
end

% ------------------------------------------------------- visual identity ---

function identity = recordIdentityEvidence(conn, layout)
%RECORDIDENTITYEVIDENCE Clean before, ambiguous during, reversed after.
crossing = layout.crossing_s;
span = layout.tracking_span_s;
reid = layout.reidentification_values;

% Before: manual assertions, and deliberately no number. A manual reviewer who
% is certain has still produced no measurement, so the value stays missing.
assertIdentity(conn, "mouse_a", "mouse_a", [span(1) crossing(1)], "assigned", ...
    "manual_assertion");
assertIdentity(conn, "mouse_b", "mouse_b", [span(1) crossing(1)], "assigned", ...
    "manual_assertion");

% During: one trajectory is compatible with either animal, and the upstream
% scores say which is which only weakly. Both candidates are stored.
scoreIdentity(conn, "mouse_a", "mouse_a", crossing, reid(1));
scoreIdentity(conn, "mouse_a", "mouse_b", crossing, reid(2));

% And the other trajectory's identity is explicitly unknown, which is a
% different finding from having no evidence at all.
vawlume.tracking.registerIdentityAssociation(conn, streamRef(), struct( ...
    native_track_id="mouse_b", start_time_native=crossing(1), ...
    end_time_native=crossing(2), assignment_state="unresolved", ...
    evidence_kind="manual_review", review_state="reviewed", ...
    method="manual_review_of_crossing"));

% After: the association has reversed. The trajectory still labelled 'mouse_a'
% now carries evidence for the animal 'mouse_b'.
assertIdentity(conn, "mouse_a", "mouse_b", [crossing(2) span(2)], "assigned", ...
    "manual_assertion");
assertIdentity(conn, "mouse_b", "mouse_a", [crossing(2) span(2)], "assigned", ...
    "manual_assertion");

before = vawlume.tracking.identityCandidates(conn, streamRef(), ...
    [span(1) crossing(1) - 0.5]);
during = vawlume.tracking.identityCandidates(conn, streamRef(), ...
    [crossing(1) + 0.2, crossing(2) - 0.2]);
after = vawlume.tracking.identityCandidates(conn, streamRef(), ...
    [crossing(2) + 0.5, span(2)]);

identity = struct( ...
    before=before, during=during, after=after, ...
    resolution_by_window=resolutionTable(before, during, after), ...
    label_versus_identity=labelComparison(before, after, layout), ...
    missing_values_remain_missing=all(isnan(before.associations.identity_value)), ...
    numeric_evidence=during.associations(~isnan( ...
        during.associations.identity_value), ["native_track_id", ...
        "entity_native_id", "assignment_state", "identity_value", ...
        "identity_value_semantics", "calibration_status"]), ...
    unexamined_track=layout.native_track_ids(3), ...
    image_reidentification_performed=false);
end

function assertIdentity(conn, trackId, entityNativeId, interval, state, evidenceKind)
vawlume.tracking.registerIdentityAssociation(conn, streamRef(), struct( ...
    native_track_id=trackId, entity_native_id=entityNativeId, ...
    start_time_native=interval(1), end_time_native=interval(2), ...
    assignment_state=state, evidence_kind=evidenceKind, ...
    review_state="reviewed", method="manual_review_by_scorer"));
end

function scoreIdentity(conn, trackId, entityNativeId, interval, value)
%SCOREIDENTITY An upstream similarity score, recorded with what it means.
vawlume.tracking.registerIdentityAssociation(conn, streamRef(), struct( ...
    native_track_id=trackId, entity_native_id=entityNativeId, ...
    start_time_native=interval(1), end_time_native=interval(2), ...
    assignment_state="ambiguous", evidence_kind="reidentification_score", ...
    identity_value=value, ...
    identity_value_semantics="cosine_similarity_of_appearance_embeddings", ...
    calibration_status="uncalibrated", method="upstream_tracker_similarity"));
end

function value = resolutionTable(before, during, after)
value = table();
for entry = [struct(name="before", result=before), ...
        struct(name="during", result=during), ...
        struct(name="after", result=after)]
    tracks = entry.result.tracks;
    value = [value; table(repmat(string(entry.name), height(tracks), 1), ...
        tracks.native_track_id, tracks.resolution, tracks.candidate_count, ...
        tracks.has_numeric_evidence, ...
        VariableNames=["window", "native_track_id", "resolution", ...
        "candidate_count", "has_numeric_evidence"])]; %#ok<AGROW>
end
end

function value = labelComparison(before, after, layout)
%LABELCOMPARISON What the tracker called each trajectory, beside the evidence.
%
% Two of the labels are spelled exactly like canonical entities and agree with
% the evidence before the crossing. That agreement is a coincidence of naming
% with no authority behind it, and it stops holding after the crossing while the
% labels stay put. The third label names no entity at all.
tracks = layout.native_track_ids(:);
beforeEntity = strings(numel(tracks), 1);
afterEntity = strings(numel(tracks), 1);
for index = 1:numel(tracks)
    beforeEntity(index) = entityFor(before.associations, tracks(index));
    afterEntity(index) = entityFor(after.associations, tracks(index));
end
value = table(tracks, beforeEntity, afterEntity, ...
    beforeEntity == tracks, afterEntity == tracks, ...
    VariableNames=["native_track_id", "entity_before_crossing", ...
    "entity_after_crossing", "label_matches_evidence_before", ...
    "label_matches_evidence_after"]);
value.Properties.Description = "A track label is never canonical identity. " + ...
    "Where the spelling agrees before the crossing it disagrees after it, " + ...
    "and the label never moved.";
end

function value = entityFor(associations, trackId)
selected = associations(associations.native_track_id == trackId, :);
named = unique(selected.entity_native_id(strlength( ...
    selected.entity_native_id) > 0));
if isempty(named)
    value = "<no evidence>";
else
    value = strjoin(sort(named)', "|");
end
end

% --------------------------------------------------- clocks and alignment ---

function clocks = demonstrateClockSeparation(conn, repoRoot, workspace, layout)
%DEMONSTRATECLOCKSEPARATION Alignment QC is its own field, not a confidence.
missing = vawlume.tracking.readWindow(conn, streamRef(), [0 2], ...
    SourceRoot=workspace, RepoRoot=repoRoot, ...
    ReferenceTimebaseKey="neural_native");

writeStoredTransform(conn, layout);
applied = vawlume.tracking.readWindow(conn, streamRef(), [0 2], ...
    SourceRoot=workspace, RepoRoot=repoRoot, ...
    ReferenceTimebaseKey="neural_native");

clocks = struct( ...
    without_transform=struct( ...
        reference_time_status=string(missing.reference_time_status), ...
        reference_times_all_missing=all(isnan(missing.samples.time_reference_s)), ...
        native_times_untouched=all(isfinite(missing.samples.time_native_s)), ...
        pose_confidence_unchanged=isequal( ...
            unique(missing.samples.pose_confidence), ...
            layout.pose_confidence_nominal)), ...
    with_transform=struct( ...
        reference_time_status=string(applied.reference_time_status), ...
        method=string(applied.transform.method), ...
        rmse_s=applied.transform.rmse_s, ...
        max_abs_residual_s=applied.transform.max_abs_residual_s, ...
        status=string(applied.transform.status), ...
        offset_recovered_s=unique(round(applied.samples.time_reference_s - ...
            applied.samples.time_native_s, 9))), ...
    fit_is_estimated_not_validated=applied.transform.status == "estimated", ...
    note="The transform below is written directly as fixture material. " + ...
        "Fitting belongs to the alignment layer, which temporal_alignment_demo " + ...
        "demonstrates; what matters here is that its residual evidence arrives " + ...
        "beside pose confidence and identity evidence without touching either.");
end

