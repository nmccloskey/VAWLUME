% --------------------------------------------------------- synthetic session ---

function facts = writeSyntheticAudio(workspace, layout)
%WRITESYNTHETICAUDIO A deterministic two-channel file with four reference bursts.
%
% Each reference interval spans an integer number of cycles of every component it
% contains, so its RMS is exact rather than approximate, and every interval of a
% family carries the identical waveform. That is what makes the aggregated
% profile reproducible: the repeats agree because the signal does, not because
% the aggregation smoothed anything.
mkdir(fullfile(workspace, "audio"));
audioPath = fullfile(workspace, "audio", "session01.wav");
sampleRate = layout.sample_rate_hz;
total = sampleRate * layout.duration_s;
time = (0:total - 1)' / sampleRate;
left = zeros(total, 1);

toneAmplitude = layout.tone_rms_target * sqrt(2);
for index = 1:size(layout.tone_intervals_s, 1)
    selected = intervalSamples(layout.tone_intervals_s(index, :), sampleRate, total);
    left(selected) = toneAmplitude * ...
        sin(2 * pi * layout.tone_frequency_hz * time(selected));
end

% Orthogonal components share the family's power equally, so k sinusoids of
% amplitude target*sqrt(2/k) give the interval exactly the target RMS.
noiseAmplitude = layout.noise_rms_target * ...
    sqrt(2 / numel(layout.noise_frequencies_hz));
for index = 1:size(layout.noise_intervals_s, 1)
    selected = intervalSamples(layout.noise_intervals_s(index, :), sampleRate, total);
    component = zeros(numel(selected), 1);
    for frequency = layout.noise_frequencies_hz
        component = component + noiseAmplitude * ...
            sin(2 * pi * frequency * time(selected));
    end
    left(selected) = component;
end

samples = [left, layout.right_channel_scale * left];
audiowrite(char(audioPath), samples, sampleRate, BitsPerSample=24);
fileInfo = dir(audioPath);
facts = struct( ...
    relative_path="audio/session01.wav", ...
    filename="session01.wav", ...
    sample_rate_hz=sampleRate, ...
    channel_count=layout.channel_count, ...
    duration_s=layout.duration_s, ...
    size_bytes=fileInfo.bytes, ...
    expected_rms=table(["tone"; "tone"; "noise"; "noise"], [1; 2; 1; 2], ...
        [layout.tone_rms_target; ...
            layout.right_channel_scale * layout.tone_rms_target; ...
            layout.noise_rms_target; ...
            layout.right_channel_scale * layout.noise_rms_target], ...
        VariableNames=["reference_type", "channel_index", "expected_rms"]));
end

function selected = intervalSamples(interval, sampleRate, total)
%INTERVALSAMPLES Half-open [start,end) in seconds as one-based sample indices.
first = floor(interval(1) * sampleRate) + 1;
last = min(round(interval(2) * sampleRate), total);
selected = (first:last)';
end

