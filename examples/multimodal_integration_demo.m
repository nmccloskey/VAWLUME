% ------------------------------------------------------------- acoustics ---

function acoustic = demonstrateAcousticResponse(conn, recordingRef, workspace, layout)
%DEMONSTRATEACOUSTICRESPONSE References, bounded reads, measurements, profile.
references = registerReferences(conn, recordingRef, layout);
windows = readAudioWindows(conn, recordingRef, workspace, layout);
measurements = measureEveryChannel(conn, recordingRef, workspace, references);

% Only the RMS rows are aggregated, selected by exact identifier. The population
% of a profile is therefore visible in the call rather than dependent on what a
% later query happens to return.
rmsIds = measurements.derived_measurement_id( ...
    measurements.metric_key == "acoustic_rms_amplitude");

planned = vawlume.acoustic.estimateChannelResponse(conn, recordingRef, rmsIds, ...
    RequiredReferenceTypes=["tone", "noise"], MinReferences=2, ...
    DivergenceRelativeThreshold=0.25);
applied = vawlume.acoustic.estimateChannelResponse(conn, recordingRef, rmsIds, ...
    RequiredReferenceTypes=["tone", "noise"], MinReferences=2, ...
    DivergenceRelativeThreshold=0.25, Apply=true, ...
    RunKey="session01-channel-response", ...
    RunLabel="Synthetic per-family channel response", VawlumeVersion="demo");
audit = vawlume.acoustic.readChannelResponse(conn, struct( ...
    project_key="multimodal_demo", run_key="session01-channel-response"));

% A required family with no evidence is an explicit QC row, not a silent gap.
% Planned only: the demonstration keeps one profile in the database.
missingFamily = vawlume.acoustic.estimateChannelResponse(conn, recordingRef, ...
    rmsIds, RequiredReferenceTypes=["tone", "noise", "impulse"], MinReferences=2);

acoustic = struct( ...
    references=references, ...
    declared_references=vawlume.acoustic.readReferences(conn, recordingRef, ...
        ChannelIndex=1, StartTimeS=0, EndTimeS=layout.duration_s), ...
    windows=windows, ...
    measurements=measurements, ...
    planned_profile_wrote_nothing=planned.action == "planned", ...
    profile=applied, ...
    estimates=applied.estimates(:, ["reference_type", "channel_index", ...
        "metric_key", "value_real", "n_references", "relative_range", ...
        "qc_status"]), ...
    audit=audit, ...
    lineage=struct( ...
        source_measurements=height(audit.source_measurements), ...
        source_analyses=height(audit.source_analyses), ...
        dependency_roles=unique(audit.source_analyses.dependency_role)), ...
    families_kept_separate=numel(unique(applied.estimates.reference_type)) == 2, ...
    blended_family_value_absent=noBlendedValue(applied.estimates, layout), ...
    missing_family=missingFamilyRows(missingFamily), ...
    is_caller_probability=false, ...
    is_gain_correction=false);
end

function references = registerReferences(conn, recordingRef, layout)
%REGISTERREFERENCES Two families of two intervals each, recording-wide.
%
% No channel_index is declared, so each reference applies to both channels and
% the same interval can be measured on each. Reference types are open text and
% neither family is required by VAWLUME.
references = table();
definitions = [ ...
    struct(type="tone", intervals=layout.tone_intervals_s), ...
    struct(type="noise", intervals=layout.noise_intervals_s)];
for definition = definitions
    for index = 1:size(definition.intervals, 1)
        interval = definition.intervals(index, :);
        result = vawlume.acoustic.registerReference(conn, recordingRef, struct( ...
            reference_key=definition.type + "-" + string(index), ...
            reference_type=definition.type, ...
            native_label=upper(definition.type) + "_" + string(index), ...
            start_time_s=interval(1), end_time_s=interval(2), ...
            frequency_min_hz=layout.declared_band_hz(1), ...
            frequency_max_hz=layout.declared_band_hz(2)));
        references = [references; table(result.acoustic_reference_id, ...
            string(definition.type), interval(1), interval(2), ...
            string(result.action), VariableNames=["acoustic_reference_id", ...
            "reference_type", "start_time_s", "end_time_s", "action"])]; %#ok<AGROW>
    end
end
end

function value = noBlendedValue(estimates, layout)
%NOBLENDEDVALUE No estimate equals the average of the two families on any channel.
%
% The check is worth making explicitly: averaging a tone family with a noise
% family would produce a plausible-looking number that describes neither.
blended = mean([layout.tone_rms_target layout.noise_rms_target]) * ...
    [1, layout.right_channel_scale];
value = ~any(min(abs(estimates.value_real - blended), [], 2) < 1e-6);
end

function rows = missingFamilyRows(profile)
%MISSINGFAMILYROWS The explicit rows a required family with no evidence produces.
estimates = profile.estimates;
rows = estimates(estimates.reference_type == "impulse", ["reference_type", ...
    "channel_index", "value_real", "n_references", "qc_status"]);
end

function windows = readAudioWindows(conn, recordingRef, workspace, layout)
%READAUDIOWINDOWS Bounded native-clock reads, including past the end of audio.
covered = vawlume.acoustic.readAudioWindow(conn, recordingRef, 1, ...
    layout.tone_intervals_s(1, 1), layout.tone_intervals_s(1, 2), ...
    SourceRoot=workspace);
quiet = vawlume.acoustic.readAudioWindow(conn, recordingRef, 2, 6, 6.5, ...
    SourceRoot=workspace);
partial = vawlume.acoustic.readAudioWindow(conn, recordingRef, 1, 9.5, 10.5, ...
    SourceRoot=workspace);
outside = vawlume.acoustic.readAudioWindow(conn, recordingRef, 1, 11, 12, ...
    SourceRoot=workspace);
windows = struct( ...
    covered=covered, quiet=quiet, partial=partial, outside=outside, ...
    summary=table(["tone interval, channel 1"; "silence, channel 2"; ...
            "past end of audio"; "entirely past end of audio"], ...
        [string(covered.status); string(quiet.status); string(partial.status); ...
            string(outside.status)], ...
        [covered.sample_count; quiet.sample_count; partial.sample_count; ...
            outside.sample_count], ...
        [windowRms(covered.samples); windowRms(quiet.samples); ...
            windowRms(partial.samples); NaN], ...
        VariableNames=["window", "status", "sample_count", "rms"]));
end

function value = windowRms(samples)
if isempty(samples)
    value = NaN;
    return
end
value = sqrt(mean(double(samples) .^ 2));
end

function measurements = measureEveryChannel(conn, recordingRef, workspace, references)
%MEASUREEVERYCHANNEL One measurement run per reference and channel.
channels = double(unique(fetch(conn, "SELECT channel_index FROM " + ...
    "recording_channels WHERE recording_id=" + ...
    string(recordingRef.recording_id)).channel_index));
measurements = table();
for index = 1:height(references)
    referenceId = references.acoustic_reference_id(index);
    for channel = channels'
        runKey = "response-" + references.reference_type(index) + "-" + ...
            string(referenceId) + "-ch" + string(channel);
        result = vawlume.acoustic.measureReferenceResponse(conn, struct( ...
            acoustic_reference_id=referenceId), channel, ...
            SourceRoot=workspace, Apply=true, RunKey=runKey, ...
            RunLabel="Synthetic reference response", VawlumeVersion="demo");
        rows = table(result.derived_measurement_ids(:), ...
            repmat(referenceId, height(result.metrics), 1), ...
            repmat(references.reference_type(index), height(result.metrics), 1), ...
            repmat(channel, height(result.metrics), 1), ...
            result.metrics.metric_key, result.metrics.value, ...
            repmat(string(result.status), height(result.metrics), 1), ...
            VariableNames=["derived_measurement_id", "acoustic_reference_id", ...
            "reference_type", "channel_index", "metric_key", "value", "run_status"]);
        measurements = [measurements; rows]; %#ok<AGROW>
    end
end
end

