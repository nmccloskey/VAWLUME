function value = uncertaintySummary(windows, identity, clocks, acoustic)
%UNCERTAINTYSUMMARY The four components side by side, deliberately uncombined.
%
% The numbers differ from one another, which is the point: none is derived from
% or substituted for another, and no fifth row combines them.
reid = identity.numeric_evidence.identity_value;
tone = acoustic.estimates(acoustic.estimates.reference_type == "tone" & ...
    acoustic.estimates.channel_index == 1, :);
value = table( ...
    ["pose_localization"; "visual_identity"; "temporal_alignment"; ...
        "acoustic_channel_response"], ...
    ["vawlume.tracking.readWindow samples.pose_confidence"; ...
        "vawlume.tracking.identityCandidates associations.identity_value"; ...
        "vawlume.tracking.readWindow transform.rmse_s"; ...
        "vawlume.acoustic.estimateChannelResponse estimates.relative_range"], ...
    [string(compose("%.2f", windows.pose_confidence_crossing)); ...
        strjoin(compose("%.2f", reid(:))', "/"); ...
        string(compose("%.3f", clocks.with_transform.rmse_s)); ...
        string(compose("%.2e", tone.relative_range))], ...
    ["upstream per-sample keypoint likelihood"; ...
        "cosine similarity of appearance embeddings, uncalibrated"; ...
        "anchor-fit residual RMSE in seconds, estimated not validated"; ...
        "relative spread across repeats of one reference family"], ...
    ["dimensionless tracker output"; "dimensionless similarity"; "seconds"; ...
        "dimensionless ratio"], ...
    VariableNames=["dimension", "queried_from", "value", "semantics", "units"]);
value.Properties.Description = "No row combines these, and no caller " + ...
    "confidence is derived from them.";
end

