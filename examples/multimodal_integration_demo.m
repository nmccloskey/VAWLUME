function demonstration = multimodal_integration_demo(options)
%MULTIMODAL_INTEGRATION_DEMO Demonstrate the Phase 2 multimodal input layer.
%
% DEMONSTRATION = MULTIMODAL_INTEGRATION_DEMO() creates a disposable database, a
% two-channel synthetic recording, a declared arena frame with two microphone
% placements, an external tracking artifact holding three native trajectories,
% time-varying visual-identity evidence across a crossing, four acoustic
% references, per-channel reference-response measurements, and one aggregated
% response/QC profile with exact supporting lineage.
%
% Everything is synthetic and every generated file is removed before return.
%
% What the example is for is the separation it maintains. Four uncertainty
% dimensions appear side by side and none is derived from another:
%
%   pose/localization confidence   from the tracking artifact, per sample
%   visual-identity evidence       per interval, with declared semantics
%   temporal-alignment residual    from a stored clock transform
%   acoustic channel response      per reference family, per channel
%
% No caller is assigned. Nothing here multiplies visual and acoustic evidence
% into a caller score, ranks channels, computes an animal-to-microphone distance,
% or suggests that a nearer animal produced a detected call. Phase 2 preserves
% these components for later attribution work; combining them is not its job.
%
% Name-value options:
%   Print     print compact developer-facing read-backs (default true)
%   RepoRoot  repository root, inferred from this file by default
%
% See also VAWLUME.TRACKING.READWINDOW, VAWLUME.TRACKING.IDENTITYCANDIDATES,
% VAWLUME.ACOUSTIC.ESTIMATECHANNELRESPONSE

arguments
    options.Print (1,1) logical = true
    options.RepoRoot (1,1) string = ""
end

repoRoot = options.RepoRoot;
if strlength(repoRoot) == 0
    repoRoot = string(fileparts(fileparts(mfilename("fullpath"))));
end
sourcePath = fullfile(repoRoot, "src");
removePath = ~contains(path, sourcePath);
if removePath, addpath(sourcePath); end
cleanupPath = onCleanup(@() restorePath(sourcePath, removePath));

workspace = string(tempname);
mkdir(workspace);
cleanupWorkspace = onCleanup(@() removeTree(workspace));
databasePath = fullfile(workspace, "multimodal_integration_demo.sqlite");
conn = sqlite(char(databasePath), "create");
cleanupConnection = onCleanup(@() closeConnection(conn));
vawlume.db.applySchema(conn, fullfile(repoRoot, "schema", "schema.sql"));
vawlume.db.registerBuiltinSemantics(conn, repoRoot);

layout = sessionLayout();
audioFacts = writeSyntheticAudio(workspace, layout);
seedSession(conn, audioFacts);
recordingRef = struct(recording_id=1);
projectRef = struct(project_key="multimodal_demo");

geometry = declareGeometry(conn, projectRef, recordingRef);
tracking = registerTracking(conn, repoRoot, workspace, recordingRef, layout);
windows = readTrackingWindows(conn, repoRoot, workspace, layout);
compatibility = vawlume.tracking.assertGeometryCompatible(conn, streamRef(), ...
    recordingRef);
identity = recordIdentityEvidence(conn, layout);
clocks = demonstrateClockSeparation(conn, repoRoot, workspace, layout);
acoustic = demonstrateAcousticResponse(conn, recordingRef, workspace, layout);

uncertainty = uncertaintySummary(windows, identity, clocks, acoustic);
inventory = struct( ...
    tracking_series=rowCount(conn, "tracking_series"), ...
    tracking_samples_in_sqlite=windows.covered.dense_samples_stored, ...
    identity_associations=rowCount(conn, "tracking_identity_associations"), ...
    acoustic_references=rowCount(conn, "acoustic_references"), ...
    derived_measurements=rowCount(conn, "derived_measurements"), ...
    channel_response_estimates=rowCount(conn, "channel_response_estimates"), ...
    channel_response_estimate_sources=rowCount(conn, ...
        "channel_response_estimate_sources"), ...
    caller_attribution_rows=0);

demonstration = struct( ...
    session_layout=layout, ...
    audio=audioFacts, ...
    geometry=geometry, ...
    tracking=tracking, ...
    tracking_windows=windows, ...
    geometry_compatibility=compatibility, ...
    identity=identity, ...
    clock_separation=clocks, ...
    acoustic=acoustic, ...
    uncertainty=uncertainty, ...
    database_inventory=inventory, ...
    foreign_key_check=fetch(conn, "PRAGMA foreign_key_check"), ...
    proves=[ ...
        "tracking coordinates and microphone placements share one declared frame"; ...
        "dense tracking samples are read from the artifact and never stored"; ...
        "coverage distinguishes covered, partial, and uncovered windows"; ...
        "an animal-like track label acquires no canonical identity by itself"; ...
        "identity is interval-scoped evidence and may be ambiguous or unresolved"; ...
        "a missing identity value stays missing rather than becoming 1.0"; ...
        "pose, identity, clock, and acoustic uncertainty stay separately queryable"; ...
        "reference families are aggregated separately and never blended"; ...
        "a response profile cites every supporting measurement and source run"], ...
    does_not_prove=[ ...
        "which animal produced any detected vocalization"; ...
        "any calibrated distance, gain correction, or normalized call amplitude"; ...
        "real synchronization accuracy between acquisition clocks"; ...
        "real tracker or re-identification performance"; ...
        "calibrated divergence, confidence, or coverage thresholds"], ...
    caller_attribution=struct( ...
        performed=false, ...
        combined_confidence_computed=false, ...
        note="Phase 2 preserves pose, identity, alignment, and acoustic " + ...
            "evidence as separate components. No caller is assigned, no " + ...
            "channel is ranked, and no distance is computed."), ...
    temporary_artifacts_removed=false);

if options.Print, printDemo(demonstration); end

close(conn);
clear cleanupConnection
removeTree(workspace);
clear cleanupWorkspace
demonstration.temporary_artifacts_removed = ...
    ~isfolder(workspace) && ~isfile(databasePath);
clear cleanupPath
end

