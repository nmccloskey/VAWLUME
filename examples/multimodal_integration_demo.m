function writeTrackingArtifact(path, layout)
%WRITETRACKINGARTIFACT Three native trajectories, two of which cross at 5 s.
%
% The track labels are animal-like on purpose. A tracker naming a trajectory
% 'mouse_a' is still only naming a trajectory, and after the crossing the
% trajectory labelled 'mouse_a' carries evidence for the animal 'mouse_b'.
lines = "time_s,track,bodypart,x,y,likelihood";
times = layout.tracking_span_s(1):layout.tracking_interval_s:layout.tracking_span_s(2);
for track = layout.native_track_ids
    for part = ["snout", "tail_base"]
        for t = times
            [x, y] = trackPosition(track, t);
            if part == "tail_base"
                y = y - 3;
            end
            confidence = layout.pose_confidence_nominal;
            if t >= layout.crossing_s(1) && t <= layout.crossing_s(2)
                confidence = layout.pose_confidence_crossing;
            end
            lines(end + 1, 1) = join([compose("%.4f", t), track, part, ...
                compose("%.4f", x), compose("%.4f", y), ...
                compose("%.2f", confidence)], ","); %#ok<AGROW>
        end
    end
end
writelines(lines, path);
end

function [x, y] = trackPosition(track, t)
%TRACKPOSITION Two trajectories meeting near x = 18 cm at t = 5 s, plus one idler.
switch track
    case "mouse_a"
        x = 2 + 3.2 * t;
        y = 15;
    case "mouse_b"
        x = 34 - 3.2 * t;
        y = 15;
    otherwise
        x = 5;
        y = 27;
end
end

