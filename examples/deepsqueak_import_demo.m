function value = prototypeBoundaries()
value = [ ...
    "Supported: the DeepSqueak Excel call-statistics export for the tracked v3.2 output mapping profile."; ...
    "Not supported: arbitrary workbook shapes or every DeepSqueak version."; ...
    "Not supported: native .mat parsing, classifier and clustering workflows."; ...
    "Not supported: MUPET import or any cross-extractor matching or consensus."; ...
    "Accepted state and labels are extractor evidence, not biological truth."];
end

% -------------------------------------------------------- read-back rows ---

function rows = recordingContextRows(conn, recordingId)
rows = fetch(conn, ...
    "SELECT project_key, entity_type, IFNULL(canonical_role,'') AS canonical_role, " + ...
    "entity_native_id, link_type, " + ...
    "CASE WHEN role_label IS NULL OR role_label = '' THEN '-' ELSE role_label END AS role_label " + ...
    "FROM v_recording_entity_context WHERE recording_id = " + ...
    string(recordingId) + " ORDER BY entity_type, entity_native_id, link_type");
end

function rows = extractionRunRows(conn)
rows = fetch(conn, ...
    "SELECT er.run_key, sf.filename AS recording_source, e.extractor_name, " + ...
    "ev.version_label AS extractor_version, " + ...
    "ocp.profile_key AS output_mapping_profile, " + ...
    "ocv.version_label AS profile_version, " + ...
    "substr(ocv.checksum_sha256, 1, 12) AS profile_checksum, " + ...
    "IFNULL(scp.profile_key, '<not recoverable>') AS settings_profile " + ...
    "FROM extraction_runs er " + ...
    "JOIN extraction_run_inputs eri ON eri.extraction_run_id = er.extraction_run_id " + ...
    "JOIN recordings r ON r.recording_id = eri.recording_id " + ...
    "JOIN source_files sf ON sf.source_file_id = r.source_file_id " + ...
    "JOIN extractor_versions ev ON ev.extractor_version_id = er.extractor_version_id " + ...
    "JOIN extractors e ON e.extractor_id = ev.extractor_id " + ...
    "JOIN config_profile_versions ocv ON ocv.profile_version_id = er.output_mapping_profile_version_id " + ...
    "JOIN config_profiles ocp ON ocp.profile_id = ocv.profile_id " + ...
    "LEFT JOIN config_profile_versions scv ON scv.profile_version_id = er.settings_profile_version_id " + ...
    "LEFT JOIN config_profiles scp ON scp.profile_id = scv.profile_id " + ...
    "ORDER BY er.run_key");
end

function rows = artifactRows(conn)
rows = fetch(conn, ...
    "SELECT ra.artifact_role, a.artifact_type, a.path_or_uri, " + ...
    "IFNULL(a.file_format,'') AS file_format, " + ...
    "substr(IFNULL(a.checksum_sha256,''), 1, 12) AS checksum " + ...
    "FROM extraction_run_artifacts ra " + ...
    "JOIN artifacts a ON a.artifact_id = ra.artifact_id " + ...
    "ORDER BY ra.artifact_role");
end

function rows = detectionRows(conn)
rows = fetch(conn, ...
    "SELECT c.native_event_id, c.start_time_s, c.end_time_s, c.duration_s, " + ...
    "c.detection_score, ce.status_after AS review_state, " + ...
    "cc.native_class_label AS native_label " + ...
    "FROM v_detection_core c " + ...
    "JOIN detections d ON d.detection_id = c.detection_id " + ...
    "LEFT JOIN curation_events ce ON ce.detection_id = d.detection_id " + ...
    "LEFT JOIN classification_assignments ca ON ca.detection_id = d.detection_id " + ...
    "LEFT JOIN classification_classes cc " + ...
    "ON cc.classification_class_id = ca.classification_class_id " + ...
    "ORDER BY CAST(c.native_event_id AS INTEGER)");
end

function rows = measurementRows(conn)
% A representative subset rather than every column: one identity transform, two
% unit transforms, and the explicitly missing optional measurement.
% Missing values are rendered as missing. Substituting a numeric zero here would
% display exactly the fabricated value the storage contract exists to prevent.
rows = fetch(conn, ...
    "SELECT d.native_event_id, xf.native_name, em.native_value_type, " + ...
    "CASE WHEN em.native_value_real IS NULL THEN '<missing>' " + ...
    "ELSE CAST(em.native_value_real AS TEXT) END AS native_value, " + ...
    "IFNULL(em.native_unit,'') AS native_unit, " + ...
    "IFNULL(cf.canonical_name,'') AS canonical_feature, " + ...
    "CASE WHEN em.canonical_value_real IS NULL THEN '<missing>' " + ...
    "ELSE CAST(em.canonical_value_real AS TEXT) END AS canonical_value, " + ...
    "IFNULL(em.canonical_unit,'') AS canonical_unit, " + ...
    "IFNULL(em.transform_key,'') AS transform_key, " + ...
    "IFNULL(xf.derivation_stage,'') AS derivation_stage " + ...
    "FROM event_measurements em " + ...
    "JOIN detections d ON d.detection_id = em.detection_id " + ...
    "JOIN extractor_features xf ON xf.extractor_feature_id = em.extractor_feature_id " + ...
    "LEFT JOIN canonical_features cf ON cf.canonical_feature_id = em.canonical_feature_id " + ...
    "WHERE xf.native_name IN ('Begin Time (s)', 'Principle Frequency (kHz)', " + ...
    "'Slope (kHz/s)', 'Tonality') " + ...
    "AND d.native_event_id IN ('1', '2') " + ...
    "ORDER BY CAST(d.native_event_id AS INTEGER), xf.native_name");
end

function rows = reviewLabelRows(conn)
rows = fetch(conn, ...
    "SELECT d.native_event_id, ce.action_type, ce.status_after, ce.actor_type, " + ...
    "cr.method AS classification_method, cc.native_class_label, " + ...
    "IFNULL(cc.canonical_class_label, '<no canonical interpretation>') AS canonical_class " + ...
    "FROM detections d " + ...
    "JOIN curation_events ce ON ce.detection_id = d.detection_id " + ...
    "LEFT JOIN classification_assignments ca ON ca.detection_id = d.detection_id " + ...
    "LEFT JOIN classification_runs cr ON cr.classification_run_id = ca.classification_run_id " + ...
    "LEFT JOIN classification_classes cc " + ...
    "ON cc.classification_class_id = ca.classification_class_id " + ...
    "ORDER BY CAST(d.native_event_id AS INTEGER)");
end

function value = scientificInventory(conn)
tables = ["extraction_runs", "extraction_run_inputs", "extraction_run_artifacts", ...
    "artifacts", "detections", "event_measurements", "curation_events", ...
    "classification_runs", "classification_classes", "classification_assignments"];
value = struct();
for name = tables
    value.(name) = scalar(conn, "SELECT COUNT(*) AS n FROM " + name);
end
end

