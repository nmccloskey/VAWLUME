end

function printDemonstration(value)
disp("VAWLUME DEEPSQUEAK IMPORT DEMONSTRATION")
disp(strjoin(value.architecture, " -> "))
fprintf("\nProject intake: %s (project %d, recording %d), preview %s\n", ...
    value.project_intake.status, value.project_intake.project_id, ...
    value.project_intake.recording_id, value.project_intake.preview_verdict);
disp("Recording context:")
disp(value.recording_context)
fprintf("Import: IR valid %d over %d source rows; plan %s with %d conflict(s); " + ...
    "apply %s; settings %s; model %s\n", ...
    value.import_summary.ir_valid, value.import_summary.ir_source_rows, ...
    value.import_summary.plan_status, value.import_summary.plan_conflicts, ...
    value.import_summary.apply_status, value.import_summary.settings_status, ...
    value.import_summary.model_status);
disp("Extraction-run provenance:")
disp(value.extraction_run_provenance)
disp("Artifact provenance:")
disp(value.artifact_provenance)
disp("Detections:")
disp(value.detections)
disp("Selected measurements (native evidence beside canonical form):")
disp(value.measurements)
disp("Review and label evidence:")
disp(value.review_and_labels)
fprintf("Rerun: %d created, %d reused detections; scientific rows unchanged: %d\n", ...
    value.rerun.detections_created, value.rerun.detections_reused, ...
    value.rerun.scientific_rows_unchanged);
fprintf("Relocation: run %s, artifact %s, stored portable path %s; unchanged: %d\n", ...
    value.relocation.extraction_run_action, value.relocation.artifact_action, ...
    value.relocation.stored_portable_path, ...
    value.relocation.scientific_rows_unchanged);
fprintf("Foreign-key violations: %d; temporary artifacts removed: %d\n", ...
    height(value.foreign_key_violations), value.temporary_artifacts_removed);
disp("Scope:")
disp(value.boundaries)
end

function makeParentFolder(path)
parent = fileparts(path);
if ~isfolder(parent)
    mkdir(parent);
end
end

function writeText(path, text)
makeParentFolder(path);
fileId = fopen(path, "w");
if fileId < 0
    error("vawlume:examples:FileWriteFailed", ...
        "Could not open %s for writing.", path);
end
cleaner = onCleanup(@() fclose(fileId));
fprintf(fileId, "%s", text);
delete(cleaner);
end

function root = normalizedRepoRoot(root)
if strlength(root) > 0
    root = string(root);
    return
end
root = string(fileparts(fileparts(mfilename("fullpath"))));
end

function value = pathContains(target)
value = any(strcmp(strsplit(string(path), pathsep), target));
end

function restoreSourcePath(sourcePath, shouldRemove)
if shouldRemove && pathContains(sourcePath)
    rmpath(sourcePath);
end
end

function closeConnection(conn)
try
    close(conn);
catch
end
end

function removeTree(root)
%REMOVETREE Best-effort workspace removal.
%
% This also runs while an exception is unwinding, when the SQLite file may still
% be held briefly. Failing loudly here would bury the real error, so removal is
% retried and then reported through the returned struct rather than thrown.
for attempt = 1:5
    if ~isfolder(root)
        return
    end
    try
        rmdir(root, "s");
        return
    catch
        pause(0.2);
    end
end
end
