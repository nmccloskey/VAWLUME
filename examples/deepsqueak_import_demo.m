function demonstration = deepsqueak_import_demo(options)
%DEEPSQUEAK_IMPORT_DEMO Demonstrate the DeepSqueak import path end to end.
%
% DEMONSTRATION = DEEPSQUEAK_IMPORT_DEMO() establishes one project recording
% through the real project-intake path, generates a small DeepSqueak-style call
% statistics workbook, imports it with the public DeepSqueak importer, and
% returns relational read-back tables covering run provenance, artifacts,
% detections, native and canonical measurements, and review and label evidence.
% It then reruns the identical import and relocates the workbook to show that
% neither creates a second scientific population.
%
% Every input is generated under the system temporary directory and removed
% before this function returns. No private data is involved and no database edit
% is made by hand.
%
% The flow is:
%
%   synthetic source tree
%       -> project-input JSON profile
%       -> source_mapping.parse + preview
%       -> vawlume.ingest.project(..., Apply=true)
%       -> synthetic DeepSqueak call-statistics .xlsx
%       -> vawlume.ingest.deepsqueak (plan)
%       -> vawlume.ingest.deepsqueak (Apply=true)
%       -> relational read-back
%       -> unchanged rerun and artifact relocation
%
% Name-value options:
%   Print     print a concise developer-facing summary (default true)
%   RepoRoot  repository root; inferred from this file's location by default
%
% What this demonstrates is bounded. It covers the DeepSqueak Excel
% call-statistics export for the tracked v3.2 output mapping profile, and
% nothing else: not every DeepSqueak version, not arbitrary workbook shapes, not
% native .mat parsing, not DeepSqueak classifier or clustering workflows, not
% MUPET, and not cross-extractor matching. The imported review state and labels
% are extractor evidence, not biological truth.
%
% From the repository root:
%
%   addpath("examples")
%   deepsqueak_import_demo
%
% See also VAWLUME.INGEST.DEEPSQUEAK, PROJECT_INTAKE_DEMO.

arguments
    options.Print (1,1) logical = true
    options.RepoRoot (1,1) string = ""
end

repoRoot = normalizedRepoRoot(options.RepoRoot);
sourcePath = fullfile(repoRoot, "src");
removeSourcePath = ~pathContains(sourcePath);
if removeSourcePath
    addpath(sourcePath);
end
cleanupPath = onCleanup(@() restoreSourcePath(sourcePath, removeSourcePath));

workspaceRoot = fullfile(tempdir, ...
    "VAWLUME deepsqueak import demo " + string(java.util.UUID.randomUUID));
mkdir(workspaceRoot);
cleanupWorkspace = onCleanup(@() removeTree(workspaceRoot));
databasePath = fullfile(workspaceRoot, "deepsqueak_import_demo.sqlite");
conn = sqlite(char(databasePath), "create");
cleanupConnection = onCleanup(@() closeConnection(conn));

vawlume.db.applySchema(conn, fullfile(repoRoot, "schema", "schema.sql"));
vawlume.db.registerBuiltinSemantics(conn, repoRoot);

% --- Phase 3: establish one project recording through the public path --------
projectProfilePath = fullfile(repoRoot, "config", "01_mapping_profiles", ...
    "project_inputs", "project_input_source_mapping_examples.json");
sourceRoot = fullfile(workspaceRoot, "project");
audioPath = fullfile(sourceRoot, "control", "mouse_001", "baseline", ...
    "001_baseline_1.wav");
makeParentFolder(audioPath);
writeText(audioPath, "synthetic audio stand-in; no recorded sound is involved");

projectIR = vawlume.source_mapping.parse(projectProfilePath, sourceRoot, ...
    ProfileId="example.project.mouse_courtship.folder_driven", RepoRoot=repoRoot);
projectPreview = vawlume.source_mapping.preview(projectIR);
intake = vawlume.ingest.project(conn, projectIR, struct( ...
    project_key="demo_deepsqueak_import", ...
    project_name="DeepSqueak import demonstration", ...
    description="Disposable Phase 4 demonstration project."), Apply=true, ...
    ProfileLinkagePath=fullfile(repoRoot, "config", "04_examples", ...
    "profile_linkage_example.json"), RepoRoot=repoRoot);

recording = fetch(conn, ...
    "SELECT r.recording_id, IFNULL(r.native_recording_id,'') AS native_recording_id, " + ...
    "IFNULL(sf.relative_path,'') AS source_relative_path " + ...
    "FROM recordings r JOIN source_files sf ON sf.source_file_id = r.source_file_id");
recordingId = double(recording.recording_id(1));

% --- Phase 4: generate a small, deterministic call-statistics workbook -------
artifactRoot = fullfile(workspaceRoot, "deepsqueak");
exportPath = fullfile(artifactRoot, "exports", "MOUSE001_BASELINE_Stats.xlsx");
makeParentFolder(exportPath);
writecell(demonstrationExport(), exportPath);

settingsPath = fullfile(artifactRoot, "deepsqueak_detection_settings.json");
writeText(settingsPath, jsonencode(struct( ...
    profile=struct(id="demo.deepsqueak.settings.v1", ...
    name="Demonstration DeepSqueak detection settings", ...
    kind="extractor_settings", profile_version="1.0.0"), ...
    detection=struct(score_threshold=0.15, frequency_range_khz=[15, 115]))));

runSpec = struct( ...
    run_key="demo_deepsqueak_run_1", ...
    extractor_version="3.2.1", ...
    run_label="Demonstration DeepSqueak detection run", ...
    settings=struct(profile_path=settingsPath));

% Settings provenance is supplied because it is genuinely available here. No
% detector model is declared, because none is known: the demonstration shows
% that absence explicitly rather than inventing a model identity.
recordingRef = struct(recording_id=recordingId);
plan = vawlume.ingest.deepsqueak(conn, exportPath, recordingRef, runSpec, ...
    RepoRoot=repoRoot, ArtifactRoot=artifactRoot);
imported = vawlume.ingest.deepsqueak(conn, exportPath, recordingRef, runSpec, ...
    RepoRoot=repoRoot, ArtifactRoot=artifactRoot, Apply=true);

% --- Rerun and relocation ---------------------------------------------------
beforeRerun = scientificInventory(conn);
rerun = vawlume.ingest.deepsqueak(conn, exportPath, recordingRef, runSpec, ...
    RepoRoot=repoRoot, ArtifactRoot=artifactRoot, Apply=true);
rerunSummary = struct( ...
    committed=rerun.committed, ...
    extraction_run_action=rerun.extraction_run.action, ...
    extraction_run_id_stable=rerun.extraction_run.extraction_run_id == ...
        imported.extraction_run.extraction_run_id, ...
    detections_created=rerun.applied_counts.detections, ...
    detections_reused=rerun.detections.detections_reuse, ...
    measurements_created=rerun.applied_counts.event_measurements, ...
    measurements_reused=rerun.detections.measurements_reuse, ...
    scientific_rows_unchanged=isequal(scientificInventory(conn), beforeRerun));

relocatedRoot = fullfile(workspaceRoot, "relocated");
relocatedPath = fullfile(relocatedRoot, "exports", "MOUSE001_BASELINE_Stats.xlsx");
makeParentFolder(relocatedPath);
copyfile(exportPath, relocatedPath);
relocated = vawlume.ingest.deepsqueak(conn, relocatedPath, recordingRef, ...
    runSpec, RepoRoot=repoRoot, ArtifactRoot=relocatedRoot, Apply=true);
storedArtifactPath = scalarText(conn, ...
    "SELECT path_or_uri FROM artifacts WHERE artifact_type = 'extractor_event_export'");
relocationSummary = struct( ...
    committed=relocated.committed, ...
    extraction_run_action=relocated.extraction_run.action, ...
    artifact_action=string(relocated.artifacts.action(1)), ...
    runtime_path_changed=relocated.export.runtime_path ~= imported.export.runtime_path, ...
    stored_portable_path=storedArtifactPath, ...
    scientific_rows_unchanged=isequal(scientificInventory(conn), beforeRerun));

inventory = scientificInventory(conn);
foreignKeyViolations = fetch(conn, "PRAGMA foreign_key_check");

demonstration = struct( ...
    architecture=[ ...
        "synthetic project source tree"; ...
        "project intake with tracked device/setup linkage"; ...
        "synthetic DeepSqueak call-statistics workbook"; ...
        "adapter read + source_mapping IR"; ...
        "extraction run/artifact provenance"; ...
        "detections, measurements, review, labels"; ...
        "idempotent relational read-back"], ...
    boundaries=prototypeBoundaries(), ...
    project_intake=struct( ...
        status=intake.status, committed=intake.committed, ...
        project_id=intake.project_id, ...
        preview_verdict=projectPreview.verdict, ...
        recording_id=recordingId, ...
        native_recording_id=string(recording.native_recording_id(1)), ...
        source_relative_path=string(recording.source_relative_path(1))), ...
    recording_context=recordingContextRows(conn, recordingId), ...
    import_summary=struct( ...
        ir_valid=imported.plan.export.ir.valid_for_ingest, ...
        ir_source_rows=imported.export.row_count, ...
        ir_value_count=height(imported.plan.export.ir.values), ...
        plan_status=plan.status, ...
        plan_conflicts=numel(plan.conflicts), ...
        planned_detections=plan.detections.planned, ...
        planned_measurements=plan.detections.measurements_create, ...
        apply_status=imported.status, ...
        committed=imported.committed, ...
        settings_status=imported.settings.status, ...
        model_status=imported.model.status), ...
    diagnostics=imported.diagnostics, ...
    extraction_run_provenance=extractionRunRows(conn), ...
    artifact_provenance=artifactRows(conn), ...
    detections=detectionRows(conn), ...
    measurements=measurementRows(conn), ...
    review_and_labels=reviewLabelRows(conn), ...
    rerun=rerunSummary, ...
    relocation=relocationSummary, ...
    database_inventory=inventory, ...
    foreign_key_violations=foreignKeyViolations, ...
    workspace_root=workspaceRoot, database_path=databasePath, ...
    temporary_artifacts_removed=false);

close(conn);
clear cleanupConnection
removeTree(workspaceRoot);
clear cleanupWorkspace
demonstration.temporary_artifacts_removed = ...
    ~isfolder(workspaceRoot) && ~isfile(databasePath);

if options.Print
    printDemonstration(demonstration);
end
clear cleanupPath
end

