function value = upstreamFingerprint(conn)
value = fetch(conn, "SELECT d.detection_id,d.extraction_run_id,d.native_event_id," + ...
    "d.start_time_s,d.end_time_s,COUNT(em.event_measurement_id) AS measurements," + ...
    "IFNULL(SUM(em.canonical_value_real),0) AS canonical_total " + ...
    "FROM detections d LEFT JOIN event_measurements em ON em.detection_id=d.detection_id " + ...
    "GROUP BY d.detection_id ORDER BY d.detection_id");
end

function value = countOf(conn, tableName)
rows = fetch(conn, "SELECT COUNT(*) AS n FROM " + tableName);
value = double(rows.n(1));
end

function value = nativeId(conn, detectionId)
rows = fetch(conn, "SELECT native_event_id FROM detections WHERE detection_id=" + ...
    string(detectionId));
value = string(rows.native_event_id(1));
end

function value = joinNativeIds(conn, detectionIds)
value = "";
if isempty(detectionIds), return, end
items = strings(numel(detectionIds), 1);
for index = 1:numel(detectionIds), items(index) = nativeId(conn, detectionIds(index)); end
value = strjoin(items, ", ");
end

function writeCells(path, cells)
makeParent(path);
if isfile(path), delete(path); end
writecell(cells, path);
end

function writeText(path, value)
makeParent(path);
fileId = fopen(path, "w");
if fileId < 0
    error("vawlume:examples:FixtureCreationFailed", ...
        "Could not create demonstration input: %s", path);
end
cleanupFile = onCleanup(@() fclose(fileId));
fprintf(fileId, "%s", value);
clear cleanupFile
end

function makeParent(path)
parent = fileparts(path);
if ~isfolder(parent), mkdir(parent); end
end

function root = normalizedRepoRoot(root)
if strlength(root) == 0, root = fileparts(fileparts(mfilename("fullpath"))); end
try
    root = string(java.io.File(char(root)).getCanonicalPath());
catch
end
end

function value = pathContains(target)
value = any(split(string(path), pathsep) == string(target));
end

function restoreSourcePath(sourcePath, shouldRemove)
